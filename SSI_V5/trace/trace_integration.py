def create_integration_manager(
    world_engine: Any = None,
    strategy_lab: Any = None,
    agent_runtime: Any = None,
    collective_manager: Any = None,
    model_evaluator: Any = None,
    strategy_memory_manager: Any = None
) -> TraceIntegrationManager:
    """
    Fabryka: Utworz i skonfiguruj TraceIntegrationManager.
    
    Args:
        world_engine: Instancja WorldEngine
        strategy_lab: Instancja StrategyLab
        agent_runtime: Instancja AgentRuntime
        collective_manager: Instancja CollectiveManager
        model_evaluator: Instancja ModelEvaluator
        strategy_memory_manager: Instancja StrategyMemoryManager
        
    Returns:
        Skonfigurowany TraceIntegrationManager
    """
    integration_manager = TraceIntegrationManager()
    
    # Pod 자체가 komponenty
    integration_manager.connect_all(
        world_engine=world_engine,
        strategy_lab=strategy_lab,
        agent_runtime=agent_runtime,
        collective_manager=collective_manager,
        model_evaluator=model_evaluator
    )
    
    # Integracja z Strategy Memory
    if strategy_memory_manager:
        integration_manager.integrate_with_strategy_memory(strategy_memory_manager)
    
    return integration_manager


def quick_setup(
    world_engine: Any = None,
    strategy_lab: Any = None,
    pipeline: Any = None
) -> TraceIntegrationManager:
    """
    Szybka konfiguracja z minimalnymi parametrami.
    
    Args:
        world_engine: Instancja WorldEngine (opcjonalnie)
        strategy_lab: Instancja StrategyLab (opcjonalnie)
        pipeline: Instancja Pipeline (opcjonalnie - pobiera z niej komponenty)
        
    Returns:
        Skonfigurowany TraceIntegrationManager
    """
    integration_manager = TraceIntegrationManager()
    
    if pipeline:
        integration_manager.connect_from_pipeline(pipeline)
    else:
        integration_manager.connect_all(
            world_engine=world_engine,
            strategy_lab=strategy_lab
        )
    
    # Wlacz hooki
    integration_manager.enable_all_hooks()
    
    return integration_manager


