class InputDataReference:
    """
    Referencja do danych wejsciowych z hashowaniem dla reprodukowalnosci.
    """
    # Hash danych wejsciowych (kluczowy для reprodukowalnosci)
    data_hash: str = ""
    
    # Typ hashowania
    hash_algorithm: str = "sha256"
    
    # Source reference
    source: str = "unknown"
    
    # Dodatkowe informacje
    data_shape: Optional[Dict[str, int]] = None
    feature_count: int = 0
    sample_count: int = 0
    
    @classmethod
    def from_data(cls, data: Any, source: str = "unknown") -> 'InputDataReference':
        """Utworz referencje z danych"""
        data_str = json.dumps(data, sort_keys=True, default=str) if isinstance(data, (dict, list)) else str(data)
        data_hash = hashlib.sha256(data_str.encode('utf-8')).hexdigest()
        
        # Określ shape
        data_shape = None
        feature_count = 0
        sample_count = 0
        
        if isinstance(data, dict):
            feature_count = len(data)
            # Sprawdź czy to feature values
            for key, value in data.items():
                if isinstance(value, (list, tuple)):
                    sample_count = max(sample_count, len(value))
        elif isinstance(data, list):
            sample_count = len(data)
            if data and isinstance(data[0], dict):
                feature_count = len(data[0])
        
        if sample_count > 0 and feature_count > 0:
            data_shape = {"n_samples": sample_count, "n_features": feature_count}
        
        return cls(
            data_hash=data_hash,
            hash_algorithm="sha256",
            source=source,
            data_shape=data_shape,
            feature_count=feature_count,
            sample_count=sample_count
        )
    
    def verify_data(self, data: Any) -> bool:
        """Zweryfikuj czy dane pasuja do hashu"""
        if not self.data_hash:
            return False
        
        data_str = json.dumps(data, sort_keys=True, default=str) if isinstance(data, (dict, list)) else str(data)
        computed_hash = hashlib.sha256(data_str.encode('utf-8')).hexdigest()
        
        return computed_hash == self.data_hash


