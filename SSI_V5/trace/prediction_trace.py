class PredictionTraceManager:
    """
    Menadzer sladow predykcji.
    
    Odpowiedzialny za:
    - Tworzenie i zarzadzanie PredictionTraceRecord
    - Zapis trace z roznych zrodel
    - Pobieranie trace wedlug roznych kryteriów
    - Reprodukcja predykcji
    - Integracja z Strategy Memory
    - Zapis/odczyt JSON
    
    ZASADA: Tylko zapisuje slady. Nie wplywa na system.
    """
    
    def __init__(self, trace_dir: str = None):
        """
        Inicjalizacja PredictionTraceManager.
        
        Args:
            trace_dir: Katalog do zapisywania trace (domyslnie z config)
        """
        if trace_dir is None:
            from ..core.config import PathConfig
            trace_dir = os.path.join(PathConfig.MEMORY_DIR, "prediction_trace")
        
        self.trace_dir = Path(trace_dir)
        os.makedirs(self.trace_dir, exist_ok=True)
        
        # Rejestr trace w pamięci
        self._trace_register: Dict[str, PredictionTraceRecord] = {}
        
        # Indeksy dla szybkiego wyszukiwania
        self._index_by_model: Dict[str, List[str]] = {}
        self._index_by_world: Dict[str, List[str]] = {}
        self._index_by_prediction: Dict[str, str] = {}
        self._index_by_strategy: Dict[str, List[str]] = {}
        
        # Blokada thread-safety
        self._lock = RLock()
        
        # Wczytanie istniejacych trace
        self._load_existing_traces()
    
    def _load_existing_traces(self) -> None:
        """Wczytanie istniejacych trace z dysku"""
        if not self.trace_dir.exists():
            return
        
        for trace_file in self.trace_dir.glob("*.json"):
            try:
                with open(trace_file, 'r', encoding='utf-8') as f:
                    data = json.load(f)
                
                record = PredictionTraceRecord.from_dict(data)
                self._register_trace(record)
                
            except Exception as e:
                print(f"[TRACE] Warning: Error loading {trace_file}: {e}")
    
    def _register_trace(self, record: PredictionTraceRecord) -> None:
        """Rejestracja trace w indeksach"""
        with self._lock:
            # Rejestr główny
            self._trace_register[record.trace_id] = record
            
            # Indeks po prediction_id
            self._index_by_prediction[record.prediction_id] = record.trace_id
            
            # Indeks po modelu
            model_key = record.model.get_identifier()
            if model_key not in self._index_by_model:
                self._index_by_model[model_key] = []
            if record.trace_id not in self._index_by_model[model_key]:
                self._index_by_model[model_key].append(record.trace_id)
            
            # Indeks po world_version
            if record.context.world_version:
                if record.context.world_version not in self._index_by_world:
                    self._index_by_world[record.context.world_version] = []
                if record.trace_id not in self._index_by_world[record.context.world_version]:
                    self._index_by_world[record.context.world_version].append(record.trace_id)
            
            # Indeks po strategy_experiment_id
            if record.strategy_experiment_id:
                if record.strategy_experiment_id not in self._index_by_strategy:
                    self._index_by_strategy[record.strategy_experiment_id] = []
                if record.trace_id not in self._index_by_strategy[record.strategy_experiment_id]:
                    self._index_by_strategy[record.strategy_experiment_id].append(record.trace_id)
    
    def _get_trace_file_path(self, trace_id: str) -> Path:
        """Pobierz sciezke pliku trace"""
        return self.trace_dir / f"{trace_id}.json"
    
    def _save_trace_record(self, record: PredictionTraceRecord) -> bool:
        """Zapisz pojedynczy trace na dysk"""
        try:
            file_path = self._get_trace_file_path(record.trace_id)
            with open(file_path, 'w', encoding='utf-8') as f:
                json.dump(record.to_dict(), f, indent=4, ensure_ascii=False)
            return True
        except Exception as e:
            print(f"[TRACE] Error saving trace {record.trace_id}: {e}")
            return False
    
    def create_trace(
        self,
        world_version: str = "",
        world_name: str = "",
        dataset_version: str = "",
        cycle_id: str = "",
        model_reference: str = "",
        model_version: str = "1.0.0",
        model_parameters: Dict[str, Any] = None,
        input_features: List[str] = None,
        feature_values: Dict[str, Any] = None,
        input_data: Any = None,
        prediction_result: Any = None,
        prediction_confidence: float = 0.0,
        prediction_type: Union[str, PredictionType] = PredictionType.UNKNOWN,
        metadata: Dict[str, Any] = None
    ) -> PredictionTraceRecord:
        """
        Utworz nowy slad predykcji.
        
        Args:
            world_version: Wersja swiata
            world_name: Nazwa swiata
            dataset_version: Wersja datasetu
            cycle_id: ID cyklu WorldEngine
            model_reference: Referencja do modelu
            model_version: Wersja modelu
            model_parameters: Parametry modelu
            input_features: Lista cech
            feature_values: Wartosci cech
            input_data: Dane wejsciowe (dla hash)
            prediction_result: Wynik predykcji
            prediction_confidence: Pewnosc predykcji
            prediction_type: Typ predykcji
            metadata: Metadane
            
        Returns:
            PredictionTraceRecord: Nowy rekord trace
        """
        with self._lock:
            # Utworz rekord
            record = PredictionTraceRecord(
                context=TraceContext(
                    world_version=world_version,
                    world_name=world_name,
                    dataset_version=dataset_version,
                    cycle_id=cycle_id,
                    created_timestamp=datetime.now()
                ),
                model=ModelReference(
                    reference=model_reference,
                    version=model_version,
                    parameters=model_parameters or {}
                ),
                input_features=input_features or [],
                feature_values=feature_values or {},
                prediction=PredictionResult(
                    result=prediction_result,
                    confidence=prediction_confidence,
                    prediction_type=prediction_type if isinstance(prediction_type, PredictionType) else PredictionType(prediction_type)
                ),
                metadata=metadata or {}
            )
            
            # Generuj hash input data
            if input_data is not None:
                record.input_data_ref = InputDataReference.from_data(input_data, "prediction_input")
            
            # Ustaw status
            if prediction_result is not None:
                record.update_status(TraceStatus.PREDICTION_MADE)
            
            # Zarejestruj
            self._register_trace(record)
            
            # Zapisz na dysk
            self._save_trace_record(record)
            
            return record
    
    def receive_from_world_engine(
        self,
        world_engine_output: Any,
        cycle_id: str = None,
        world_version: str = None
    ) -> Optional[PredictionTraceRecord]:
        """
        Odbierz dane z WorldEngine i utworz trace.
        
        Args:
            world_engine_output: Instancja WorldEngineOutput
            cycle_id: ID cyklu (opcjonalnie)
            world_version: Wersja swiata (opcjonalnie)
            
        Returns:
            PredictionTraceRecord lub None
        """
        if world_engine_output is None:
            return None
        
        # Pobierz dane z output
        features = getattr(world_engine_output, 'features', {})
        predictions = getattr(world_engine_output, 'predictions', {})
        models = getattr(world_engine_output, 'models', {})
        results = getattr(world_engine_output, 'results', {})
        metadata = getattr(world_engine_output, 'metadata', {})
        
        # Utworz trace
        trace = self.create_trace(
            world_version=world_version or metadata.get('world_version', ''),
            world_name=metadata.get('world_name', 'unknown'),
            dataset_version=metadata.get('dataset_version', ''),
            cycle_id=cycle_id or metadata.get('cycle_id', ''),
            model_reference=metadata.get('model_reference', ''),
            input_features=list(features.keys()) if isinstance(features, dict) else [],
            feature_values=features if isinstance(features, dict) else {},
            input_data=features,
            prediction_result=predictions,
            metadata={'source': 'world_engine', **metadata}
        )
        
        # Powiaz z cyklem WorldEngine
        trace.world_engine_cycle_id = cycle_id or metadata.get('cycle_id')
        
        # Zaktualizuj status
        if predictions:
            trace.update_status(TraceStatus.PREDICTION_MADE)
        
        # Zapisz zmiany
        self._save_trace_record(trace)
        
        return trace
    
    def update_trace_prediction(
        self,
        trace_id: str,
        prediction_result: Any,
        confidence: float = 0.0,
        prediction_type: Union[str, PredictionType] = None,
        model_reference: str = None,
        model_version: str = None,
        model_parameters: Dict[str, Any] = None
    ) -> bool:
        """
        Zaktualizuj predykcje w trace.
        
        Args:
            trace_id: ID trace do zaktualizowania
            prediction_result: Wynik predykcji
            confidence: Pewnosc
            prediction_type: Typ predykcji
            model_reference: Referencja do modelu
            model_version: Wersja modelu
            model_parameters: Parametry modelu
            
        Returns:
            bool: Czy aktualizacja sie powiodla
        """
        record = self.get_trace(trace_id)
        if record is None:
            return False
        
        with self._lock:
            # Zaktualizuj model
            if model_reference:
                record.model.reference = model_reference
            if model_version:
                record.model.version = model_version
            if model_parameters:
                record.model.parameters.update(model_parameters)
            
            # Zaktualizuj predykcje
            record.prediction.result = prediction_result
            record.prediction.confidence = confidence
            if prediction_type:
                record.prediction.prediction_type = prediction_type if isinstance(prediction_type, PredictionType) else PredictionType(prediction_type)
            
            # Zaktualizuj status
            record.update_status(TraceStatus.PREDICTION_MADE)
            
            # Zapisz
            self._save_trace_record(record)
            
            return True
    
