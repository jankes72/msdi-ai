    def search_traces(
        self,
        world_version: str = None,
        model_reference: str = None,
        model_version: str = None,
        has_decision: bool = None,
        has_collective: bool = None,
        min_completeness: float = None,
        status: TraceStatus = None,
        limit: int = None
    ) -> List[PredictionTraceRecord]:
        """
        Zaawansowane wyszukiwanie trace.
        
        Args:
            world_version: Filtr po wersji świata
            model_reference: Filtr po referencji modelu
            model_version: Filtr po wersji modelu
            has_decision: Czy ma decyzję
            has_collective: Czy ma konsensus
            min_completeness: Minimalna kompletność
            status: Filtr po statusie
            limit: Maksymalna liczba wyników
            
        Returns:
            Lista pasujących trace
        """
        results = self.get_all_traces()
        
        # Filtrowanie
        if world_version:
            results = [r for r in results if r.context.world_version == world_version]
        
        if model_reference:
            if model_version:
                # Szukaj dokładnego dopasowania model@version
                model_key = f"{model_reference}@{model_version}"
                results = [r for r in results if r.model.get_identifier() == model_key]
            else:
                # Szukaj wszystkich modeli z tą nazwą (dowolna wersja)
                results = [r for r in results if r.model.get_identifier().startswith(f"{model_reference}@") or r.model.reference == model_reference]
        
        if has_decision is not None:
            results = [r for r in results if (r.decision is not None) == has_decision]
        
        if has_collective is not None:
            results = [r for r in results if (r.collective is not None) == has_collective]
        
        if min_completeness is not None:
            results = [r for r in results if r.completeness_score >= min_completeness]
        
        if status:
            results = [r for r in results if r.status == status]
        
        # Limit
        if limit:
            results = results[:limit]
        
        return results
    
