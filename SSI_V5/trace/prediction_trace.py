    def get_statistics(self) -> Dict[str, Any]:
        """Pobierz statystyki trace"""
        total_traces = len(self._trace_register)
        
        # Statystyki po statusie
        status_counts = {}
        for status in TraceStatus:
            count = len(self.get_traces_by_status(status))
            if count > 0:
                status_counts[status.value] = count
        
        # Statystyki po modelu
        model_counts = {}
        for model_key, trace_ids in self._index_by_model.items():
            model_counts[model_key] = len(trace_ids)
        
        # Statystyki po wersji świata
        world_counts = {}
        for world_version, trace_ids in self._index_by_world.items():
            world_counts[world_version] = len(trace_ids)
        
        # Średnia kompletność
        all_traces = self.get_all_traces()
        avg_completeness = sum(t.completeness_score for t in all_traces) / max(len(all_traces), 1)
        
        return {
            'total_traces': total_traces,
            'status_counts': status_counts,
            'model_counts': model_counts,
            'world_counts': world_counts,
            'average_completeness': avg_completeness,
            'completeness_distribution': {
                'complete': len(self.get_traces_by_completeness(1.0)),
                'high': len(self.get_traces_by_completeness(0.8)),
                'medium': len(self.get_traces_by_completeness(0.5)),
                'low': len(all_traces) - len(self.get_traces_by_completeness(0.5))
            }
        }
    
    def clear_trace(self, trace_id: str) -> bool:
        """Usun trace"""
        with self._lock:
            if trace_id not in self._trace_register:
                return False
            
            # Usun z rejestru
            del self._trace_register[trace_id]
            
            # Usun z indeksów
            record = self._trace_register.get(trace_id)
            if record:
                if record.prediction_id in self._index_by_prediction:
                    del self._index_by_prediction[record.prediction_id]
                
                model_key = record.model.get_identifier()
                if model_key in self._index_by_model:
                    self._index_by_model[model_key].remove(trace_id)
                
                if record.context.world_version in self._index_by_world:
                    self._index_by_world[record.context.world_version].remove(trace_id)
                
                if record.strategy_experiment_id in self._index_by_strategy:
                    self._index_by_strategy[record.strategy_experiment_id].remove(trace_id)
            
            # Usun plik
            file_path = self._get_trace_file_path(trace_id)
            if file_path.exists():
                file_path.unlink()
            
            return True
    
    def clear_all_traces(self) -> bool:
        """Usun wszystkie trace"""
        with self._lock:
            self._trace_register.clear()
            self._index_by_model.clear()
            self._index_by_world.clear()
            self._index_by_prediction.clear()
            self._index_by_strategy.clear()
            
            # Usun pliki
            for trace_file in self.trace_dir.glob("*.json"):
                trace_file.unlink()
            
            return True
    
    def save_all_to_json(self, file_path: str = None) -> bool:
        """Zapisz wszystkie trace do jednego pliku JSON"""
        if file_path is None:
            file_path = str(self.trace_dir / "all_traces.json")
        
        try:
            data = {
                'timestamp': datetime.now().isoformat(),
                'total_traces': len(self._trace_register),
                'traces': [record.to_dict() for record in self._trace_register.values()]
            }
            
            with open(file_path, 'w', encoding='utf-8') as f:
                json.dump(data, f, indent=4, ensure_ascii=False)
            
            return True
        except Exception as e:
            print(f"[TRACE] Error saving all traces to {file_path}: {e}")
            return False
    
    def load_all_from_json(self, file_path: str = None) -> bool:
        """Wczytanie wszystkich trace z pliku JSON"""
        if file_path is None:
            file_path = str(self.trace_dir / "all_traces.json")
        
        if not os.path.exists(file_path):
            return False
        
        try:
            with open(file_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
            
            with self._lock:
                for trace_data in data.get('traces', []):
                    record = PredictionTraceRecord.from_dict(trace_data)
                    self._register_trace(record)
            
            return True
        except Exception as e:
            print(f"[TRACE] Error loading all traces from {file_path}: {e}")
            return False
    
    def list_all_traces(self) -> List[Dict[str, Any]]:
        """Lista podsumowań wszystkich trace"""
        return [record.to_summary() for record in self._trace_register.values()]


