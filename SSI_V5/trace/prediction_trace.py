    def integrate_with_strategy_memory(self, strategy_memory_manager: Any) -> None:
        """
        Zintegruj z StrategyMemoryManager.
        
        Automatycznie uzupełnia PREDICTION_HISTORY w StrategyMemoryRecord.
        
        Args:
            strategy_memory_manager: Instancja StrategyMemoryManager
        """
        self._strategy_memory_manager = strategy_memory_manager
        
        # Przeskanuj istniejące trace i zaktualizuj Strategy Memory
        for trace in self.get_all_traces():
            if trace.strategy_experiment_id:
                self._sync_trace_to_strategy_memory(trace)
    
    def sync_trace_to_strategy_memory(self, trace: PredictionTraceRecord) -> bool:
        """
        Synchronizuj pojedynczy trace z Strategy Memory.
        
        Args:
            trace: Trace do zsynchronizowania
            
        Returns:
            bool: Czy synchronizacja sie powiodla
        """
        if not hasattr(self, '_strategy_memory_manager') or self._strategy_memory_manager is None:
            return False
        
        if not trace.strategy_experiment_id:
            return False
        
        # Pobierz pamięć strategii
        memory = self._strategy_memory_manager.get_strategy_memory(
            trace.strategy_experiment_id
        )
        
        if memory is None:
            # Utwórz nową pamięć
            memory = self._strategy_memory_manager.create_strategy_memory(
                strategy_id=trace.strategy_experiment_id,
                version="1.0.0"
            )
        
        # Dodaj trace do historii
        trace_data = trace.to_dict()
        memory.PREDICTION_HISTORY.append(trace_data)
        
        # Zaktualizuj pamięć
        self._strategy_memory_manager._save_record(memory)
        
        return True
    
    def _sync_trace_to_strategy_memory(self, trace: PredictionTraceRecord) -> bool:
        """Wewnetrzna metoda synchronizacji"""
        return self.sync_trace_to_strategy_memory(trace)
    
