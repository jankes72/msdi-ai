    def create_genome_from_strategy(self, strategy_id: str, 
                                    strategy_version: str = "1.0.0",
                                    parameters: Optional[Dict[str, Any]] = None,
                                    features: Optional[List[str]] = None,
                                    rules: Optional[Dict[str, Any]] = None) -> StrategyGenome:
        """
        Tworzy nowy genom strategii z parametrow.
        
        Args:
            strategy_id: ID strategii
            strategy_version: Wersja strategii
            parameters: Parametry strategii
            features: Lista cech
            rules: Regu³y strategii
            
        Returns:
            StrategyGenome: Utworzony genom
        """
        genome = StrategyGenome(
            strategy_id=strategy_id,
            strategy_version=strategy_version,
            features=features or [],
            rules=rules or {}
        )
        
        # Dodaj parametry jako geny
        if parameters:
            for param_name, param_value in parameters.items():
                # Okrel typ genu na podstawie nazwy
                gene_type = self._get_gene_type_from_name(param_name)
                
                # Okrel zakresy
                min_val, max_val = self._get_value_range(gene_type, param_value)
                
                genome.add_parameter(
                    name=param_name,
                    value=param_value,
                    gene_type=gene_type,
                    min_value=min_val,
                    max_value=max_val
                )
        
        # Zapisz w pamieci
        with self._lock:
            self.genomes[genome.genome_id] = genome
        
        self.logger.info(f"Utworzono genom {genome.genome_id} dla strategii {strategy_id}")
        return genome
    
    def _get_gene_type_from_name(self, name: str) -> GeneType:
        """Okrela typ genu na podstawie nazwy"""
        name_lower = name.lower()
        
        if any(word in name_lower for word in ['threshold', 'limit', 'max', 'min']):
            return GeneType.THRESHOLD
        elif any(word in name_lower for word in ['weight', 'score', 'rate']):
            return GeneType.WEIGHT
        elif any(word in name_lower for word in ['operator', 'op']):
            return GeneType.OPERATOR
        elif any(word in name_lower for word in ['rule', 'condition']):
            return GeneType.RULE
        elif any(word in name_lower for word in ['feature', 'feats']):
            return GeneType.FEATURE
        elif any(word in name_lower for word in ['constraint']):
            return GeneType.CONSTRAINT
        else:
            return GeneType.PARAMETER
    
    def _get_value_range(self, gene_type: GeneType, value: Any) -> Tuple[Optional[float], Optional[float]]:
        """Okrela zakres wartosci dla genu"""
        if gene_type in [GeneType.THRESHOLD, GeneType.WEIGHT]:
            return (0.0, 1.0)
        elif gene_type in [GeneType.PARAMETER]:
            if isinstance(value, float):
                return (value * 0.5, value * 2.0)
            else:
                return (None, None)
        elif gene_type in [GeneType.CONSTRAINT]:
            return (0.0, 100.0)
        else:
            return (self.config.min_parameter_value, self.config.max_parameter_value)
    
    def mutate_genome(self, genome_id: str, 
                     mutation_type: MutationType = MutationType.RANDOM,
                     mutation_rate: Optional[float] = None) -> Tuple[StrategyGenome, EvolutionRecord]:
        """
        Mutuje genom i tworzy rekord ewolucji.
        
        Args:
            genome_id: ID genomu do zmutowania
            mutation_type: Typ mutacji
            mutation_rate: Prawdopodobienstwo mutacji
            
        Returns:
            Tuple[StrategyGenome, EvolutionRecord]: Zmutowany genom i rekord ewolucji
            
        Raises:
            ValueError: Jesli genom nie istnieje
        """
        with self._lock:
            if genome_id not in self.genomes:
                raise ValueError(f"Genom {genome_id} nie istnieje")
            
            parent_genome = self.genomes[genome_id]
            
            # Zmutuj genom
            child_genome = parent_genome.mutate(
                mutation_type=mutation_type,
                mutation_rate=mutation_rate or self.config.mutation_rate
            )
            
            # Utworz rekord ewolucji
            record = EvolutionRecord(
                parent_genome_id=parent_genome.genome_id,
                child_genome_id=child_genome.genome_id,
                evolution_type=EvolutionType.MUTATION,
                mutation_type=mutation_type.value,
                mutation_rate=mutation_rate or self.config.mutation_rate,
                fitness_before=parent_genome.fitness_score,
                fitness_after=child_genome.fitness_score,
                strategy_id=child_genome.strategy_id,
                strategy_version=child_genome.strategy_version
            )
            
            # Zapisz nowy genom
            self.genomes[child_genome.genome_id] = child_genome
            
            # Zapisz rekord mutacji
            self.mutation_records.append(record)
            
            # Zapisz w historii ewolucji
            if child_genome.strategy_id not in self.evolution_history:
                self.evolution_history[child_genome.strategy_id] = EvolutionHistory(
                    strategy_id=child_genome.strategy_id
                )
            self.evolution_history[child_genome.strategy_id].add_record(record)
            
            self.logger.info(f"Zmutowano genom {genome_id} -> {child_genome.genome_id}, "
                           f"typ: {mutation_type.value}")
            
            # Zapis do pliku
            try:
                self._save_history()
            except Exception as e:
                self.logger.error(f"Blad zapisu po mutacji: {e}")
            
            return child_genome, record
    
    def crossover_genomes(self, genome_id_1: str, 
                         genome_id_2: str,
                         crossover_rate: Optional[float] = None) -> Tuple[StrategyGenome, StrategyGenome, List[EvolutionRecord]]:
        """
        Krzyzuje dwa genom i tworzy dwa potomki.
        
        Args:
            genome_id_1: ID pierwszego genomu
            genome_id_2: ID drugiego genomu
            crossover_rate: Stopien krzyzowania
            
        Returns:
            Tuple[child1, child2, records]: Dwoje potomkow i lista rekordow ewolucji
            
        Raises:
            ValueError: Jesli ktorykolwiek genom nie istnieje
        """
        with self._lock:
            if genome_id_1 not in self.genomes:
                raise ValueError(f"Genom {genome_id_1} nie istnieje")
            if genome_id_2 not in self.genomes:
                raise ValueError(f"Genom {genome_id_2} nie istnieje")
            
            parent1 = self.genomes[genome_id_1]
            parent2 = self.genomes[genome_id_2]
            
            # Krzyzuj genom'y
            child1, child2 = parent1.crossover(
                parent2,
                crossover_rate=crossover_rate or self.config.crossover_rate
            )
            
            # Utworz rekordy ewolucji
            rate = crossover_rate or self.config.crossover_rate
            
            record1 = EvolutionRecord(
                parent_genome_id=parent1.genome_id,
                child_genome_id=child1.genome_id,
                evolution_type=EvolutionType.CROSSOVER,
                crossover_rate=rate,
                fitness_before=parent1.fitness_score,
                fitness_after=child1.fitness_score,
                strategy_id=child1.strategy_id,
                strategy_version=child1.strategy_version,
                metadata={'second_parent': parent2.genome_id}
            )
            
            record2 = EvolutionRecord(
                parent_genome_id=parent2.genome_id,
                child_genome_id=child2.genome_id,
                evolution_type=EvolutionType.CROSSOVER,
                crossover_rate=rate,
                fitness_before=parent2.fitness_score,
                fitness_after=child2.fitness_score,
                strategy_id=child2.strategy_id,
                strategy_version=child2.strategy_version,
                metadata={'second_parent': parent1.genome_id}
            )
            
            # Zapisz nowy genom'y
            self.genomes[child1.genome_id] = child1
            self.genomes[child2.genome_id] = child2
            
            # Zapisz rekordy
            self.mutation_records.extend([record1, record2])
            
            # Zapisz w historii ewolucji
            for strategy_id in [child1.strategy_id, child2.strategy_id]:
                if strategy_id not in self.evolution_history:
                    self.evolution_history[strategy_id] = EvolutionHistory(strategy_id=strategy_id)
                self.evolution_history[strategy_id].add_record(record1 if strategy_id == child1.strategy_id else record2)
            
            self.logger.info(f"Skrzyzowano genom'y {genome_id_1} i {genome_id_2} -> "
                           f"child1: {child1.genome_id}, child2: {child2.genome_id}")
            
            # Zapis do pliku
            try:
                self._save_history()
            except Exception as e:
                self.logger.error(f"Blad zapisu po krzyzowaniu: {e}")
            
            return child1, child2, [record1, record2]
    
    def create_population_from_strategy(self, strategy_id: str,
                                       population_size: int = 10) -> List[StrategyGenome]:
        """
        Tworzy poczatkowa populacje genomow z jednej strategii.
        
        Args:
            strategy_id: ID bazowej strategii
            population_size: Rozmiar populacji
            
        Returns:
            List[StrategyGenome]: Populacja genomow
        """
        # Nie mozna utworzyc populacji bez bazowego genomu
        base_genomes = [g for g in self.genomes.values() if g.strategy_id == strategy_id]
        
        if not base_genomes:
            raise ValueError(f"Brak genomow dla strategii {strategy_id}")
        
        base_genome = base_genomes[0]
        population = [base_genome]
        
        # Stworz reszte populacji przez mutacje
        for _ in range(1, population_size):
            child, _ = self.mutate_genome(
                base_genome.genome_id,
                mutation_type=MutationType.RANDOM
            )
            population.append(child)
        
        self.logger.info(f"Utworzono populacje {population_size} genomow dla strategii {strategy_id}")
        return population
    
    def generate_variants(self, genome_id: str, 
                        num_variants: int = 5,
                        mutation_types: Optional[List[MutationType]] = None) -> List[StrategyGenome]:
        """
        Generuje wiele wariantow genomu.
        
        Args:
            genome_id: ID genomu bazowego
            num_variants: Liczba wariantow
            mutation_types: Lista typow mutacji do uzycia
            
        Returns:
            List[StrategyGenome]: Lista wariantow
        """
        variants = []
        
        if mutation_types is None:
            mutation_types = [MutationType.RANDOM, MutationType.SMALL, MutationType.LARGE]
        
        for i in range(num_variants):
            # Wybierz losowy typ mutacji
            mutation_type = random.choice(mutation_types)
            
            child, _ = self.mutate_genome(
                genome_id,
                mutation_type=mutation_type
            )
            variants.append(child)
        
        self.logger.info(f"Wygenerowano {len(variants)} wariantow genomu {genome_id}")
        return variants
    
    def get_genome(self, genome_id: str) -> Optional[StrategyGenome]:
        """Pobiera genom po ID"""
        with self._lock:
            return copy.deepcopy(self.genomes.get(genome_id))
    
    def get_all_genomes(self) -> List[StrategyGenome]:
        """Pobiera wszystkie genom'y"""
        with self._lock:
            return [copy.deepcopy(g) for g in self.genomes.values()]
    
    def get_genomes_by_strategy(self, strategy_id: str) -> List[StrategyGenome]:
        """Pobiera genom'y dla danej strategii"""
        with self._lock:
            return [copy.deepcopy(g) for g in self.genomes.values() 
                   if g.strategy_id == strategy_id]
    
    def get_evolution_history(self, strategy_id: str) -> Optional[EvolutionHistory]:
        """Pobiera historiê ewolucji dla strategii"""
        with self._lock:
            return copy.deepcopy(self.evolution_history.get(strategy_id))
    
    def get_mutation_records(self, limit: int = 100) -> List[EvolutionRecord]:
        """Pobiera rekordy mutacji"""
        with self._lock:
            return [copy.deepcopy(r) for r in self.mutation_records[-limit:]]
    
    def get_statistics(self) -> Dict[str, Any]:
        """Pobiera statystyki silnika"""
        with self._lock:
            total_genomes = len(self.genomes)
            total_records = len(self.mutation_records)
            
            strategies = set(g.strategy_id for g in self.genomes.values())
            
            # Statystyki ewolucji
            total_improvements = 0
            total_evaluated = 0
            
            for history in self.evolution_history.values():
                for record in history.records:
                    if record.status == EvolutionStatus.EVALUATED:
                        total_evaluated += 1
                        if record.is_improvement():
                            total_improvements += 1
            
            return {
                'total_genomes': total_genomes,
                'total_records': total_records,
                'strategy_count': len(strategies),
                'success_rate': (total_improvements / total_evaluated * 100) if total_evaluated > 0 else 0.0,
                'evaluated_count': total_evaluated,
                'improvement_count': total_improvements
            }
    
    def clear_history(self) -> None:
        """Czysci historiê"""
        with self._lock:
            self.genomes.clear()
            self.evolution_history.clear()
            self.mutation_records.clear()
            
            try:
                if self.storage_path.exists():
                    self.storage_path.unlink()
                self.logger.info("Wyczyszczono historiê ewolucji")
            except Exception as e:
                self.logger.error(f"Blad czyszczenia historii: {e}")
    
    def set_fitness(self, genome_id: str, fitness_score: float,
                    metrics: Optional[Dict[str, float]] = None) -> bool:
        """
        Ustawia fitness score dla genomu.
        
        Args:
            genome_id: ID genomu
            fitness_score: Wartosc fitness
            metrics: Opcjonalne metryki
            
        Returns:
            bool: True jesli ustawienie sie powiodlo
        """
        with self._lock:
            if genome_id not in self.genomes:
                return False
            
            genome = self.genomes[genome_id]
            genome.fitness_score = fitness_score
            
            if metrics:
                genome.fitness_metrics.update(metrics)
            
            # Zaktualizuj rekordy ewolucji
            for history in self.evolution_history.values():
                for record in history.records:
                    if record.child_genome_id == genome_id:
                        record.fitness_after = fitness_score
                        if metrics:
                            record.fitness_metrics.update(metrics)
                        record.set_evaluated(fitness_score, metrics)
            
            self.logger.info(f"Ustawiono fitness {fitness_score} dla genomu {genome_id}")
            return True
    
    def remove_genome(self, genome_id: str) -> bool:
        """Usuwa genom z pamięci"""
        with self._lock:
            if genome_id in self.genomes:
                del self.genomes[genome_id]
                self.logger.info(f"Usunieto genom {genome_id}")
                return True
            return False
    
    def get_lineage(self, genome_id: str, depth: int = 5) -> List[StrategyGenome]:
        """
        Pobiera rodowód genomu (przodków).
        
        Args:
            genome_id: ID genomu
            depth: Glebia rekursji
            
        Returns:
            List[StrategyGenome]: Lista przodków
        """
        with self._lock:
            lineage = []
            current_id = genome_id
            
            for _ in range(depth):
                if current_id not in self.genomes:
                    break
                
                genome = self.genomes[current_id]
                lineage.append(copy.deepcopy(genome))
                
                if genome.parent_genome_id:
                    current_id = genome.parent_genome_id
                else:
                    break
            
            return lineage
