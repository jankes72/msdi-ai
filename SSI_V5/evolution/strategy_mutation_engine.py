class StrategyMutationEngine:
    """
    Silnik mutacji strategii.
    
    Odpowiedzialnosc:
    - Tworzenie nowych wariantow genomow
    - Kontrolowane mutacje strategii
    - Generowanie populacji poczatkowej
    - Zachowanie historii mutacji
    
    ZASADA: TYLKO LABORATORIUM - nie wplywa na produkcje.
    """
    
    def __init__(self, config: Optional[MutationConfig] = None,
                 storage_path: str = "data/evolution_engine.json"):
        """
        Inicjalizacja silnika mutacji.
        
        Args:
            config: Konfiguracja silnika
            storage_path: Sciezka do storage
        """
        self.config = config or MutationConfig()
        self.storage_path = Path(storage_path)
        
        # Populacja genomow
        self.genomes: Dict[str, StrategyGenome] = {}
        
        # Historia ewolucji
        self.evolution_history: Dict[str, EvolutionHistory] = {}  # strategy_id -> EvolutionHistory
        
        # Historia rewolucji
        self.mutation_records: List[EvolutionRecord] = []
        
        # Lock dla thread-safety
        self._lock = RLock()
        
        # Konfiguracja logowania
        self._setup_logging()
        
        # Zapewnij katalog storage
        self._ensure_storage_dir()
        
        # Zaladuj historiê
        self._load_history()
    
    def _setup_logging(self) -> None:
        """Konfiguracja logowania"""
        self.logger = logging.getLogger('StrategyMutationEngine')
        if not self.logger.handlers:
            handler = logging.StreamHandler()
            handler.setFormatter(logging.Formatter(
                '%(asctime)s - %(name)s - %(levelname)s - %(message)s'
            ))
            self.logger.addHandler(handler)
            self.logger.setLevel(logging.INFO)
    
    def _ensure_storage_dir(self) -> None:
        """Zapewnia, ze katalog storage istnieje"""
        storage_dir = self.storage_path.parent
        if not storage_dir.exists():
            storage_dir.mkdir(parents=True, exist_ok=True)
            self.logger.info(f"Utworzono katalog storage: {storage_dir}")
    
    def _load_history(self) -> None:
        """Ladenie historii z pliku"""
        if not self.storage_path.exists():
            return
        
        try:
            with open(self.storage_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
                
                # Zaladuj config
                if 'config' in data:
                    self.config = MutationConfig.from_dict(data['config'])
                
                # Zaladuj genome'y
                for genome_data in data.get('genomes', []):
                    genome = StrategyGenome.from_dict(genome_data)
                    self.genomes[genome.genome_id] = genome
                
                # Zaladuj historiê ewolucji
                for strategy_id, history_data in data.get('evolution_history', {}).items():
                    history = EvolutionHistory.from_dict(history_data)
                    self.evolution_history[strategy_id] = history
                
                # Zaladuj rekordy mutacji
                for record_data in data.get('mutation_records', []):
                    record = EvolutionRecord.from_dict(record_data)
                    self.mutation_records.append(record)
            
            self.logger.info(f"Zaladowano {len(self.genomes)} genomow i {len(self.mutation_records)} rekordow")
            
        except Exception as e:
            self.logger.error(f"Blad ladowania historii: {e}")
    
    def _save_history(self) -> None:
        """Zapis historii do pliku"""
        with self._lock:
            try:
                data = {
                    'config': self.config.to_dict(),
                    'genomes': [g.to_dict() for g in self.genomes.values()],
                    'evolution_history': {
                        strategy_id: history.to_dict()
                        for strategy_id, history in self.evolution_history.items()
                    },
                    'mutation_records': [r.to_dict() for r in self.mutation_records],
                    'last_updated': datetime.now().isoformat()
                }
                
                with open(self.storage_path, 'w', encoding='utf-8') as f:
                    json.dump(data, f, indent=2, default=str, ensure_ascii=False)
                
                self.logger.info(f"Zapisano {len(self.genomes)} genomow i {len(self.mutation_records)} rekordow")
                
            except Exception as e:
                self.logger.error(f"Blad zapisu historii: {e}")
    
