    evaluated_time: Optional[datetime] = None
    
    # ===== METODY ======
    
    def calculate_fitness_improvement(self) -> float:
        """Oblicza poprawe fitness"""
        if self.fitness_before > 0:
            self.fitness_improvement = self.fitness_after - self.fitness_before
        else:
            self.fitness_improvement = self.fitness_after
        return self.fitness_improvement
    
    def get_improvement_percentage(self) -> float:
        """Oblicza poprawe fitness w procentach"""
        improvement = self.fitness_after - self.fitness_before
        if self.fitness_before > 0:
            return (improvement / self.fitness_before) * 100
        else:
            return 0.0
    
    def is_improvement(self) -> bool:
        """Sprawdza czy zachodzila poprawa fitness"""
        return self.fitness_after > self.fitness_before
    
