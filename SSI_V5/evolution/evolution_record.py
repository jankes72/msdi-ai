class EvolutionStatus(Enum):
    """Status rekordu ewolucji"""
    CREATED = "created"           # Utworzony
    PENDING = "pending"           # Oczekuje na ocene
    EVALUATED = "evaluated"      # Oceniony
    SELECTED = "selected"         # Wybrany do kolejnej generacji
    REJECTED = "rejected"        # Odrzucony
    ARCHIVED = "archived"        # Zaarchiwizowany


class EvolutionType(Enum):
    """Typ ewolucji"""
    MUTATION = "mutation"         # Mutacja pojedynczego genomu
    CROSSOVER = "crossover"       # Krzyzowanie dwoch genomow
    COPY = "copy"                 # Kopia genomu
    INITIAL = "initial"           # Inicjalizacja nowej strategii
    MANUAL = "manual"             # Reczna modyfikacja


