@dataclass
class EvolutionHistory:
    """
    Historia ewolucji dla pojedynczej strategii.
    
    Zachowuje:
    - Wszystkie rekordy ewolucji
    - Drzewo ewolucyjne
    - Statystyki ewolucji
    """
    
    strategy_id: str
    records: List[EvolutionRecord] = field(default_factory=list)
    
    def add_record(self, record: EvolutionRecord) -> None:
        """Dodaje rekord do historii"""
        if record.strategy_id != self.strategy_id:
            record.strategy_id = self.strategy_id
        self.records.append(record)
    
    def get_record(self, record_id: str) -> Optional[EvolutionRecord]:
        """Pobiera rekord po ID"""
        return next((r for r in self.records if r.record_id == record_id), None)
    
    def get_records_by_parent(self, parent_genome_id: str) -> List[EvolutionRecord]:
        """Pobiera rekordy dla danego genomu rodzica"""
        return [r for r in self.records if r.parent_genome_id == parent_genome_id]
    
    def get_records_by_child(self, child_genome_id: str) -> List[EvolutionRecord]:
        """Pobiera rekordy dla danego genomu potomka"""
        return [r for r in self.records if r.child_genome_id == child_genome_id]
    
    def get_best_improvement(self) -> Optional[EvolutionRecord]:
        """Pobiera rekord z najwieksza poprawa fitness"""
        if not self.records:
            return None
        return max(self.records, key=lambda r: r.fitness_improvement)
    
    def get_success_rate(self) -> float:
        """Oblicza odsetek udanych ewolucji (poprawa fitness)"""
        if not self.records:
            return 0.0
        
        successful = sum(1 for r in self.records if r.is_improvement())
        return (successful / len(self.records)) * 100
    
    def get_average_improvement(self) -> float:
        """Oblicza srednia poprawe fitness"""
        if not self.records:
            return 0.0
        
        improvements = [r.fitness_improvement for r in self.records if r.is_improvement()]
        return sum(improvements) / len(improvements) if improvements else 0.0
    
    def get_evolution_tree(self) -> Dict[str, Any]:
        """
        Generuje drzewo ewolucyjne jako strukture zagniezdzona.
        
        Returns:
            Dict: Drzewo ewolucyjne
        """
        tree = {}
        
        for record in self.records:
            parent_id = record.parent_genome_id or "root"
            child_id = record.child_genome_id or "unknown"
            
            if parent_id not in tree:
                tree[parent_id] = {}
            
            tree[parent_id][child_id] = {
                'record_id': record.record_id,
                'fitness_before': record.fitness_before,
                'fitness_after': record.fitness_after,
                'improvement': record.fitness_improvement,
                'type': record.evolution_type.value
            }
        
        return tree
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do slownika"""
        return {
            'strategy_id': self.strategy_id,
            'records': [r.to_dict() for r in self.records],
            'total_records': len(self.records),
            'success_rate': self.get_success_rate(),
            'average_improvement': self.get_average_improvement()
        }
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'EvolutionHistory':
        """Utworzenie z slownika"""
        history = cls(strategy_id=data.get('strategy_id', ''))
        
        for record_data in data.get('records', []):
            record = EvolutionRecord.from_dict(record_data)
            history.add_record(record)
        
        return history
    
    def to_json(self) -> str:
        """Konwersja do JSON"""
        return json.dumps(self.to_dict(), indent=2, default=str, ensure_ascii=False)
    
    @classmethod
    def from_json(cls, json_str: str) -> 'EvolutionHistory':
        """Utworzenie z JSON"""
        data = json.loads(json_str)
        return cls.from_dict(data)
