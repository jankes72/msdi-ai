def calculate_accumulative_fitness(
    outcomes: List[PredictionOutcome],
    window_size: int = 10
) -> List[float]:
    """
    Oblicza fitness kumulacyjny w oknie.
    
    Args:
        outcomes: Lista PredictionOutcome
        window_size: Rozmiar okna
    
    Returns:
        Lista kumulacyjnych fitness
    """
    if not outcomes:
        return []
    
    fitness_values = []
    
    for i in range(1, len(outcomes) + 1):
        window = outcomes[max(0, i - window_size):i]
        if window:
            correct = sum(1 for o in window if o.result_correct)
            fitness = correct / len(window)
            fitness_values.append(fitness)
        else:
            fitness_values.append(0.0)
    
    return fitness_values


def calculate_stability_metric(
    accuracy_scores: List[float]
) -> float:
    """
    Oblicza metrykę stabilności na podstawie historii dokładności.
    
    Args:
        accuracy_scores: Lista wyników dokładności
    
    Returns:
        Metryka stabilności (0.0 - 1.0)
    """
    if len(accuracy_scores) < 2:
        return 1.0
    
    mean = sum(accuracy_scores) / len(accuracy_scores)
    variance = sum((x - mean) ** 2 for x in accuracy_scores) / len(accuracy_scores)
    std_dev = math.sqrt(variance)
    
    # Im mniejsze odchylenie standardowe, tym wyższa stabilność
    stability = max(0.0, 1.0 - std_dev)
    
    return stability


