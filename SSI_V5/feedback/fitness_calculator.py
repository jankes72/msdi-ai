class StrategyFitnessCalculator:
    """
    Kalkulator fitness strategii.
    
    Odpowiedzialność:
    - Obliczanie fitness na podstawie historii PredictionOutcome
    - Agregacja wyników i statystyk
    - Utrzymywanie historii fitness
    
    ZASADY:
    1. TYLKO obliczanie - nie modyfikuje danych wejściowych
    2. Korzysta z kopii danych
    3. Fitness: 0.0 - 1.0
    4. Obsługuje różne strategie wag
    """
    
    def __init__(
        self,
        name: str = "StrategyFitnessCalculator",
        weights: Optional[FitnessWeights] = None,
        min_predictions_for_fitness: int = 1
    ):
        """
        Inicjalizacja kalkulatora.
        
        Args:
            name: Nazwa kalkulatora
            weights: Wagi dla składników fitness (opcjonalne)
            min_predictions_for_fitness: Minimalna liczba predykcji do obliczenia fitness
        """
        self.name = name
        self.weights = weights or FitnessWeights()
        self.min_predictions = min_predictions_for_fitness
        
        # Historia obliczeń
        self.fitness_history: Dict[str, List[float]] = {}  # strategy_id -> [fitness values]
        self.evaluation_count = 0
        self.events: List[FeedbackEvent] = []
        
        # Statystyki
        self.total_strategies = 0
        self.total_predictions = 0
    
    def calculate_fitness(
        self,
        strategy_id: str,
        outcomes: List[PredictionOutcome]
    ) -> StrategyFitness:
        """
        Oblicza fitness dla strategii na podstawie historii outcome.
        
        Args:
            strategy_id: ID strategii
            outcomes: Lista PredictionOutcome
        
        Returns:
            StrategyFitness z obliczonym fitness
        """
        import time
        start_time = time.time()
        
        # Filtrowanie outcome dla konkretnej strategii
        if strategy_id:
            filtered_outcomes = [
                o for o in outcomes 
                if o.strategy_id == strategy_id
            ]
        else:
            filtered_outcomes = outcomes
        
        # Jeśli za mało predykcji, zwróć pusty fitness
        if len(filtered_outcomes) < self.min_predictions:
            fitness = StrategyFitness(
                strategy_id=strategy_id,
                total_predictions=len(filtered_outcomes)
            )
            return fitness
        
        # Stwórz StrategyFitness
        fitness = StrategyFitness(
            strategy_id=strategy_id,
            strategy_version="1.0.0",  # Domyślna wersja
            weights=self.weights.to_dict()
        )
        
        # Dodaj wszystkie outcome
        for outcome in filtered_outcomes:
            fitness.add_prediction_outcome(outcome)
        
        # Zapisz do historii
        if strategy_id not in self.fitness_history:
            self.fitness_history[strategy_id] = []
        self.fitness_history[strategy_id].append(fitness.overall_fitness)
        
        # Zaktualizuj statystyki
        self.total_strategies += 1
        self.total_predictions += len(filtered_outcomes)
        self.evaluation_count += 1
        
        # Zarejestruj zdarzenie
        processing_time_ms = (time.time() - start_time) * 1000
        self._log_event(
            FeedbackEventType.FITNESS_CALCULATION_COMPLETED,
            strategy_id=strategy_id,
            processing_time_ms=processing_time_ms
        )
        
        return fitness
    
    def calculate_fitness_for_multiple(
        self,
        strategy_ids: List[str],
        outcomes: List[PredictionOutcome]
    ) -> Dict[str, StrategyFitness]:
        """
        Oblicza fitness dla wielu strategii.
        
        Args:
            strategy_ids: Lista ID strategii
            outcomes: Lista wszystkich PredictionOutcome
        
        Returns:
            Słownik {strategy_id: StrategyFitness}
        """
        results = {}
        
        for strategy_id in strategy_ids:
            try:
                fitness = self.calculate_fitness(strategy_id, outcomes)
                results[strategy_id] = fitness
            except Exception as e:
                # Zarejestruj błąd
                self._log_event(
                    FeedbackEventType.ERROR_CALCULATION_FAILED,
                    strategy_id=strategy_id,
                    error_message=str(e),
                    success=False
                )
        
        return results
    
    def calculate_from_outcomes(
        self,
        outcomes: List[PredictionOutcome]
    ) -> Dict[str, StrategyFitness]:
        """
        Oblicza fitness dla wszystkich strategii z listy outcome.
        
        Args:
            outcomes: Lista PredictionOutcome
        
        Returns:
            Słownik {strategy_id: StrategyFitness}
        """
        # Pobierz unikalne ID strategii
        strategy_ids = set(o.strategy_id for o in outcomes if o.strategy_id)
        
        return self.calculate_fitness_for_multiple(list(strategy_ids), outcomes)
    
    def get_components(
        self,
        outcomes: List[PredictionOutcome]
    ) -> FitnessComponents:
        """
        Oblicza składniki fitness bez tworzenia StrategyFitness.
        
        Args:
            outcomes: Lista PredictionOutcome
        
        Returns:
            FitnessComponents
        """
        if not outcomes:
            return FitnessComponents()
        
        total = len(outcomes)
        
        # Dokładność
        correct_count = sum(1 for o in outcomes if o.result_correct)
        exact_count = sum(1 for o in outcomes if o.exact_score)
        
        accuracy = correct_count / total if total > 0 else 0.0
        exact_accuracy = exact_count / total if total > 0 else 0.0
        
        # Dokładność goli
        goals_correct_count = sum(1 for o in outcomes if o.goals_correct)
        goals_accuracy = goals_correct_count / total if total > 0 else 0.0
        
        # Stabilność (odchylenie standardowe accuracy_score)
        accuracy_scores = [o.accuracy_score for o in outcomes]
        mean_accuracy = sum(accuracy_scores) / len(accuracy_scores) if accuracy_scores else 0.0
        variance = sum((x - mean_accuracy) ** 2 for x in accuracy_scores) / len(accuracy_scores) if len(accuracy_scores) > 1 else 0.0
        stability = max(0.0, 1.0 - variance)
        
        # Ryzyko
        failed_count = sum(1 for o in outcomes if not o.result_correct)
        risk = min(1.0, failed_count / total * 2) if total > 0 else 0.0
        
        # Opłacalność (symulowana)
        # Im wyższa dokładność, tym wyższa opłacalność
        profitability = min(1.0, accuracy * 1.5)
        
        # Składniki fitness
        components = FitnessComponents(
            accuracy_component=accuracy * self.weights.accuracy_weight,
            exact_accuracy_component=exact_accuracy * self.weights.exact_accuracy_weight,
            stability_component=stability * self.weights.stability_weight,
            profitability_component=profitability * self.weights.profitability_weight,
            low_risk_component=(1.0 - risk) * self.weights.low_risk_weight
        )
        
        return components
    
    def rank_strategies(
        self,
        fitness_values: Dict[str, StrategyFitness],
        reverse: bool = True
    ) -> List[Tuple[str, StrategyFitness]]:
        """
        Ranking strategii według fitness.
        
        Args:
            fitness_values: Słownik {strategy_id: StrategyFitness}
            reverse: Sortowanie malejące (domyślnie True)
        
        Returns:
            Posortowana lista (strategy_id, StrategyFitness)
        """
        sorted_fitness = sorted(
            fitness_values.items(),
            key=lambda x: x[1].overall_fitness,
            reverse=reverse
        )
        return sorted_fitness
    
    def get_top_n(
        self,
        fitness_values: Dict[str, StrategyFitness],
        n: int = 5
    ) -> List[Tuple[str, StrategyFitness]]:
        """
        Pobiera top N strategii.
        
        Args:
            fitness_values: Słownik {strategy_id: StrategyFitness}
            n: Liczba strategii do zwrócenia
        
        Returns:
            Top N strategii
        """
        ranked = self.rank_strategies(fitness_values)
        return ranked[:n]
    
    def get_statistics(self) -> Dict[str, Any]:
        """
        Pobiera statystyki kalkulatora.
        
        Returns:
            Statystyki kalkulatora
        """
        total_calculations = self.evaluation_count
        total_strategies = len(self.fitness_history)
        
        # Średni fitness
        all_fitness_values = [f for history in self.fitness_history.values() for f in history]
        avg_fitness = sum(all_fitness_values) / len(all_fitness_values) if all_fitness_values else 0.0
        
        return {
            'total_calculations': total_calculations,
            'total_strategies': total_strategies,
            'total_predictions': self.total_predictions,
            'average_fitness': round(avg_fitness, 4),
            'fitness_history': {
                strategy_id: [round(f, 4) for f in history]
                for strategy_id, history in self.fitness_history.items()
            },
            'weights': self.weights.to_dict()
        }
    
    def reset(self) -> None:
        """Resetuje kalkulator."""
        self.evaluation_count = 0
        self.events = []
        self.total_strategies = 0
        self.total_predictions = 0
        self.fitness_history = {}
    
    def _log_event(
        self,
        event_type: FeedbackEventType,
        strategy_id: str = "",
        processing_time_ms: float = 0.0,
        error_message: str = "",
        success: bool = True
    ) -> FeedbackEvent:
        """Rejestruje zdarzenie fitness."""
        event = FeedbackEvent(
            event_type=event_type,
            strategy_id=strategy_id,
            feedback_loop_id=f"fitness_sess_{self.evaluation_count}",
            reason=f"Fitness calculation for strategy {strategy_id}",
            before_state={'strategy_id': strategy_id, 'evaluation_count': self.evaluation_count},
            event_name=f"{event_type.value}_{self.evaluation_count}",
            processing_time_ms=processing_time_ms,
            success=success,
            error_message=error_message
        )
        
        self.events.append(event)
        return event


