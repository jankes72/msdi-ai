@dataclass
class FitnessWeights:
    """
    Wagi dla obliczania fitness.
    
    Sumowanie wag musi dać 1.0.
    Domyślne wagi są zoptymalizowane dla strategii typerskich.
    """
    accuracy_weight: float = 0.40      # Waga dokładności
    exact_accuracy_weight: float = 0.25  # Waga dokładnych trafień
    stability_weight: float = 0.20     # Waga stabilności
    profitability_weight: float = 0.10  # Waga opłacalności (symulowana)
    low_risk_weight: float = 0.05     # Waga niskiego ryzyka
    
    def normalize(self) -> None:
        """Normalizuje wagi tak, aby sumowały się do 1.0."""
        total = (self.accuracy_weight + self.exact_accuracy_weight + 
                self.stability_weight + self.profitability_weight + 
                self.low_risk_weight)
        
        if total > 0:
            self.accuracy_weight /= total
            self.exact_accuracy_weight /= total
            self.stability_weight /= total
            self.profitability_weight /= total
            self.low_risk_weight /= total
    
    def get_total(self) -> float:
        """Zwraca sumę wag."""
        return (self.accuracy_weight + self.exact_accuracy_weight + 
                self.stability_weight + self.profitability_weight + 
                self.low_risk_weight)
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do słownika."""
        return {
            'accuracy_weight': self.accuracy_weight,
            'exact_accuracy_weight': self.exact_accuracy_weight,
            'stability_weight': self.stability_weight,
            'profitability_weight': self.profitability_weight,
            'low_risk_weight': self.low_risk_weight
        }
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'FitnessWeights':
        """Utworzenie z słownika."""
        return cls(
            accuracy_weight=float(data.get('accuracy_weight', 0.40)),
            exact_accuracy_weight=float(data.get('exact_accuracy_weight', 0.25)),
            stability_weight=float(data.get('stability_weight', 0.20)),
            profitability_weight=float(data.get('profitability_weight', 0.10)),
            low_risk_weight=float(data.get('low_risk_weight', 0.05))
        )


@dataclass
class FitnessComponents:
    """
    Składniki fitness gotowe do agregacji.
    
    Każdy składnik to wartość 0.0 - 1.0.
    """
    accuracy_component: float = 0.0
    exact_accuracy_component: float = 0.0
    stability_component: float = 0.0
    profitability_component: float = 0.0
    low_risk_component: float = 0.0
    
    @property
    def total(self) -> float:
        """Suma wszystkich składników."""
        return (self.accuracy_component + self.exact_accuracy_component +
                self.stability_component + self.profitability_component +
                self.low_risk_component)
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do słownika."""
        return {
            'accuracy_component': self.accuracy_component,
            'exact_accuracy_component': self.exact_accuracy_component,
            'stability_component': self.stability_component,
            'profitability_component': self.profitability_component,
            'low_risk_component': self.low_risk_component,
            'total': self.total
        }


