@dataclass
class FeedbackEvent:
    """
    Zdarzenie w pętli feedback.
    
    Rejestruje wszystkie ważne zdarzenia zachodzące podczas:
    - Odbierania predykcji
    - Odbierania wyników
    - Ewaluacji
    - Obliczania fitness
    - Zapisywania do pamięci
    - Ewolucji strategii
    
    Używane do:
    - Debugowania
    - Audytu
    - Analizy wydajności
    - Reprodukcji
    """
    
    # ===== IDENTYFIKACJA =====
    event_id: str = field(default_factory=lambda: f"event_{uuid.uuid4().hex[:12]}")
    strategy_id: str = ""
    feedback_loop_id: str = ""
    
    # ===== ZDARZENIE =====
    event_type: FeedbackEventType = FeedbackEventType.SYSTEM_INITIALIZED
    event_name: str = ""
    
    # ===== STAN PRZED I PO =====
    before_state: Dict[str, Any] = field(default_factory=dict)
    after_state: Dict[str, Any] = field(default_factory=dict)
    
    # ===== DETAL =====  
    reason: str = ""
    details: Dict[str, Any] = field(default_factory=dict)
    success: bool = True
    error_message: Optional[str] = None
    
    # ===== METRYKI ZDARZENIA =====
    processing_time_ms: float = 0.0
    memory_usage_bytes: int = 0
    
    # ===== METADANE =====
    timestamp: datetime = field(default_factory=datetime.now)
    metadata: Dict[str, Any] = field(default_factory=dict)
    
    # ===== METODY =====
    
    def mark_success(self, after_state: Dict[str, Any] = None, reason: str = "") -> None:
        """Zaznacz zdarzenie jako sukces."""
        self.success = True
        self.error_message = None
        if after_state:
            self.after_state = copy.deepcopy(after_state)
        if reason:
            self.reason = reason
    
    def mark_failure(self, error_message: str, reason: str = "") -> None:
        """Zaznacz zdarzenie jako porażka."""
        self.success = False
        self.error_message = error_message
        if reason:
            self.reason = reason
    
    def is_success(self) -> bool:
        """Czy zdarzenie zakończyło się sukcesem."""
        return self.success
    
    def is_failure(self) -> bool:
        """Czy zdarzenie zakończyło się porażką."""
        return not self.success
    
    def get_summary(self) -> Dict[str, Any]:
        """Podsumowanie zdarzenia."""
        return {
            "event_id": self.event_id,
            "strategy_id": self.strategy_id,
            "event_type": self.event_type.value,
            "event_name": self.event_name,
            "success": self.success,
            "timestamp": self.timestamp.isoformat(),
            "reason": self.reason,
            "processing_time_ms": round(self.processing_time_ms, 2),
            "error_message": self.error_message
        }
    
    # ===== SERIALIZACJA =====
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do słownika."""
        data = {
            'event_id': self.event_id,
            'strategy_id': self.strategy_id,
            'feedback_loop_id': self.feedback_loop_id,
            'event_type': self.event_type.value,
            'event_name': self.event_name,
            'before_state': copy.deepcopy(self.before_state),
            'after_state': copy.deepcopy(self.after_state),
            'reason': self.reason,
            'details': copy.deepcopy(self.details),
            'success': self.success,
            'error_message': self.error_message,
            'processing_time_ms': self.processing_time_ms,
            'memory_usage_bytes': self.memory_usage_bytes,
            'timestamp': self.timestamp.isoformat(),
            'metadata': copy.deepcopy(self.metadata)
        }
        return data
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'FeedbackEvent':
        """Utworzenie z słownika."""
        timestamp = data.get('timestamp')
        if isinstance(timestamp, str):
            timestamp = datetime.fromisoformat(timestamp)
        
        return cls(
            event_id=data.get('event_id', f"event_{uuid.uuid4().hex[:12]}"),
            strategy_id=data.get('strategy_id', ''),
            feedback_loop_id=data.get('feedback_loop_id', ''),
            event_type=FeedbackEventType(data.get('event_type', 'system_initialized')),
            event_name=data.get('event_name', ''),
            before_state=copy.deepcopy(data.get('before_state', {})),
            after_state=copy.deepcopy(data.get('after_state', {})),
            reason=data.get('reason', ''),
            details=copy.deepcopy(data.get('details', {})),
            success=bool(data.get('success', True)),
            error_message=data.get('error_message'),
            processing_time_ms=float(data.get('processing_time_ms', 0.0)),
            memory_usage_bytes=int(data.get('memory_usage_bytes', 0)),
            timestamp=timestamp or datetime.now(),
            metadata=copy.deepcopy(data.get('metadata', {}))
        )
    
    def to_json(self, indent: int = 4) -> str:
        """Konwersja do JSON."""
        return json.dumps(self.to_dict(), indent=indent, ensure_ascii=False)
    
    @classmethod
    def from_json(cls, json_str: str) -> 'FeedbackEvent':
        """Utworzenie z JSON."""
        data = json.loads(json_str)
        return cls.from_dict(data)
    
    def __repr__(self) -> str:
        status = "SUCCESS" if self.success else "FAILED"
        return (f"FeedbackEvent({self.event_type.value}, "
                f"strategy='{self.strategy_id}', "
                f"{status})")


