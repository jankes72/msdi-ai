def create_prediction_outcome_from_trace_and_result(
    prediction_trace: Dict[str, Any],
    match_result: Dict[str, Any],
    strategy_id: str = ""
) -> PredictionOutcome:
    """
    Fabryka: Tworzy PredictionOutcome z PredictionTrace i MatchResult.
    
    Args:
        prediction_trace: Dane z PredictionTraceRecord
        match_result: Dane z MatchResult
        strategy_id: ID strategii (opcjonalnie)
    
    Returns:
        PredictionOutcome
    """
    # Pobierz dane predykcji
    predicted_result = prediction_trace.get('prediction', {}).get('result', '')
    predicted_confidence = prediction_trace.get('prediction', {}).get('confidence', 0.0)
    prediction_id = prediction_trace.get('prediction_id', '')
    trace_id = prediction_trace.get('trace_id', '')
    
    # Pobierz dane wyniku
    actual_result = match_result.get('result', '')
    actual_home_goals = int(match_result.get('home_goals', 0))
    actual_away_goals = int(match_result.get('away_goals', 0))
    match_id = match_result.get('match_id', '')
    
    # Stwórz outcome
    outcome = PredictionOutcome(
        prediction_trace_id=trace_id,
        prediction_id=prediction_id,
        match_id=match_id,
        strategy_id=strategy_id or prediction_trace.get('strategy_id', ''),
        prediction_data=copy.deepcopy(prediction_trace.get('prediction', {})),
        predicted_result=predicted_result,
        actual_result=actual_result,
        actual_home_goals=actual_home_goals,
        actual_away_goals=actual_away_goals,
        prediction_confidence=predicted_confidence
    )
    
    # Oblicz metryki
    outcome.calculate_scores()
    
    return outcome


def create_feedback_event(
    event_type: FeedbackEventType,
    strategy_id: str = "",
    feedback_loop_id: str = "",
    reason: str = "",
    before_state: Dict[str, Any] = None,
    event_name: str = ""
) -> FeedbackEvent:
    """
    Fabryka: Tworzy FeedbackEvent.
    
    Args:
        event_type: Typ zdarzenia
        strategy_id: ID strategii
        feedback_loop_id: ID pętli feedback
        reason: Powód zdarzenia
        before_state: Stan przed zdarzeniem
        event_name: Nazwa zdarzenia
    
    Returns:
        FeedbackEvent
    """
    return FeedbackEvent(
        event_type=event_type,
        strategy_id=strategy_id,
        feedback_loop_id=feedback_loop_id,
        reason=reason,
        before_state=copy.deepcopy(before_state) or {},
        event_name=event_name
    )


