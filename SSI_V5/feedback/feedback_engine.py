class FeedbackPipeline:
    """
    Pipeline przetwarzania pętli feedback.
    
    Określa kolejne etapy przetwarzania:
    1. Walidacja danych wejściowych
    2. Ewaluacja predykcji
    3. Obliczanie fitness
    4. Zapis do pamięci
    5. Integracja z ewolucją
    """
    
    def __init__(self):
        self.steps = []
        self.current_step = 0
    
    def add_step(self, step_name: str, step_func: Callable) -> None:
        """Dodaje nowy krok do pipeline."""
        self.steps.append((step_name, step_func))
    
    def execute(self, context: FeedbackContext) -> bool:
        """
        Wykonuje wszystkie kroki pipeline.
        
        Args:
            context: Kontekst przetwarzania
        
        Returns:
            Czy wszystkie kroki zakończyły się sukcesem
        """
        success = True
        
        for step_name, step_func in self.steps:
            try:
                context.status = f"executing_{step_name}"
                result = step_func(context)
                
                if result is False:
                    success = False
                    context.errors.append(f"Step {step_name} failed")
                    break
                    
            except Exception as e:
                success = False
                context.errors.append(f"Step {step_name} error: {str(e)}")
                break
        
        context.status = "completed" if success else "failed"
        return success


