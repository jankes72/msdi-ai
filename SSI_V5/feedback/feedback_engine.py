class FeedbackEngine:
    """
    Główny silnik feedback loop.
    
    Odpowiedzialność:
    - Orkiestracja całej pętli feedback
    - Integracja wszystkich komponentów
    - Zarządzanie stanem i pamięcią
    - Rejestracja zdarzeń
    
    Pętla feedback:
    1. Odbierz Prediction Trace i Match Result
    2. Wykonaj ewaluację (PredictionEvaluator)
    3. Oblicz fitness (StrategyFitnessCalculator)
    4. Zapisz do pamięci (Strategy Memory)
    5. Przekaż do Evolution Engine
    
    ZASADY:
    1. NIE MODYFIKUJE PRODUKCJI
    2. Tylko warstwa integracyjna
    3. Korzysta z kopii danych
    4. Izolacja od systemu produkcyjnego
    """
    
    def __init__(self, config: Optional[FeedbackConfig] = None):
        """
        Inicjalizacja silnika feedback.
        
        Args:
            config: Konfiguracja silnika (opcjonalne)
        """
        self.config = config or FeedbackConfig()
        self.config.apply_seed()
        
        # Inicjalizuj komponenty
        self._initialize_components()
        
        # Stan silnika
        self.running = False
        self._lock = RLock()
        
        # Historia
        self.contexts: Dict[str, FeedbackContext] = {}
        self.outcomes: List[PredictionOutcome] = []
        self.fitness_values: Dict[str, StrategyFitness] = {}
        self.events: List[FeedbackEvent] = []
        
        # Pipeline
        self.pipeline = FeedbackPipeline()
        self._build_pipeline()
        
        # Statystyki
        self.total_cycles = 0
        self.successful_cycles = 0
        self.failed_cycles = 0
        
        # Inicjalizuj pamięć
        self._initialize_memory()
        
        # Zarejestruj start
        self._log_event(
            FeedbackEventType.SYSTEM_INITIALIZED,
            success=True,
            reason="Feedback Engine initialized"
        )
    
    def _initialize_components(self) -> None:
        """Inicjalizuje wszystkie komponenty."""
        # Prediction Evaluator
        self.evaluator = PredictionEvaluator(name="FeedbackEngine_Evaluator")
        
        # Fitness Calculator
        self.fitness_calculator = StrategyFitnessCalculator(
            name="FeedbackEngine_FitnessCalculator",
            weights=self.config.fitness_weights,
            min_predictions_for_fitness=self.config.min_predictions_for_fitness
        )
        
        # Konfiguracja pamięci
        self.memory_path = Path(self.config.memory_dir)
        self.memory_path.mkdir(parents=True, exist_ok=True)
        
        # Zewnętrzne referencje (będą ustawiane przez connect_to_*)
        self._strategy_memory_manager = None
        self._evolution_engine = None
    
    def _build_pipeline(self) -> None:
        """Buduje pipeline przetwarzania."""
        # Krok 1: Walidacja danych wejściowych
        self.pipeline.add_step(
            "validate_input",
            self._step_validate_input
        )
        
        # Krok 2: Ewaluacja predykcji
        if self.config.enable_evaluation:
            self.pipeline.add_step(
                "evaluate_prediction",
                self._step_evaluate_prediction
            )
        
        # Krok 3: Obliczanie fitness
        if self.config.enable_fitness_calculation:
            self.pipeline.add_step(
                "calculate_fitness",
                self._step_calculate_fitness
            )
        
        # Krok 4: Zapis do pamięci
        if self.config.enable_memory_persistence:
            self.pipeline.add_step(
                "save_to_memory",
                self._step_save_to_memory
            )
        
        # Krok 5: Integracja z ewolucją
        if self.config.enable_evolution_integration:
            self.pipeline.add_step(
                "integrate_with_evolution",
                self._step_integrate_with_evolution
            )
    
    def _initialize_memory(self) -> None:
        """Inicjalizuje system pamięci."""
        # Wczytanie istniejącej pamięci feedback
        self._load_feedback_memory()
        
        # Wczytanie zdarzeń
        self._load_events_log()
    
