    # METODY GŁÓWNE
    # ========================================================================
    
    def process_feedback_cycle(
        self,
        prediction_trace: Union[Dict[str, Any], Any],
        match_result: Union[Dict[str, Any], Any],
        strategy_id: str = ""
    ) -> FeedbackContext:
        """
        Przetwarza pojedynczy cykl feedback.
        
        Cała pętla w jednym wywołaniu:
        1. Walidacja
        2. Ewaluacja
        3. Fitness
        4. Pamięć
        5. Ewolucja
        
        Args:
            prediction_trace: PredictionTraceRecord lub jego reprezentacja
            match_result: MatchResult lub jego reprezentacja
            strategy_id: ID strategii (opcjonalne)
        
        Returns:
            FeedbackContext z wynikami przetwarzania
        """
        with self._lock:
            # Utwórz kontekst
            context = FeedbackContext(
                strategy_id=strategy_id,
                prediction_trace=copy.deepcopy(prediction_trace),
                match_result=copy.deepcopy(match_result),
                start_time=datetime.now()
            )
            
            # Zapisz ID kontekstu
            context.context_id = f"ctx_{self.total_cycles}_{uuid.uuid4().hex[:8]}"
            
            # Zarejestruj początek
            self._log_event(
                FeedbackEventType.FEEDBACK_LOOP_STARTED,
                strategy_id=strategy_id,
                feedback_loop_id=context.context_id
            )
            
            # Wykonaj pipeline
            try:
                success = self.pipeline.execute(context)
                
                if success:
                    self.successful_cycles += 1
                else:
                    self.failed_cycles += 1
                
                self.total_cycles += 1
                
            except Exception as e:
                self.failed_cycles += 1
                self.total_cycles += 1
                context.errors.append(f"Pipeline execution error: {str(e)}")
                context.status = "failed"
            
            # Uaktualnij czasy
            context.end_time = datetime.now()
            if context.start_time:
                context.processing_time_ms = (
                    (context.end_time - context.start_time).total_seconds() * 1000
                )
            
            # Zapisz kontekst
            self.contexts[context.context_id] = context
            
            # Zarejestruj koniec
            self._log_event(
                FeedbackEventType.FEEDBACK_LOOP_COMPLETED,
                strategy_id=strategy_id,
                feedback_loop_id=context.context_id,
                reason=f"Status: {context.status}"
            )
            
            return context
    
    def process_batch(
        self,
        prediction_traces: List[Union[Dict[str, Any], Any]],
        match_results: List[Union[Dict[str, Any], Any]],
        strategy_ids: Optional[List[str]] = None
    ) -> List[FeedbackContext]:
        """
        Przetwarza batch cykli feedback.
        
        Args:
            prediction_traces: Lista PredictionTraceRecord
            match_results: Lista MatchResult
            strategy_ids: Lista ID strategii (opcjonalne)
        
        Returns:
            Lista FeedbackContext
        """
        if len(prediction_traces) != len(match_results):
            raise ValueError("Prediction traces and match results must have the same length")
        
        contexts = []
        
        for i, (trace, result) in enumerate(zip(prediction_traces, match_results)):
            strategy_id = strategy_ids[i] if strategy_ids else ""
            context = self.process_feedback_cycle(trace, result, strategy_id)
            contexts.append(context)
        
        return contexts
    
    # ========================================================================
    # KROKI PIPELINE
    # ========================================================================
    
    def _step_validate_input(self, context: FeedbackContext) -> bool:
        """
        Krok 1: Walidacja danych wejściowych.
        """
        # Sprawdź czy mamy dane
        if context.prediction_trace is None:
            context.errors.append("Missing prediction_trace")
            return False
        
        if context.match_result is None:
            context.errors.append("Missing match_result")
            return False
        
        # walidacja typu danych
        trace_data = self._to_dict(context.prediction_trace)
        result_data = self._to_dict(context.match_result)
        
        # WalidacjaPrediction Trace
        if 'trace_id' not in trace_data and 'prediction_id' not in trace_data:
            context.warnings.append("Prediction trace missing ID")
        
        # Walidacja Match Result
        if 'match_id' not in result_data:
            context.warnings.append("Match result missing ID")
        
        if 'home_goals' not in result_data or 'away_goals' not in result_data:
            context.errors.append("Match result missing goals")
            return False
        
        return True
    
    def _step_evaluate_prediction(self, context: FeedbackContext) -> bool:
        """
        Krok 2: Ewaluacja predykcji.
        """
        try:
            # Wykonaj ewaluację
            trace_data = self._to_dict(context.prediction_trace)
            result_data = self._to_dict(context.match_result)
            
            evaluation = self.evaluator.evaluate(trace_data, result_data)
            context.evaluation_result = evaluation
            
            # Konwertuj do PredictionOutcome
            context.prediction_outcome = evaluation.to_prediction_outcome()
            
            # Ustaw strategy_id z trace jeśli nie było ustawione
            if not context.strategy_id and evaluation.strategy_id:
                context.strategy_id = evaluation.strategy_id
            
            # Zarejestruj zdarzenie
            self._log_event(
                FeedbackEventType.EVALUATION_COMPLETED,
                strategy_id=context.strategy_id,
                feedback_loop_id=context.context_id,
                details={
                    'exact_score': evaluation.exact_score,
                    'result_correct': evaluation.result_correct,
                    'accuracy_score': evaluation.accuracy_score
                }
            )
            
            return True
            
        except Exception as e:
            context.errors.append(f"Evaluation failed: {str(e)}")
            self._log_event(
                FeedbackEventType.ERROR_PREDICTION_MISMATCH,
                strategy_id=context.strategy_id,
                error_message=str(e),
                success=False
            )
            return False
    
    def _step_calculate_fitness(self, context: FeedbackContext) -> bool:
        """
        Krok 3: Obliczanie fitness.
        """
        if context.prediction_outcome is None:
            context.errors.append("No prediction outcome for fitness calculation")
            return False
        
        try:
            # Dodaj outcome do historii
            self.outcomes.append(context.prediction_outcome)
            
            # Oblicz fitness dla strategii
            strategy_outcomes = [
                o for o in self.outcomes 
                if o.strategy_id == context.strategy_id
            ]
            
            fitness = self.fitness_calculator.calculate_fitness(
                context.strategy_id, strategy_outcomes
            )
            context.strategy_fitness = fitness
            
            # Zapisz fitness
            self.fitness_values[context.strategy_id] = fitness
            
            # Zarejestruj zdarzenie
            self._log_event(
                FeedbackEventType.FITNESS_CALCULATION_COMPLETED,
                strategy_id=context.strategy_id,
                feedback_loop_id=context.context_id,
                details={
                    'overall_fitness': fitness.overall_fitness,
                    'accuracy': fitness.accuracy,
                    'total_predictions': fitness.total_predictions
                }
            )
            
            return True
            
        except Exception as e:
            context.errors.append(f"Fitness calculation failed: {str(e)}")
            self._log_event(
                FeedbackEventType.ERROR_CALCULATION_FAILED,
                strategy_id=context.strategy_id,
                error_message=str(e),
                success=False
            )
            return False
    
    def _step_save_to_memory(self, context: FeedbackContext) -> bool:
        """
        Krok 4: Zapis do pamięci.
        """
        try:
            # Zapisz do Strategy Memory (jeśli podłączone)
            if self._strategy_memory_manager and context.prediction_outcome:
                outcome = context.prediction_outcome
                
                # Utwórz lub zaktualizuj StrategyMemoryRecord
                memory_record = self._strategy_memory_manager.get_strategy_memory(outcome.strategy_id)
                if memory_record is None:
                    # Utwórz nową pamięć jeśli nie istnieje
                    memory_record = self._strategy_memory_manager.create_strategy_memory(
                        strategy_id=outcome.strategy_id,
                        strategy_version="1.0.0"
                    )
                
                # Dodaj outcome do RESULT_HISTORY
                memory_record.RESULT_HISTORY.append(outcome.to_dict())
                
                # Zapisz do pamięci
                self._strategy_memory_manager._save_record(memory_record)
                
                # Zarejestruj zdarzenie
                self._log_event(
                    FeedbackEventType.MEMORY_SAVE_COMPLETED,
                    strategy_id=outcome.strategy_id,
                    feedback_loop_id=context.context_id
                )
            
            # Zapisz do lokalnej pamięci feedback
            self._save_feedback_memory()
            
            return True
            
        except Exception as e:
            context.errors.append(f"Memory save failed: {str(e)}")
            self._log_event(
                FeedbackEventType.ERROR_memory_FAILED,
                strategy_id=context.strategy_id,
                error_message=str(e),
                success=False
            )
            return False
    
    def _step_integrate_with_evolution(self, context: FeedbackContext) -> bool:
        """
        Krok 5: Integracja z Evolution Engine.
        """
        if self._evolution_engine is None:
            context.warnings.append("Evolution Engine not connected")
            return True  # Nie jest błąd, tylko warning
        
        try:
            if context.strategy_fitness:
                fitness = context.strategy_fitness
                
                # Przekaż fitness do Evolution Engine
                # (Implementacja zależy od API Evolution Engine)
                if hasattr(self._evolution_engine, 'update_fitness'):
                    self._evolution_engine.update_fitness(
                        strategy_id=fitness.strategy_id,
                        fitness_value=fitness.overall_fitness
                    )
                
                # Zarejestruj zdarzenie
                self._log_event(
                    FeedbackEventType.EVOLUTION_COMPLETED,
                    strategy_id=fitness.strategy_id,
                    feedback_loop_id=context.context_id,
                    details={'fitness': fitness.overall_fitness}
                )
            
            return True
            
        except Exception as e:
            context.errors.append(f"Evolution integration failed: {str(e)}")
            self._log_event(
                FeedbackEventType.ERROR_CALCULATION_FAILED,
                strategy_id=context.strategy_id,
                error_message=str(e),
                success=False
            )
            return False
    
