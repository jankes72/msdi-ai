class PredictionEvaluator:
    """
    Ewaluator predykcji.
    
    Odpowiedzialność:
    - Porównywanie Prediction Trace z Result Ingestion
    - Generowanie EvaluationResult i PredictionOutcome
    - Obsługa różnych formatów danych wejściowych
    
    ZASADY:
    1. TYLKO porównywanie - nie modyfikuje danych wejściowych
    2. Korzysta z kopii danych (deep copy)
    3. Obsługuje różne formaty predykcji i wyników
    4. Zwraca wyniku w postaci EvaluationResult i PredictionOutcome
    """
    
    def __init__(self, name: str = "PredictionEvaluator"):
        """
        Inicjalizacja ewaluatora.
        
        Args:
            name: Nazwa ewaluatora
        """
        self.name = name
        self.evaluation_count = 0
        self.events: List[FeedbackEvent] = []
        
    def evaluate(
        self,
        prediction_trace: Union[Dict[str, Any], Any],
        match_result: Union[Dict[str, Any], Any]
    ) -> EvaluationResult:
        """
        Ewaluuje predykcję w oparciu o rzeczywisty wynik.
        
        Args:
            prediction_trace: PredictionTraceRecord lub jego dict reprezentacja
            match_result: MatchResult lub jego dict reprezentacja
            
        Returns:
            EvaluationResult z Ergebnisatis ewaluacji
        """
        import time
        start_time = time.time()
        
        # Utwórz ID ewaluacji
        eval_id = f"eval_{uuid.uuid4().hex[:12]}"
        
        # Konwertuj do dict jeśli to obiekty
        trace_data = self._to_dict(prediction_trace)
        result_data = self._to_dict(match_result)
        
        # wyekstrahować dane z trace
        trace_id = trace_data.get('trace_id', '')
        prediction_id = trace_data.get('prediction_id', '')
        strategy_id = trace_data.get('strategy_id', '') or trace_data.get('metadata', {}).get('strategy_id', '')
        
        # Dane predykcji
        prediction_data = trace_data.get('prediction', {})
        predicted_result = str(prediction_data.get('result', ''))
        
        # Jeśli result jest w formacie tuple lub listy
        if isinstance(predicted_result, (list, tuple)) and len(predicted_result) >= 2:
            predicted_result = str(predicted_result[0]) if predicted_result[0] is not None else ""
        
        # Ekstrakcja goli z predykcji (jeśli dostępne)
        predicted_home = None
        predicted_away = None
        
        # Próba 1: z model_output
        model_output = prediction_data.get('model_output', {})
        if 'home_goals' in model_output:
            predicted_home = int(model_output.get('home_goals')) if model_output.get('home_goals') is not None else None
        if 'away_goals' in model_output:
            predicted_away = int(model_output.get('away_goals')) if model_output.get('away_goals') is not None else None
        
        # Próba 2: z raw_output (np. [2, 1])
        raw_output = prediction_data.get('raw_output')
        if isinstance(raw_output, (list, tuple)) and len(raw_output) >= 2:
            try:
                predicted_home = int(raw_output[0]) if raw_output[0] is not None else None
                predicted_away = int(raw_output[1]) if raw_output[1] is not None else None
            except (ValueError, TypeError):
                pass
        
        # Próba 3: z probabilities (jeśli to rozkład)
        probabilities = prediction_data.get('probabilities', {})
        if predicted_home is None or predicted_away is None:
            # Nie możemy wyekstrahować goli z probabilities
            pass
        
        # Dane wyniku
        match_id = result_data.get('match_id', '')
        actual_result = str(result_data.get('result', ''))
        actual_home = int(result_data.get('home_goals', 0))
        actual_away = int(result_data.get('away_goals', 0))
        
        # Jeśli actual_result nie jest ustawiony, ustaw go na podstawie goli
        if not actual_result:
            if actual_home > actual_away:
                actual_result = "1"
            elif actual_home < actual_away:
                actual_result = "2"
            else:
                actual_result = "X"
        
        # Utwórz obiekty ewaluacji
        exact_eval = ExactScoreEvaluation(
            predicted_home=predicted_home,
            predicted_away=predicted_away,
            actual_home=actual_home,
            actual_away=actual_away,
            confidence=prediction_data.get('confidence', 0.0)
        )
        
        result_eval = ResultEvaluation(
            predicted_result=predicted_result or "",
            actual_result=actual_result or "",
            confidence=prediction_data.get('confidence', 0.0)
        )
        
        goals_eval = GoalsEvaluation(
            predicted_home=predicted_home,
            predicted_away=predicted_away,
            actual_home=actual_home,
            actual_away=actual_away
        )
        
        # Wykonać ewaluacje
        exact_eval.evaluate()
        result_eval.evaluate()
        goals_eval.evaluate()
        
        # Ustal statusy
        is_exact = exact_eval.is_exact
        is_result_correct = result_eval.is_correct
        is_goals_correct = goals_eval.home_correct and goals_eval.away_correct
        is_total_correct = goals_eval.total_goals_correct
        
        # Ustal ogólny status ewaluacji
        if is_exact:
            status = EvaluationStatus.EXACT
        elif is_result_correct and is_goals_correct:
            status = EvaluationStatus.CORRECT
        elif is_result_correct:
            status = EvaluationStatus.PARTIAL
        elif not is_result_correct and not is_exact:
            status = EvaluationStatus.INCORRECT
        else:
            status = EvaluationStatus.UNEVALUATED
        
        # Oblicz accuracy_score
        accuracy_score = self._calculate_accuracy_score(
            is_exact, is_result_correct, is_goals_correct, is_total_correct
        )
        
        # Oblicz czas przetwarzania
        processing_time_ms = (time.time() - start_time) * 1000
        
        # Zwiększ licznik
        self.evaluation_count += 1
        
        # Zarejestruj zdarzenie
        self._log_event(
            FeedbackEventType.EVALUATION_COMPLETED,
            strategy_id=strategy_id,
            trace_id=trace_id,
            match_id=match_id,
            processing_time_ms=processing_time_ms
        )
        
        # Utwórz EvaluationResult
        evaluation_result = EvaluationResult(
            evaluation_id=eval_id,
            prediction_trace_id=trace_id,
            prediction_id=prediction_id,
            strategy_id=strategy_id,
            match_id=match_id,
            exact_score_eval=exact_eval,
            result_eval=result_eval,
            goals_eval=goals_eval,
            status=status,
            processing_time_ms=processing_time_ms,
            exact_score=is_exact,
            result_correct=is_result_correct,
            goals_correct=is_goals_correct,
            total_correct=is_total_correct,
            accuracy_score=accuracy_score
        )
        
        return evaluation_result
    
    def evaluate_batch(
        self,
        prediction_traces: List[Union[Dict[str, Any], Any]],
        match_results: List[Union[Dict[str, Any], Any]]
    ) -> List[EvaluationResult]:
        """
        Ewaluuje many predykcji w partii.
        
        Args:
            prediction_traces: Lista PredictionTraceRecord
            match_results: Lista MatchResult
            
        Returns:
            Lista EvaluationResult
        """
        if len(prediction_traces) != len(match_results):
            raise ValueError("Prediction traces and match results must have the same length")
        
        results = []
        for i, (trace, result) in enumerate(zip(prediction_traces, match_results)):
            try:
                eval_result = self.evaluate(trace, result)
                results.append(eval_result)
            except Exception as e:
                # Zarejestruj błąd
                trace_data = self._to_dict(trace)
                result_data = self._to_dict(result)
                trace_id = trace_data.get('trace_id', f'trace_{i}')
                match_id = result_data.get('match_id', f'result_{i}')
                
                self._log_event(
                    FeedbackEventType.ERROR_PREDICTION_MISMATCH,
                    strategy_id=trace_data.get('strategy_id', ''),
                    trace_id=trace_id,
                    match_id=match_id,
                    error_message=str(e),
                    success=False
                )
                
                # Utwórz pusty EvaluationResult z błędem
                error_result = EvaluationResult(
                    evaluation_id=f"eval_{uuid.uuid4().hex[:12]}",
                    prediction_trace_id=trace_id,
                    match_id=match_id,
                    status=EvaluationStatus.UNEVALUATED,
                    accuracy_score=0.0
                )
                error_resultGoals_eval = error_result
                results.append(error_result)
        
        return results
    
    def evaluate_to_outcome(
        self,
        prediction_trace: Union[Dict[str, Any], Any],
        match_result: Union[Dict[str, Any], Any]
    ) -> PredictionOutcome:
        """
        Ewaluuje i zwraca PredictionOutcome.
        
        Args:
            prediction_trace: PredictionTraceRecord lub jego dict
            match_result: MatchResult lub jego dict
            
        Returns:
            PredictionOutcome
        """
        eval_result = self.evaluate(prediction_trace, match_result)
        return eval_result.to_prediction_outcome()
    
    def _calculate_accuracy_score(
        self,
        is_exact: bool,
        is_result_correct: bool,
        is_goals_correct: bool,
        is_total_correct: bool
    ) -> float:
        """
        Oblicza accuracy_score (0.0 - 1.0) na podstawie ocen.
        
        Wagi:
        - Dokładny wynik: 0.40
        - Poprawny typ wyniku: 0.30
        - Poprawne gole: 0.20
        - Poprawna łączna liczba goli: 0.10
        """
        score = 0.0
        
        if is_exact:
            score += 0.40
        
        if is_result_correct:
            score += 0.30
        
        if is_goals_correct:
            score += 0.20
        
        if is_total_correct:
            score += 0.10
        
        return min(1.0, score)
    
    def _to_dict(self, obj: Union[Dict[str, Any], Any]) -> Dict[str, Any]:
        """
        Konwertuje obiekt do dict.
        """
        if isinstance(obj, dict):
            return copy.deepcopy(obj)
        elif hasattr(obj, 'to_dict'):
            return obj.to_dict()
        elif hasattr(obj, '__dict__'):
            return copy.deepcopy(obj.__dict__)
        else:
            return {}
    
    def _log_event(
        self,
        event_type: FeedbackEventType,
        strategy_id: str = "",
        trace_id: str = "",
        match_id: str = "",
        processing_time_ms: float = 0.0,
        error_message: str = "",
        success: bool = True
    ) -> FeedbackEvent:
        """
        Rejestruje zdarzenie ewaluacji.
        """
        event = FeedbackEvent(
            event_type=event_type,
            strategy_id=strategy_id,
            feedback_loop_id=f"eval sess_{self.evaluation_count}",
            reason=f"Evaluation of trace {trace_id} with result {match_id}",
            before_state={'trace_id': trace_id, 'match_id': match_id},
            event_name=f"{event_type.value}_{self.evaluation_count}",
            processing_time_ms=processing_time_ms,
            success=success,
            error_message=error_message
        )
        
        self.events.append(event)
        return event
    
    def get_statistics(self) -> Dict[str, Any]:
        """
        Pobiera statystyki ewaluacji.
        
        Returns:
            Statystyki ewaluacji
        """
        total = self.evaluation_count
        success_count = sum(1 for e in self.events if e.success)
        error_count = sum(1 for e in self.events if not e.success)
        
        return {
            'total_evaluations': total,
            'success_count': success_count,
            'error_count': error_count,
            'success_rate': (success_count / total * 100) if total > 0 else 0.0,
            'events': [e.get_summary() for e in self.events]
        }
    
    def reset(self) -> None:
        """Resetuje ewaluator."""
        self.evaluation_count = 0
        self.events = []


