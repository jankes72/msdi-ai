@dataclass
class ExactScoreEvaluation:
    """Ocena dokładnego wyniku (np. 2:1 == 2:1)."""
    predicted_home: Optional[int] = None
    predicted_away: Optional[int] = None
    actual_home: int = 0
    actual_away: int = 0
    is_exact: bool = False
    confidence: float = 0.0
    
    def evaluate(self) -> None:
        """Ocenia czy wynik jest dokładny."""
        if self.predicted_home is not None and self.predicted_away is not None:
            self.is_exact = (
                self.predicted_home == self.actual_home and
                self.predicted_away == self.actual_away
            )
        else:
            self.is_exact = False
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do słownika."""
        return {
            'predicted_home': self.predicted_home,
            'predicted_away': self.predicted_away,
            'actual_home': self.actual_home,
            'actual_away': self.actual_away,
            'is_exact': self.is_exact,
            'confidence': self.confidence
        }


@dataclass
class ResultEvaluation:
    """Ocena typu wyniku (1/X/2)."""
    predicted_result: str = ""  # "1", "X", "2"
    actual_result: str = ""    # "1", "X", "2"
    is_correct: bool = False
    confidence: float = 0.0
    
    def evaluate(self) -> None:
        """Ocenia czy typ wyniku jest poprawny."""
        if self.predicted_result and self.actual_result:
            self.is_correct = self.predicted_result == self.actual_result
        else:
            self.is_correct = False
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do słownika."""
        return {
            'predicted_result': self.predicted_result,
            'actual_result': self.actual_result,
            'is_correct': self.is_correct,
            'confidence': self.confidence
        }


@dataclass
class GoalsEvaluation:
    """Ocena具体 goli."""
    predicted_home: Optional[int] = None
    predicted_away: Optional[int] = None
    actual_home: int = 0
    actual_away: int = 0
    home_correct: bool = False
    away_correct: bool = False
    total_goals_predicted: Optional[int] = None
    total_goals_actual: int = 0
    total_goals_correct: bool = False
    
    def evaluate(self) -> None:
        """Ocenia trafnosc goli."""
        self.home_correct = (self.predicted_home is not None and 
                          self.predicted_home == self.actual_home)
        self.away_correct = (self.predicted_away is not None and 
                          self.predicted_away == self.actual_away)
        
        # Czy przewidzianołączną liczbę goli
        if self.predicted_home is not None and self.predicted_away is not None:
            predicted_total = self.predicted_home + self.predicted_away
            actual_total = self.actual_home + self.actual_away
            self.total_goals_predicted = predicted_total
            self.total_goals_actual = actual_total
            self.total_goals_correct = predicted_total == actual_total
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do słownika."""
        return {
            'predicted_home': self.predicted_home,
            'predicted_away': self.predicted_away,
            'actual_home': self.actual_home,
            'actual_away': self.actual_away,
            'home_correct': self.home_correct,
            'away_correct': self.away_correct,
            'total_goals_predicted': self.total_goals_predicted,
            'total_goals_actual': self.total_goals_actual,
            'total_goals_correct': self.total_goals_correct
        }


@dataclass
class EvaluationResult:
    """
    Kompletny wynik ewaluacji predykcji.
    
    Zawiera:
    - Ocena dokładnego wyniku
    - Ocena typu wyniku  
    - Ocena goli
    - Ogólna ocena
    """
    evaluation_id: str = field(default_factory=lambda: f"eval_{uuid.uuid4().hex[:12]}")
    
    # Predykcja
    prediction_trace_id: str = ""
    prediction_id: str = ""
    strategy_id: str = ""
    
    # Wynik
    match_id: str = ""
    
    # Ewaluacje
    exact_score_eval: ExactScoreEvaluation = field(default_factory=ExactScoreEvaluation)
    result_eval: ResultEvaluation = field(default_factory=ResultEvaluation)
    goals_eval: GoalsEvaluation = field(default_factory=GoalsEvaluation)
    
    # Status
    status: EvaluationStatus = EvaluationStatus.PENDING
    timestamp: datetime = field(default_factory=datetime.now)
    processing_time_ms: float = 0.0
    
    # Metryki
    exact_score: bool = False
    result_correct: bool = False
    goals_correct: bool = False
    total_correct: bool = False
    accuracy_score: float = 0.0
    
    # Konwersja do PredictionOutcome
    def to_prediction_outcome(self) -> PredictionOutcome:
        """Konwertuje EvaluationResult do PredictionOutcome."""
        outcome = PredictionOutcome(
            prediction_trace_id=self.prediction_trace_id,
            prediction_id=self.prediction_id,
            match_id=self.match_id,
            strategy_id=self.strategy_id,
            predicted_result=self.result_eval.predicted_result,
            predicted_home_goals=self.goals_eval.predicted_home,
            predicted_away_goals=self.goals_eval.predicted_away,
            actual_result=self.result_eval.actual_result,
            actual_home_goals=self.goals_eval.actual_home,
            actual_away_goals=self.goals_eval.actual_away,
            exact_score=self.exact_score,
            result_correct=self.result_correct,
            goals_correct=self.goals_correct,
            accuracy_score=self.accuracy_score,
            evaluation_status=self.status
        )
        return outcome
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do słownika."""
        return {
            'evaluation_id': self.evaluation_id,
            'prediction_trace_id': self.prediction_trace_id,
            'prediction_id': self.prediction_id,
            'strategy_id': self.strategy_id,
            'match_id': self.match_id,
            'exact_score_eval': self.exact_score_eval.to_dict(),
            'result_eval': self.result_eval.to_dict(),
            'goals_eval': self.goals_eval.to_dict(),
            'status': self.status.value,
            'timestamp': self.timestamp.isoformat(),
            'processing_time_ms': self.processing_time_ms,
            'exact_score': self.exact_score,
            'result_correct': self.result_correct,
            'goals_correct': self.goals_correct,
            'total_correct': self.total_correct,
            'accuracy_score': self.accuracy_score
        }
    
    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> 'EvaluationResult':
        """Utworzenie z słownika."""
        timestamp = data.get('timestamp')
        if isinstance(timestamp, str):
            timestamp = datetime.fromisoformat(timestamp)
        
        return cls(
            evaluation_id=data.get('evaluation_id', f"eval_{uuid.uuid4().hex[:12]}"),
            prediction_trace_id=data.get('prediction_trace_id', ''),
            prediction_id=data.get('prediction_id', ''),
            strategy_id=data.get('strategy_id', ''),
            match_id=data.get('match_id', ''),
            exact_score_eval=ExactScoreEvaluation(**data.get('exact_score_eval', {})),
            result_eval=ResultEvaluation(**data.get('result_eval', {})),
            goals_eval=GoalsEvaluation(**data.get('goals_eval', {})),
            status=EvaluationStatus(data.get('status', 'pending')),
            timestamp=timestamp or datetime.now(),
            processing_time_ms=float(data.get('processing_time_ms', 0.0)),
            exact_score=bool(data.get('exact_score', False)),
            result_correct=bool(data.get('result_correct', False)),
            goals_correct=bool(data.get('goals_correct', False)),
            total_correct=bool(data.get('total_correct', False)),
            accuracy_score=float(data.get('accuracy_score', 0.0))
        )


