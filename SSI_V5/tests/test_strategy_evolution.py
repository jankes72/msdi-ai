class TestAcceptanceCriteria:
    """Testy weryfikacji kryteriów akceptacji"""
    
    def test_criteria_01_creating_genome(self, mutation_engine):
        """Kryterium 1: Tworzenie genomu strategii"""
        genome = mutation_engine.create_genome_from_strategy(
            strategy_id="test_strategy",
            parameters={'param1': 1.0, 'param2': 2.0}
        )
        
        assert genome is not None
        assert genome.strategy_id == "test_strategy"
        assert len(genome.parameters) == 2
        assert len(genome.genes) == 2
    
    def test_criteria_02_mutation(self, mutation_engine):
        """Kryterium 2: Mutacja strategii"""
        genome = mutation_engine.create_genome_from_strategy(
            strategy_id="test_strategy",
            parameters={'value': 1.0}
        )
        
        child, record = mutation_engine.mutate_genome(genome.genome_id)
        
        assert child is not None
        assert child.genome_id != genome.genome_id
        assert record.evolution_type == EvolutionType.MUTATION
    
    def test_criteria_03_parent_child_relationship(self, mutation_engine):
        """Kryterium 3: Zachowanie parent-child relationship"""
        parent = mutation_engine.create_genome_from_strategy(
            strategy_id="test_strategy",
            parameters={'value': 1.0}
        )
        
        child, record = mutation_engine.mutate_genome(parent.genome_id)
        
        assert child.parent_genome_id == parent.genome_id
        assert record.parent_genome_id == parent.genome_id
        assert record.child_genome_id == child.genome_id
    
    def test_criteria_04_ranking(self, mutation_engine):
        """Kryterium 4: Ranking populacji"""
        population = StrategyPopulation()
        
        for i in range(5):
            genome = mutation_engine.create_genome_from_strategy(
                strategy_id="test_strategy",
                parameters={'value': float(i)}
            )
            genome.fitness_score = float(i)
            population.add_genome(genome)
        
        ranked = population.rank_genomes()
        
        assert len(ranked) == 5
        assert ranked[0][1] > ranked[4][1]  # Najlepszy > Najgorszy
    
    def test_criteria_05_history_saving(self, mutation_engine):
        """Kryterium 5: Zapis historii ewolucji"""
        genome = mutation_engine.create_genome_from_strategy(
            strategy_id="test_strategy",
            parameters={'value': 1.0}
        )
        
        child, record = mutation_engine.mutate_genome(genome.genome_id)
        
        # Sprawdz, czy rekordy sa zachowane
        records = mutation_engine.get_mutation_records()
        assert len(records) >= 1
        
        # Sprawdz, czy historia ewolucji jest zachowana
        history = mutation_engine.get_evolution_history("test_strategy")
        assert history is not None
        assert len(history.records) >= 1
    
    def test_criteria_06_isolation(self, mutation_engine):
        """Kryterium 6: Izolacja od produkcji"""
        genome = mutation_engine.create_genome_from_strategy(
            strategy_id="production_strategy",
            parameters={'important_param': 1.0}
        )
        
        child, _ = mutation_engine.mutate_genome(genome.genome_id)
        
        # Zmodyfikuj child
        mutation_engine.set_fitness(child.genome_id, 100.0)
        child = mutation_engine.get_genome(child.genome_id)
        child.parameters['important_param'] = 2.0
        mutation_engine.genomes[child.genome_id] = child
        
        # Oryginalny genom powinien pozostac niezmieniony
        original = mutation_engine.get_genome(genome.genome_id)
        assert original.parameters['important_param'] == 1.0
        assert original.fitness_score == 0.0
    
