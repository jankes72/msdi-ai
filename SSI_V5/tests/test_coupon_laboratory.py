class TestCouponLaboratoryEdgeCases:
    """Testy przypadków brzegowych"""
    
    def test_empty_laboratory(self, coupon_lab):
        """Test pustego laboratorium"""
        history = coupon_lab.get_history()
        assert history == []
        
        stats = coupon_lab.get_statistics()
        assert stats['total_experiments'] == 0
    
    def test_duplicate_coupon_id(self, coupon_lab):
        """Test zduplikowanego coupon_id"""
        trace_ids = ["ptr_001"]
        selection_rules = {'min_confidence': 0.7}
        
        exp1 = coupon_lab.create_experiment(
            prediction_trace_ids=trace_ids,
            strategy_id="strategy_1",
            strategy_version="1.0.0",
            selection_rules=selection_rules
        )
        
        # Próba utworzenia drugiego eksperymentu z tymi samymi parametrami
        exp2 = coupon_lab.create_experiment(
            prediction_trace_ids=trace_ids,
            strategy_id="strategy_1",
            strategy_version="1.0.0",
            selection_rules=selection_rules
        )
        
        # Powinny zwrocic ten sam eksperyment (reprodukowalnosc)
        assert exp1.coupon_id == exp2.coupon_id
    
    def test_concurrent_modification(self, coupon_lab):
        """Test modyfikacji konkurentnej"""
        exp = coupon_lab.create_experiment(
            prediction_trace_ids=["ptr_001"],
            strategy_id="strategy_1"
        )
        
        # Modyfikuj i zapisz wielokrotnie
        for i in range(5):
            exp.expected_value = float(i)
            coupon_lab.save_experiment(exp)
        
        # Sprawdz ostatnia wartosc
        loaded_exp = coupon_lab.load_experiment(exp.coupon_id)
        assert loaded_exp.expected_value == 4.0
    
    def test_special_characters_in_metadata(self, coupon_lab):
        """Test specjalnych znakow w metadanych"""
        special_chars = r'@#$%^&*()_+-=[]{}|;:",.<>?/'
        exp = coupon_lab.create_experiment(
            prediction_trace_ids=["ptr_001"],
            strategy_id="strategy_1",
            metadata={
                'notes': 'Test z polskimi znakami: ąĘŁŃÓŚŹŻ',
                'special': special_chars
            }
        )
        
        coupon_lab.save_experiment(exp)
        loaded_exp = coupon_lab.load_experiment(exp.coupon_id)
        
        assert loaded_exp.metadata['notes'] == 'Test z polskimi znakami: ąĘŁŃÓŚŹŻ'
        assert loaded_exp.metadata['special'] == special_chars
