    def get_score_candidate(self, score: str) -> Optional[ExactScoreCandidate]:
        """Pobierz kandydata dla danego wyniku"""
        for candidate in self.candidates:
            if candidate.score == score:
                return candidate
        return None
    
    def get_group_by_type(self, group_type: ScoreGroupType) -> Optional[ScoreGroup]:
        """Pobierz grupę po typie"""
        for group in self.score_groups:
            if group.group_type == group_type:
                return group
        return None


