class ScoreEvidence:
    """
    Dowód dla wyniku - numpy sprawdzenia wszyskich źródeł
    
    Przechowuje pełną ewidencję dla jednego wyniku:
    - WORLD (level_1, level_2, full_group) z uwzględnieniem wielkości próbek
    - MARKET (prawdopodobieństwo z kursów bukmacherskich)
    - POISSON (prawdopodobieństwo z modelu Poisson Dixon Coles)
    """
    
    score: str  # Wynik w formacie "X:Y"
    
    # WORLD Evidence
    world_level_1: Optional[WorldLevelEvidence] = None
    world_level_2: Optional[WorldLevelEvidence] = None
    world_full_group: Optional[WorldLevelEvidence] = None
    
    # MARKET Evidence
    market_probability: Optional[float] = None
    
    # POISSON Evidence
    poisson_probability: Optional[float] = None
    
    def __post_init__(self):
        """Walidacja danych"""
        if self.score not in VALID_SCORES:
            raise ValueError(f"Score {self.score} not in VALID_SCORES")
        
        # Walidacja prawdopodobieństw
        for prob in [self.market_probability, self.poisson_probability]:
            if prob is not None and (prob < 0 or prob > 100):
                raise ValueError(f"Probability must be between 0-100, got {prob}")
    
    @property
    def world_weighted_average(self) -> Optional[float]:
        """
        Średnia ważona po wszystkich poziomach WORLD
        Waga = liczba przypadków (sample_count)
        """
        levels = [
            self.world_level_1,
            self.world_level_2,
            self.world_full_group
        ]
        
        valid_levels = [l for l in levels if l is not None]
        if not valid_levels:
            return None
        
        total_weight = sum(l.sample_count for l in valid_levels)
        if total_weight == 0:
            return None
            
        weighted_sum = sum(l.percentage * l.sample_count for l in valid_levels)
        return weighted_sum / total_weight
    
    @property
    def world_max_samples(self) -> int:
        """Maksymalna liczba przypadków spośród poziomów WORLD"""
        samples = []
        if self.world_level_1:
            samples.append(self.world_level_1.sample_count)
        if self.world_level_2:
            samples.append(self.world_level_2.sample_count)
        if self.world_full_group:
            samples.append(self.world_full_group.sample_count)
        
        return max(samples) if samples else 0
    
    @property
    def world_min_samples(self) -> int:
        """Minimalna liczba przypadków spośród poziomów WORLD"""
        samples = []
        if self.world_level_1:
            samples.append(self.world_level_1.sample_count)
        if self.world_level_2:
            samples.append(self.world_level_2.sample_count)
        if self.world_full_group:
            samples.append(self.world_full_group.sample_count)
        
        return min(samples) if samples else 0
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do dict"""
        return {
            "score": self.score,
            "world": {
                "level_1": self.world_level_1.to_dict() if self.world_level_1 else None,
                "level_2": self.world_level_2.to_dict() if self.world_level_2 else None,
                "full_group": self.world_full_group.to_dict() if self.world_full_group else None,
            },
            "market": {
                "probability": self.market_probability
            },
            "poisson": {
                "probability": self.poisson_probability
            },
            "world_weighted_average": self.world_weighted_average,
            "world_samples": {
                "max": self.world_max_samples,
                "min": self.world_min_samples
            }
        }


