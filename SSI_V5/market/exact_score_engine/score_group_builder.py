@dataclass
class GroupScore:
    """
    Wynik z przypisanym confidence w grupie
    
    Zawiera dodatkowe metryki używane do obliczenia group_confidence
    """
    score: str                           # Wynik (np. "1:0")
    confidence: float = 0.0              # Pewność z Confidence Engine
    market_probability: float = 0.0    # Prawdopodobieństwo rynkowe (%)
    world_probability: float = 0.0     # Prawdopodobieństwo WORLD (%)
    sample_count: int = 0               # Liczba przypadków
    poisson_probability: float = 0.0   # Prawdopodobieństwo Poisson (%)
    
    def __post_init__(self):
        """Walidacja"""
        if self.score not in VALID_SCORES:
            raise ValueError(f"Score {self.score} not in VALID_SCORES")
        
        for attr in ['confidence', 'market_probability', 'world_probability', 'poisson_probability']:
            value = getattr(self, attr)
            if not isinstance(value, (int, float)) or value < 0:
                raise ValueError(f"{attr} must be >= 0, got {value}")
    
    def weighted_value(self) -> float:
        """Oblicz wartość ważoną dla grupowania"""
        return (self.confidence * GROUP_CONFIDENCE_WEIGHTS["confidence"] +
                self.market_probability * GROUP_CONFIDENCE_WEIGHTS["market_probability"] +
                (math.log10(self.sample_count + 1) / math.log10(5001)) * GROUP_CONFIDENCE_WEIGHTS["sample_strength"])
    
    def to_dict(self) -> Dict[str, Any]:
        """Serializacja do dict"""
        return {
            "score": self.score,
            "confidence": self.confidence,
            "market_probability": self.market_probability,
            "world_probability": self.world_probability,
            "sample_count": self.sample_count,
            "poisson_probability": self.poisson_probability
        }


@dataclass
class ScoreGroup:
    """
    Grupa strategiczna wyników
    
    Zawiera:
    - Identyfikator grupy
    - Listę wyników z metrykami
    - Metryki grupy
    """
    group_type: ScoreGroupType        # Typ grupy
    name: str                         # Nazwa grupy
    description: str                  # Opis
    scores: List[GroupScore] = field(default_factory=list)  # Wyniki w grupie
    
    # Metryki grupy
    group_confidence: float = 0.0    # Średnia ważona confidence
    total_sample_count: int = 0      # Całkowita liczba przypadków
    average_confidence: float = 0.0 # Średnia confidence
    quality: GroupQuality = GroupQuality.AVERAGE
    
    # Ranking
    rank: int = 0
    
    def __post_init__(self):
        """Obliczenia po inicjalizacji"""
        if self.scores:
            self._calculate_metrics()
    
    def _calculate_metrics(self):
        """Oblicz metryki grupy"""
        # Całkowita liczba przypadków
        self.total_sample_count = sum(s.sample_count for s in self.scores)
        
        # Średnia confidence
        if self.scores:
            self.average_confidence = sum(s.confidence for s in self.scores) / len(self.scores)
        
        # Group confidence (średnia ważona)
        if self.scores:
            weighted_sum = sum(s.weighted_value() for s in self.scores)
            self.group_confidence = weighted_sum / len(self.scores)
        
        # Klassfikacja jakości
        self.quality = self._classify_quality()
    
    def _classify_quality(self) -> GroupQuality:
        """Klasyfikuj jakość grupy"""
        if self.group_confidence >= 0.90:
            return GroupQuality.EXCELLENT
        elif self.group_confidence >= 0.80:
            return GroupQuality.VERY_GOOD
        elif self.group_confidence >= 0.70:
            return GroupQuality.GOOD
        elif self.group_confidence >= 0.60:
            return GroupQuality.AVERAGE
        elif self.group_confidence >= 0.50:
            return GroupQuality.BELOW_AVERAGE
        else:
            return GroupQuality.WEAK
    
    def add_score(self, group_score: GroupScore):
        """Dodaj wynik do grupy"""
        self.scores.append(group_score)
        self._calculate_metrics()
    
    def get_score(self, score: str) -> Optional[GroupScore]:
        """Pobierz GroupScore dla danego wyniku"""
        for gs in self.scores:
            if gs.score == score:
                return gs
        return None
    
    def to_dict(self) -> Dict[str, Any]:
        """Serializacja do dict"""
        return {
            "group_type": self.group_type.value,
            "name": self.name,
            "description": self.description,
            "scores": [s.to_dict() for s in self.scores],
            "metrics": {
                "group_confidence": self.group_confidence,
                "average_confidence": self.average_confidence,
                "total_sample_count": self.total_sample_count,
                "quality": self.quality.value
            },
            "rank": self.rank
        }


@dataclass
class ScoreGroupCollection:
    """
    Kolekcja wszystkich grup dla meczu
    
    Zawiera wszystkie ScoreGroup dla danego meczu
    """
    match_id: str
    groups: Dict[ScoreGroupType, ScoreGroup] = field(default_factory=dict)
    
    # Statystyki
    total_groups: int = 0
    best_group: Optional[ScoreGroup] = None
    groups_by_quality: Dict[GroupQuality, List[ScoreGroupType]] = field(default_factory=dict)
    
    def __post_init__(self):
        """Obliczenia"""
        self.total_groups = len(self.groups)
        self._index_by_quality()
        self._rank_groups()
    
    def _index_by_quality(self):
        """Indeksowanie grup po jakości"""
        for group_type, group in self.groups.items():
            quality = group.quality
            if quality not in self.groups_by_quality:
                self.groups_by_quality[quality] = []
            self.groups_by_quality[quality].append(group_type)
    
    def _rank_groups(self):
        """Ranking grup po group_confidence"""
        sorted_groups = sorted(
            self.groups.values(),
            key=lambda g: (g.group_confidence, g.total_sample_count),
            reverse=True
        )
        for rank, group in enumerate(sorted_groups, 1):
            group.rank = rank
        
        if sorted_groups:
            self.best_group = sorted_groups[0]
    
    def get_group(self, group_type: ScoreGroupType) -> Optional[ScoreGroup]:
        """Pobierz grupę po typie"""
        return self.groups.get(group_type)
    
    def get_best_groups(self, n: int = 3) -> List[ScoreGroup]:
        """Pobierz N najlepszych grup"""
        sorted_groups = sorted(
            self.groups.values(),
            key=lambda g: (g.group_confidence, g.total_sample_count),
            reverse=True
        )
        return sorted_groups[:n]
    
    def get_groups_by_category(self, category: str) -> List[ScoreGroup]:
        """Pobierz grupy po kategorii"""
        result = []
        for group_type, group in self.groups.items():
            if GROUP_DEFINITIONS[group_type]["category"] == category:
                result.append(group)
        return result
    
    def to_dict(self) -> Dict[str, Any]:
        """Serializacja do dict"""
        return {
            "match_id": self.match_id,
            "total_groups": self.total_groups,
            "groups": {gtype.value: group.to_dict() for gtype, group in self.groups.items()},
            "best_group": self.best_group.to_dict() if self.best_group else None,
            "statistics": {
                "by_quality": {
                    q.value: [gt.value for gt in gtypes]
                    for q, gtypes in self.groups_by_quality.items()
                }
            }
        }
    
    def to_json(self, indent: int = 2) -> str:
        """Serializacja do JSON"""
        import json
        return json.dumps(self.to_dict(), indent=indent, ensure_ascii=False)


