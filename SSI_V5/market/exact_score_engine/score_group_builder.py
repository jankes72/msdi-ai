class ScoreGroupBuilder:
    """
    Budowniczy grup wyników
    
    Odpowiedzialność:
    - Klasyfikacja wyników do grup
    - Obliczanie metryki grupowych
    - Tworzenie ScoreGroup i ScoreGroupCollection
    """
    
    def __init__(self, confidence_engine: Optional[ConfidenceEngine] = None):
        """
        Inicjalizacja
        
        Args:
            confidence_engine: Opcjonalny Confidence Engine
        """
        self.confidence_engine = confidence_engine or ConfidenceEngine()
        logger.info("[ScoreGroupBuilder] Inicjalizacja")
    
    def extract_group_score(self, candidate: ExactScoreCandidate) -> GroupScore:
        """
        Wyekstraktuj GroupScore z ExactScoreCandidate
        
        Args:
            candidate: Kandydat wyniku
            
        Returns:
            GroupScore
        """
        evidence = candidate.evidence
        
        # Wyekstraktuj confidence jako float
        # candidate.confidence może być ConfidenceLevel lub float
        if isinstance(candidate.confidence, ConfidenceLevel):
            # Mapowanie ConfidenceLevel na float
            confidence_map = {
                ConfidenceLevel.CRITICAL: 0.2,
                ConfidenceLevel.LOW: 0.4,
                ConfidenceLevel.MEDIUM: 0.7,
                ConfidenceLevel.HIGH: 0.85,
                ConfidenceLevel.VERY_HIGH: 0.95
            }
            confidence_value = confidence_map.get(candidate.confidence, 0.5)
        else:
            confidence_value = float(candidate.confidence)
        
        # Pobierz world_probability z evidence
        world_pct = evidence.world_weighted_average or 0.0
        
        return GroupScore(
            score=candidate.score,
            confidence=confidence_value,
            market_probability=candidate.market_probability * 100,  # Konwersja na %
            world_probability=world_pct,
            sample_count=evidence.world_max_samples,
            poisson_probability=(candidate.poisson_probability * 100) if hasattr(candidate, 'poisson_probability') else 0.0
        )
    
    def classify_score(self, score: str) -> List[ScoreGroupType]:
        """
        Klasyfikuj wynik do typów grup
        
        Args:
            score: Wynik w formacie "X:Y"
            
        Returns:
            Lista typów grup, do których należy wynik
        """
        home, away = self._parse_score(score)
        groups = []
        
        # HOME_DOMINANCE
        if score in GROUP_DEFINITIONS[ScoreGroupType.HOME_DOMINANCE]["score_patterns"]:
            groups.append(ScoreGroupType.HOME_DOMINANCE)
        
        # AWAY_DOMINANCE  
        if score in GROUP_DEFINITIONS[ScoreGroupType.AWAY_DOMINANCE]["score_patterns"]:
            groups.append(ScoreGroupType.AWAY_DOMINANCE)
        
        # DRAW_LOW_SCORE
        if score in GROUP_DEFINITIONS[ScoreGroupType.DRAW_LOW_SCORE]["score_patterns"]:
            groups.append(ScoreGroupType.DRAW_LOW_SCORE)
        
        # HIGH_SCORE
        if score in GROUP_DEFINITIONS[ScoreGroupType.HIGH_SCORE]["score_patterns"]:
            groups.append(ScoreGroupType.HIGH_SCORE)
        
        # SAFE_RESULTS
        if score in GROUP_DEFINITIONS[ScoreGroupType.SAFE_RESULTS]["score_patterns"]:
            groups.append(ScoreGroupType.SAFE_RESULTS)
        
        # OFFENSIVE
        if score in GROUP_DEFINITIONS[ScoreGroupType.OFFENSIVE]["score_patterns"]:
            groups.append(ScoreGroupType.OFFENSIVE)
        
        return groups
    
    def _parse_score(self, score: str) -> Tuple[int, int]:
        """Parsuj wynik na home:away"""
        parts = score.split(":")
        return int(parts[0]), int(parts[1])
    
    def _get_score_category(self, score: str) -> str:
        """Okrel_category wyniku"""
        home, away = self._parse_score(score)
        
        if home > away:
            return "home"
        elif away > home:
            return "away"
        else:
            return "draw"
    
    def build_group(self, group_type: ScoreGroupType, candidates: List[ExactScoreCandidate]) -> ScoreGroup:
        """
        Utwórz pojedynczą grupę
        
        Args:
            group_type: Typ grupy
            candidates: Lista kandydatów należących do grupy
            
        Returns:
            ScoreGroup
        """
        definition = GROUP_DEFINITIONS[group_type]
        
        group_scores = []
        for candidate in candidates:
            group_scores.append(self.extract_group_score(candidate))
        
        return ScoreGroup(
            group_type=group_type,
            name=definition["name"],
            description=definition["description"],
            scores=group_scores
        )
    
    def build_groups_from_candidates(
        self,
        candidates: List[ExactScoreCandidate]
    ) -> ScoreGroupCollection:
        """
        Utwórz grupy z listy kandydatów
        
        Args:
            candidates: Lista ExactScoreCandidate
            
        Returns:
            ScoreGroupCollection
        """
        #ိわけLesz kandydaci po typach grup
        groups_dict = {gtype: [] for gtype in ScoreGroupType}
        
        for candidate in candidates:
            #lasyfikuj kandidata do grup
            group_types = self.classify_score(candidate.score)
            for gtype in group_types:
                groups_dict[gtype].append(candidate)
        
        # Twórz grupy
        groups = {}
        for gtype, gtype_candidates in groups_dict.items():
            if gtype_candidates:  # Tylko niepuste grupy
                group = self.build_group(gtype, gtype_candidates)
                groups[gtype] = group
        
        # Utwórz kolekcję
        collection = ScoreGroupCollection(
            match_id=candidates[0].evidence.score if candidates else "unknown",
            groups=groups
        )
        
        return collection
    
    def build_groups_from_knowledge(
        self,
        knowledge: ExactScoreKnowledge
    ) -> ScoreGroupCollection:
        """
        Utwórz grupy z ExactScoreKnowledge
        
        Args:
            knowledge: Obiekt ExactScoreKnowledge
            
        Returns:
            ScoreGroupCollection
        """
        return self.build_groups_from_candidates(knowledge.candidates)
    
    def build_groups(
        self,
        match_id: str,
        candidates: Optional[List[ExactScoreCandidate]] = None,
        knowledge: Optional[ExactScoreKnowledge] = None
    ) -> ScoreGroupCollection:
        """
        Główna funkcja - utwórz grupy dla meczu
        
        Args:
            match_id: Identyfikator meczu
            candidates: Opcjonalna lista kandydatów
            knowledge: Opcjonalny ExactScoreKnowledge
            
        Returns:
            ScoreGroupCollection
        """
        if knowledge:
            return self.build_groups_from_knowledge(knowledge)
        
        if candidates:
            return self.build_groups_from_candidates(candidates)
        
        # Jeśli nic nie podano, spróbuj pobrać dane
        # To jest fallback - w rzeczywistości należy dostarczyć dane
        raise ValueError("Musisz podać candidates lub knowledge")
    
    def build_balanced_group(
        self,
        candidates: List[ExactScoreCandidate],
        threshold: float = 0.7
    ) -> Optional[ScoreGroup]:
        """
        Utwórz grupę BALANCED_SCORE z wyników o najwyższej zgodności
        
        Args:
            candidates: Lista kandydatów
            threshold: Minimalny confidence do włączenia
            
        Returns:
            ScoreGroup lub None
        """
        # Mapowanie ConfidenceLevel na float
        confidence_map = {
            ConfidenceLevel.CRITICAL: 0.2,
            ConfidenceLevel.LOW: 0.4,
            ConfidenceLevel.MEDIUM: 0.7,
            ConfidenceLevel.HIGH: 0.85,
            ConfidenceLevel.VERY_HIGH: 0.95
        }
        
        # Filtrowanie wyników z wysokim confidence
        high_confidence_candidates = [
            c for c in candidates 
            if confidence_map.get(c.confidence, 0.0) >= threshold
        ]
        
        if not high_confidence_candidates:
            return None
        
        # Mapowanie ConfidenceLevel na float
        confidence_map = {
            ConfidenceLevel.CRITICAL: 0.2,
            ConfidenceLevel.LOW: 0.4,
            ConfidenceLevel.MEDIUM: 0.7,
            ConfidenceLevel.HIGH: 0.85,
            ConfidenceLevel.VERY_HIGH: 0.95
        }
        
        # Sortuj po confidence (malejąco)
        sorted_candidates = sorted(
            high_confidence_candidates,
            key=lambda c: confidence_map.get(c.confidence, 0.0),
            reverse=True
        )
        
        # Pobierz top 3 wyniki
        top_candidates = sorted_candidates[:3]
        
        definition = GROUP_DEFINITIONS[ScoreGroupType.BALANCED_SCORE]
        group_scores = [self.extract_group_score(c) for c in top_candidates]
        
        return ScoreGroup(
            group_type=ScoreGroupType.BALANCED_SCORE,
            name=definition["name"],
            description=definition["description"],
            scores=group_scores
        )
    
    def rank_groups(
        self,
        collection: ScoreGroupCollection
    ) -> ScoreGroupCollection:
        """
        Posortuj grupy po group_confidence
        
        Args:
            collection: ScoreGroupCollection do posortowania
            
        Returns:
            ScoreGroupCollection (z zaktualizowanym rankingiem)
        """
        # Ranking jest już obliczany w __post_init__, ale możemy wymusić ponowne sortowanie
        sorted_groups = sorted(
            collection.groups.values(),
            key=lambda g: (g.group_confidence, g.total_sample_count),
            reverse=True
        )
        
        for rank, group in enumerate(sorted_groups, 1):
            group.rank = rank
        
        collection._rank_groups()
        return collection
    
    def get_best_groups(
        self,
        match_id: str,
        n: int = 3
    ) -> List[ScoreGroup]:
        """
        Pobierz N najlepszych grup dla meczu
        
        Args:
            match_id: Identyfikator meczu
            n: Liczba grup do zwrócenia
            
        Returns:
            Lista ScoreGroup
        """
        # Tutaj powinniśmy użyć ExactScoreKnowledge, ale uprościmy
        # W rzeczywistości należy zintegrować z pełnym systemem
        
        # Na razie zwracamy zestaw domyślny (do implementacji z danymi rzeczywistymi)
        all_candidates = []  # Powinno być pobrane z ExactScoreKnowledge
        collection = self.build_groups(match_id, candidates=all_candidates)
        return collection.get_best_groups(n)


