class MarketProbabilityConverter:
    """
    Konwerter kursów bukmacherskich na prawdopodobieństwa
    
    Odpowiedzialność:
    - Konwersja kursów na prawdopodobieństwa
    - Normalizacja marży bukmachera
    - Obliczanie implikowanych prawdopodobieństw
    """
    
    @staticmethod
    def odds_to_probability(odds: float) -> float:
        """
        Konwersja kursu na prawdopodobieństwo (w procentach)
        
        Args:
            odds: Kurs bukmacherski (np. 2.50)
            
        Returns:
            Prawdopodobieństwo w procentach (np. 40.0)
        """
        if odds <= 0:
            raise ValueError(f"Kurs musi być > 0, otrzymałem: {odds}")
        
        probability = 1.0 / odds
        return probability * 100.0  # Konwersja na procenty
    
    @staticmethod
    def probability_to_odds(probability: float) -> float:
        """
        Konwersja prawdopodobieństwa na kurs
        
        Args:
            probability: Prawdopodobieństwo w procentach (np. 40.0)
            
        Returns:
            Kurs bukmacherski (np. 2.5)
        """
        if probability <= 0 or probability >= 100:
            raise ValueError(f"Prawdopodobieństwo musi być > 0 i < 100, otrzymałem: {probability}")
        
        probability_decimal = probability / 100.0
        return 1.0 / probability_decimal
    
    @staticmethod
    def normalize_probabilities(
        home_prob: float,
        draw_prob: float,
        away_prob: float
    ) -> Tuple[float, float, float, float]:
        """
        Normalizacja prawdopodobieństw uwzględniająca marżę bukmachera
        
        Args:
            home_prob: Prawdopodobieństwo wygranej gospodarzy (%)
            draw_prob: Prawdopodobieństwo remisu (%)
            away_prob: Prawdopodobieństwo wygranej gości (%)
            
        Returns:
            Tuple(znormalizowane_home, znormalizowane_draw, znormalizowane_away, marża%)
        """
        raw_sum = home_prob + draw_prob + away_prob
        margin = raw_sum - 100.0
        
        if raw_sum == 0:
            raise ValueError("Suma prawdopodobieństw wynosi 0")
        
        # Normalizacja
        home_normalized = (home_prob / raw_sum) * 100.0
        draw_normalized = (draw_prob / raw_sum) * 100.0
        away_normalized = (away_prob / raw_sum) * 100.0
        
        return home_normalized, draw_normalized, away_normalized, abs(margin)
    
    def convert_odds_to_probabilities(
        self,
        home_odds: float,
        draw_odds: float,
        away_odds: float,
        match_id: Optional[str] = None
    ) -> MarketProbability:
        """
        Konwersja kursów na prawdopodobieństwa z normalizacją
        
        Args:
            home_odds: Kurs na wygraną gospodarzy
            draw_odds: Kurs na remis
            away_odds: Kurs na wygraną gości
            match_id: Opcjonalny identyfikator meczu
            
        Returns:
            MarketProbability obiekt
        """
        # Konwersja na prawdopodobieństwa brute
        home_prob = self.odds_to_probability(home_odds)
        draw_prob = self.odds_to_probability(draw_odds)
        away_prob = self.odds_to_probability(away_odds)
        
        # Normalizacja
        home_norm, draw_norm, away_norm, margin = self.normalize_probabilities(
            home_prob, draw_prob, away_prob
        )
        
        raw_sum = home_prob + draw_prob + away_prob
        
        return MarketProbability(
            match_id=match_id or "unknown",
            home_win_probability=home_prob,
            draw_probability=draw_prob,
            away_win_probability=away_prob,
            bookmaker_margin=margin,
            home_win_normalized=home_norm,
            draw_normalized=draw_norm,
            away_win_normalized=away_norm,
            raw_sum=raw_sum
        )
    
    def convert_batch(
        self,
        odds_list: List[Tuple[str, float, float, float]]
    ) -> Dict[str, MarketProbability]:
        """
        Konwersja wielu zestawów kursów na prawdopodobieństwa
        
        Args:
            odds_list: Lista tuple (match_id, home_odds, draw_odds, away_odds)
            
        Returns:
            Dict[match_id, MarketProbability]
        """
        results = {}
        
        for item in odds_list:
            if len(item) == 4:
                match_id, home_odds, draw_odds, away_odds = item
                results[match_id] = self.convert_odds_to_probabilities(
                    home_odds, draw_odds, away_odds, match_id
                )
            elif len(item) == 3:
                # Bez match_id
                home_odds, draw_odds, away_odds = item
                results[f"match_{len(results) + 1}"] = self.convert_odds_to_probabilities(
                    home_odds, draw_odds, away_odds
                )
        
        return results
    
    def get_margin_percentage(self, odds_list: List[float]) -> float:
        """
        Oblicz marżę bukmachera dla listy kursów
        
        Args:
            odds_list: Lista kursów (np. [2.5, 3.0, 2.8])
            
        Returns:
            Marża w procentach
        """
        probabilities = [1.0 / odds for odds in odds_list]
        sum_probabilities = sum(probabilities)
        return (sum_probabilities - 1.0) * 100.0


