def create_test_evidence(score: str, world_pct: float = 10.0, samples: int = 1000) -> ScoreEvidence:
    """Tworzy testową ewidencję"""
    world_level_1 = WorldLevelEvidence(level="level_1", percentage=world_pct, sample_count=samples)
    world_level_2 = WorldLevelEvidence(level="level_2", percentage=world_pct + 1, sample_count=samples // 2)
    full_group = WorldLevelEvidence(level="full_group", percentage=world_pct + 2, sample_count=samples // 4)
    
    return ScoreEvidence(
        score=score,
        world_level_1=world_level_1,
        world_level_2=world_level_2,
        world_full_group=full_group,
        market_probability=world_pct,
        poisson_probability=world_pct
    )


def create_test_candidate(score: str, confidence: float = 0.8, world_pct: float = 10.0, 
                         market_pct: float = 10.0, samples: int = 1000) -> ExactScoreCandidate:
    """Tworzy testowego kandydata"""
    evidence = create_test_evidence(score, world_pct, samples)
    
    # Mapowanie ConfidenceLevel
    if confidence >= 0.8:
        level = ConfidenceLevel.HIGH
    elif confidence >= 0.6:
        level = ConfidenceLevel.MEDIUM
    else:
        level = ConfidenceLevel.LOW
    
    return ExactScoreCandidate(
        score=score,
        evidence=evidence,
        world_probability=world_pct,
        market_probability=market_pct,
        poisson_probability=world_pct,
        combined_probability=(world_pct + market_pct) / 2,
        confidence=level,
        rank=0,
        risk_score=0.0,
        value_score=0.0
    )


