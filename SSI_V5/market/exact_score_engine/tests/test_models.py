    def test_roundtrip_world_level_evidence(self):
        """Test: WorldLevelEvidence - serializacja i deserializacja"""
        original = WorldLevelEvidence(
            level="level_1",
            percentage=12.73,
            sample_count=3448
        )
        
        data = original.to_dict()
        # Zmień 'samples' na 'sample_count' dla deserializacji
        if 'samples' in data:
            data['sample_count'] = data.pop('samples')
        restored = WorldLevelEvidence(**data)
        
        assert restored.level == original.level
        assert restored.percentage == original.percentage
        assert restored.sample_count == original.sample_count
    
    def test_roundtrip_score_evidence(self):
        """Test: ScoreEvidence - serializacja i deserializacja"""
        level_1 = WorldLevelEvidence("level_1", 12.73, 3448)
        original = ScoreEvidence(
            score="1:1",
            world_level_1=level_1,
            market_probability=15.0
        )
        
        data = original.to_dict()
        # WorldLevelEvidence trzeba odtworzyć ręcznie
        world_data = data["world"]["level_1"]
        if world_data and 'samples' in world_data:
            world_data['sample_count'] = world_data.pop('samples')
        
        restored = ScoreEvidence(
            score=data["score"],
            world_level_1=WorldLevelEvidence(**world_data) if world_data else None,
            market_probability=data["market"]["probability"]
        )
        
        assert restored.score == original.score
        assert restored.market_probability == original.market_probability


