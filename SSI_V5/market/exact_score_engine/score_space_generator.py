@dataclass
class ScoreLevelData:
    """Dane dla jednego poziomu (level_1, level_2, full_group)"""
    
    level: str  # "level_1", "level_2", "full_group"
    group_name: str  # Nazwa grupy (np. "poziom7")
    sample_count: int  # Liczba przypadków
    scores: Dict[str, float]  # {wynik: procent}
    
    def __post_init__(self):
        """Walidacja"""
        if self.sample_count < 0:
            raise ValueError(f"Sample count cannot be negative: {self.sample_count}")
        if not self.scores:
            logger.warning(f"No scores data for {self.level} - {self.group_name}")
    
    def get_score_percentage(self, score: str) -> Optional[float]:
        """Pobierz procent dla konkretnego wyniku"""
        return self.scores.get(score)
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do dict"""
        return {
            "level": self.level,
            "group_name": self.group_name,
            "samples": self.sample_count,
            "scores": self.scores
        }


@dataclass
class ExactScoreSpace:
    """
    Prestrzeń wyników dla pojedynczego meczu
    
    Zawiera dane z trzech poziomów WORLD dla wszystkich VALID_SCORES
    """
    
    match_id: str  # Nazwa meczu
    match_group: str  # Grupa identyfikacyjna (np. "poziom7poziom11poziom10")
    
    # Dane dla każdego poziomu
    level_1: Optional[ScoreLevelData] = None
    level_2: Optional[ScoreLevelData] = None
    full_group: Optional[ScoreLevelData] = None
    
    def __post_init__(self):
        """Walidacja i uzupełnianie"""
        # Upewnij się, że wszystkie VALID_SCORES są obecne w każdym poziomie
        self._ensure_valid_scores()
    
    def _ensure_valid_scores(self):
        """Upewnij się, że wszystkie VALID_SCORES są obecne (z 0.0 jeśli brak)"""
        for level_data in [self.level_1, self.level_2, self.full_group]:
            if level_data:
                for score in VALID_SCORES:
                    if score not in level_data.scores:
                        level_data.scores[score] = 0.0
    
    def get_levels(self) -> Dict[str, ScoreLevelData]:
        """Pobierz wszystkie poziomy"""
        levels = {}
        if self.level_1:
            levels["level_1"] = self.level_1
        if self.level_2:
            levels["level_2"] = self.level_2
        if self.full_group:
            levels["full_group"] = self.full_group
        return levels
    
    def get_score_across_levels(self, score: str) -> Dict[str, Optional[float]]:
        """
        Pobierz procentowy wynik dla danego wyniku na wszystkich poziomach
        
        Args:
            score: Wynik w formacie "X:Y"
            
        Returns:
            Dict[level, percentage] dla level_1, level_2, full_group
        """
        if score not in VALID_SCORES:
            raise ValueError(f"Score {score} not in VALID_SCORES")
        
        result = {}
        
        if self.level_1:
            result["level_1"] = self.level_1.get_score_percentage(score)
        else:
            result["level_1"] = None
            
        if self.level_2:
            result["level_2"] = self.level_2.get_score_percentage(score)
        else:
            result["level_2"] = None
            
        if self.full_group:
            result["full_group"] = self.full_group.get_score_percentage(score)
        else:
            result["full_group"] = None
        
        return result
    
    def get_sample_counts(self) -> Dict[str, int]:
        """Pobierz liczbę przypadków dla każdego poziomu"""
        return {
            "level_1": self.level_1.sample_count if self.level_1 else 0,
            "level_2": self.level_2.sample_count if self.level_2 else 0,
            "full_group": self.full_group.sample_count if self.full_group else 0
        }
    
    def to_dict(self) -> Dict[str, Any]:
        """Konwersja do dict"""
        return {
            "match": self.match_id,
            "match_group": self.match_group,
            "levels": {
                "level_1": self.level_1.to_dict() if self.level_1 else None,
                "level_2": self.level_2.to_dict() if self.level_2 else None,
                "full_group": self.full_group.to_dict() if self.full_group else None
            },
            "sample_counts": self.get_sample_counts()
        }


class ScoreSpaceGenerator:
    """
    Generator przestrzeni wyników z WORLD DATABASE
    
    Odpowiedzialność:
    - Ładowanie WORLD_MATCH_DATABASE.json
    - Ekstrakcja danych dla poszczególnych meczów
    - Budowa ExactScoreSpace dla każdego meczu
    - Filtrowanie tylko VALID_SCORES
    """
    
    WORLD_DATABASE_PATH = "WORLD/aktualny/WORLD_MATCH_DATABASE.json"
    
    def __init__(self, database_path: Optional[str] = None):
        """
        Inicjalizacja generatora
        
        Args:
            database_path: Ścieżka do WORLD_MATCH_DATABASE.json
        """
        self.database_path = database_path or self._find_database_path()
        self._world_data: Dict[str, Any] = {}
        self._score_spaces: Dict[str, ExactScoreSpace] = {}
        self._level_analysis_cache: Dict[str, Dict[str, Any]] = {}
        self._loaded = False
        logger.info(f"[ScoreSpaceGenerator] Inicjalizacja - path: {self.database_path}")
    
    def _find_database_path(self) -> str:
        """Odszukaj WORLD_MATCH_DATABASE.json"""
        possible_paths = [
            "WORLD/aktualny/WORLD_MATCH_DATABASE.json",
            os.path.join(os.getcwd(), "WORLD", "aktualny", "WORLD_MATCH_DATABASE.json"),
            os.path.join(os.getcwd(), "..", "WORLD", "aktualny", "WORLD_MATCH_DATABASE.json"),
        ]
        
        for path in possible_paths:
            if os.path.exists(path):
                return path
        
        return "WORLD/aktualny/WORLD_MATCH_DATABASE.json"
    
    def load_database(self) -> int:
        """
        Załaduj WORLD_MATCH_DATABASE
        
        Returns:
            Liczba załadowanych meczów
        """
        if not os.path.exists(self.database_path):
            logger.error(f"[ScoreSpaceGenerator] Plik nie istnieje: {self.database_path}")
            raise FileNotFoundError(f"WORLD_MATCH_DATABASE nie znaleziony: {self.database_path}")
        
        try:
            with open(self.database_path, 'r', encoding='utf-8') as f:
                self._world_data = json.load(f)
        except json.JSONDecodeError as e:
            logger.error(f"[ScoreSpaceGenerator] Błędny format JSON: {e}")
            raise
        except Exception as e:
            logger.error(f"[ScoreSpaceGenerator] Błąd ładowania pliku: {e}")
            raise
        
        self._loaded = True
        logger.info(f"[ScoreSpaceGenerator] Załadowano {len(self._world_data)} meczy")
        return len(self._world_data)
    
    def _extract_level_data(
        self,
        level_key: str,
        analysis_data: Dict[str, Any]
    ) -> Optional[ScoreLevelData]:
        """
        Wyekstraktuj dane dla jednego poziomu
        
        Args:
            level_key: Klucz poziomu ("level_1", "level_2", "full_group")
            analysis_data: Dane analityczne z world_analysis
            
        Returns:
            ScoreLevelData lub None
        """
        if level_key not in analysis_data:
            logger.warning(f"Brakujący poziom: {level_key}")
            return None
        
        level_data = analysis_data[level_key]
        if not level_data or "analiza" not in level_data:
            return None
        
        analiza = level_data["analiza"]
        
        # Pobierz ilosc_przypadkow
        sample_count = analiza.get("ilosc_przypadkow", 0)
        
        # Pobierz wyniki_docelowe
        wyniki_docelowe = analiza.get("wyniki_docelowe", {})
        
        # Filtrowanie tylko VALID_SCORES
        filtered_scores = {}
        for score, data in wyniki_docelowe.items():
            if score in VALID_SCORES:
                filtered_scores[score] = float(data.get("procent", 0.0))
            else:
                logger.debug(f"Pominąłem wynik {score} - nie w VALID_SCORES")
        
        # Pobierz nazwę grupy
        group_name = level_data.get("poziom", level_key)
        
        return ScoreLevelData(
            level=level_key,
            group_name=group_name,
            sample_count=sample_count,
            scores=filtered_scores
        )
    
    def generate_score_space(self, match_id: str) -> Optional[ExactScoreSpace]:
        """
        Wygeneruj przestrzeń wyników dla pojedynczego meczu
        
        Args:
            match_id: Nazwa meczu
            
        Returns:
            ExactScoreSpace lub None
        """
        if not self._loaded:
            self.load_database()
        
        if match_id not in self._world_data:
            logger.warning(f"[ScoreSpaceGenerator] Mecze {match_id} nie znaleziony w bazie WORLD")
            return None
        
        # Sprawdź cache
        if match_id in self._score_spaces:
            return self._score_spaces[match_id]
        
        match_data = self._world_data[match_id]
        
        # Pobierz dane analityczne
        if "world_analysis" not in match_data:
            logger.warning(f"[ScoreSpaceGenerator] Brak world_analysis dla {match_id}")
            return None
        
        world_analysis = match_data["world_analysis"]
        
        # Wyekstraktuj dane dla każdego poziomu
        level_1_data = self._extract_level_data("level_1", world_analysis)
        level_2_data = self._extract_level_data("level_2", world_analysis)
        full_group_data = self._extract_level_data("full_group", world_analysis)
        
        # Pobierz grupę identyfikacyjną
        match_group = ""
        if "identyfikacja" in match_data:
            match_group = match_data["identyfikacja"].get("full", "")
        elif "metadata" in match_data:
            match_group = match_data["metadata"].get("grupa_kursowa", "")
        
        score_space = ExactScoreSpace(
            match_id=match_id,
            match_group=match_group,
            level_1=level_1_data,
            level_2=level_2_data,
            full_group=full_group_data
        )
        
        # Cache
        self._score_spaces[match_id] = score_space
        
        return score_space
    
    def generate_all_score_spaces(self) -> Dict[str, ExactScoreSpace]:
        """
        Wygeneruj przestrzenie wyników dla wszystkich meczów
        
        Returns:
            Dict[match_id, ExactScoreSpace]
        """
        if not self._loaded:
            self.load_database()
        
        if self._score_spaces:
            return self._score_spaces
        
        for match_id in self._world_data.keys():
            self.generate_score_space(match_id)
        
        return self._score_spaces
    
    def get_match_ids(self) -> List[str]:
        """Pobierz listę wszystkich meczów"""
        if not self._loaded:
            self.load_database()
        return list(self._world_data.keys())
    
    def get_score_statistics(self, score: str) -> Dict[str, Dict[str, float]]:
        """
        Pobierz statystyki dla konkretnego wyniku na wszystkich poziomach
        
        Args:
            score: Wynik w formacie "X:Y"
            
        Returns:
            Dict[level, Dict[group_name, percentage]]
        """
        if score not in VALID_SCORES:
            raise ValueError(f"Score {score} not in VALID_SCORES")
        
        if not self._loaded:
            self.load_database()
        
        statistics = {
            "level_1": {},
            "level_2": {},
            "full_group": {}
        }
        
        for match_id, match_data in self._world_data.items():
            if "world_analysis" not in match_data:
                continue
            
            world_analysis = match_data["world_analysis"]
            
            # Level 1
            if "level_1" in world_analysis and "analiza" in world_analysis["level_1"]:
                group_name = world_analysis["level_1"].get("poziom", "unknown")
                level_1_analysis = world_analysis["level_1"]["analiza"]
                if "wyniki_docelowe" in level_1_analysis and score in level_1_analysis["wyniki_docelowe"]:
                    percentage = level_1_analysis["wyniki_docelowe"][score].get("procent", 0.0)
                    if group_name not in statistics["level_1"]:
                        statistics["level_1"][group_name] = []
                    statistics["level_1"][group_name].append(float(percentage))
            
            # Level 2
            if "level_2" in world_analysis and "analiza" in world_analysis["level_2"]:
                group_name = world_analysis["level_2"].get("poziom", "unknown")
                level_2_analysis = world_analysis["level_2"]["analiza"]
                if "wyniki_docelowe" in level_2_analysis and score in level_2_analysis["wyniki_docelowe"]:
                    percentage = level_2_analysis["wyniki_docelowe"][score].get("procent", 0.0)
                    if group_name not in statistics["level_2"]:
                        statistics["level_2"][group_name] = []
                    statistics["level_2"][group_name].append(float(percentage))
            
            # Full Group
            if "full_group" in world_analysis and "analiza" in world_analysis["full_group"]:
                group_name = world_analysis["full_group"].get("poziom", "unknown")
                full_analysis = world_analysis["full_group"]["analiza"]
                if "wyniki_docelowe" in full_analysis and score in full_analysis["wyniki_docelowe"]:
                    percentage = full_analysis["wyniki_docelowe"][score].get("procent", 0.0)
                    if group_name not in statistics["full_group"]:
                        statistics["full_group"][group_name] = []
                    statistics["full_group"][group_name].append(float(percentage))
        
        # Oblicz średnie dla każdej grupy
        result = {}
        for level in ["level_1", "level_2", "full_group"]:
            result[level] = {}
            for group_name, percentages in statistics[level].items():
                if percentages:
                    result[level][group_name] = {
                        "avg": sum(percentages) / len(percentages),
                        "min": min(percentages),
                        "max": max(percentages),
                        "count": len(percentages)
                    }
        
        return result
    
    def is_loaded(self) -> bool:
        """Sprawdź, czy dane zostały załadowane"""
        return self._loaded
    
    def count(self) -> int:
        """Pobierz liczbę meczów w bazie"""
        return len(self._world_data)


