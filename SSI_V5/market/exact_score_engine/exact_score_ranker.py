class ExactScoreRanking:
    """
    Finalny obiekt rankingowy dla Strategy Laboratory
    
    Zawiera:
    - Ranking pojedynczych wyników
    - Ranking grup strategicznych
    - Ranking scenariuszy meczowych
    - Metadane i statystyki
    """
    
    # Identyfikator meczu
    match_id: str
    match_name: str
    
    # Czas generowania
    generated_at: str = ""
    
    # Ranking pojedynczych wyników (posortowany po rankingu)
    individual_scores: List[ScoreRankingData] = field(default_factory=list)
    
    # Ranking grup strategicznych (posortowany po rankingu)
    scenario_groups: List[GroupRankingData] = field(default_factory=list)
    
    # Ranking scenariuszy meczowych (posortowany po rankingu)
    match_scenarios: List[ScenarioRankingData] = field(default_factory=list)
    
    # Statystyki
    statistics: Dict[str, Any] = field(default_factory=dict)
    
    # Metadane
    metadata: Dict[str, Any] = field(default_factory=dict)
    
    def __post_init__(self):
        """Inicjalizacja i sortowanie"""
        if not self.generated_at:
            self.generated_at = datetime.now().isoformat()
        
        # Sortuj rankingi po ranking_score (malejąco)
        self.individual_scores.sort(key=lambda x: x.ranking_score, reverse=True)
        self.scenario_groups.sort(key=lambda x: x.ranking_score, reverse=True)
        self.match_scenarios.sort(key=lambda x: x.ranking_score, reverse=True)
        
        # Uaktualnij pozycje rankingowe
        self._update_ranks()
        
        # Oblicz statystyki
        self._calculate_statistics()
    
    def _update_ranks(self):
        """Uaktualnij pozycje w rankingu"""
        for i, score_data in enumerate(self.individual_scores, 1):
            score_data.rank = i
        
        for i, group_data in enumerate(self.scenario_groups, 1):
            group_data.rank = i
            
        for i, scenario_data in enumerate(self.match_scenarios, 1):
            scenario_data.rank = i
    
    def _calculate_statistics(self):
        """Oblicz statystyki"""
        # Statystyki dla pojedynczych wyników
        if self.individual_scores:
            total_score = sum(s.ranking_score for s in self.individual_scores)
            avg_score = total_score / len(self.individual_scores)
            
            high_confidence = len([s for s in self.individual_scores if s.confidence_score >= 0.8])
            medium_confidence = len([s for s in self.individual_scores if 0.6 <= s.confidence_score < 0.8])
            low_confidence = len([s for s in self.individual_scores if s.confidence_score < 0.6])
            
            self.statistics['individual_scores'] = {
                'count': len(self.individual_scores),
                'average_ranking_score': avg_score,
                'high_confidence': high_confidence,
                'medium_confidence': medium_confidence,
                'low_confidence': low_confidence
            }
        
        # Statystyki dla grup
        if self.scenario_groups:
            total_group_score = sum(g.ranking_score for g in self.scenario_groups)
            avg_group_score = total_group_score / len(self.scenario_groups)
            
            self.statistics['scenario_groups'] = {
                'count': len(self.scenario_groups),
                'average_ranking_score': avg_group_score
            }
        
        # Statystyki dla scenariuszy
        if self.match_scenarios:
            total_scenario_score = sum(s.ranking_score for s in self.match_scenarios)
            avg_scenario_score = total_scenario_score / len(self.match_scenarios)
            
            self.statistics['match_scenarios'] = {
                'count': len(self.match_scenarios),
                'average_ranking_score': avg_scenario_score
            }
    
    def to_dict(self) -> Dict[str, Any]:
        """Serializacja do dict"""
        return {
            "match_id": self.match_id,
            "match_name": self.match_name,
            "generated_at": self.generated_at,
            "rankings": {
                "individual_scores": [s.to_dict() for s in self.individual_scores],
                "scenario_groups": [g.to_dict() for g in self.scenario_groups],
                "match_scenarios": [s.to_dict() for s in self.match_scenarios]
            },
            "statistics": self.statistics,
            "metadata": self.metadata
        }
    
    def to_json(self, indent: int = 2) -> str:
        """Serializacja do JSON"""
        import json
        return json.dumps(self.to_dict(), indent=indent, ensure_ascii=False)
    
    def get_top_individual_scores(self, n: int = 3) -> List[ScoreRankingData]:
        """Pobierz N najlepszych pojedynczych wyników"""
        return self.individual_scores[:n]
    
    def get_top_scenario_groups(self, n: int = 3) -> List[GroupRankingData]:
        """Pobierz N najlepszych grup"""
        return self.scenario_groups[:n]
    
    def get_top_match_scenarios(self, n: int = 3) -> List[ScenarioRankingData]:
        """Pobierz N najlepszych scenariuszy"""
        return self.match_scenarios[:n]
    
    def get_best_score(self) -> Optional[ScoreRankingData]:
        """Pobierz najlepszy pojedynczy wynik"""
        return self.individual_scores[0] if self.individual_scores else None
    
    def get_best_scenario(self) -> Optional[ScenarioRankingData]:
        """Pobierz najlepszy scenariusz"""
        return self.match_scenarios[0] if self.match_scenarios else None


