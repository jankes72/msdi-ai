    def create_ranking(
        self,
        candidates: List[ExactScoreCandidate],
        group_collection: Optional[ScoreGroupCollection] = None,
        match_id: str = "unknown",
        match_name: str = "Unknown Match"
    ) -> ExactScoreRanking:
        """
        Utwórz pełny ExactScoreRanking
        
        Główna funkcja modułu.
        
        Args:
            candidates: Lista ExactScoreCandidate
            group_collection: Opcjonalna ScoreGroupCollection
            match_id: Identyfikator meczu
            match_name: Nazwa meczu
        
        Returns:
            ExactScoreRanking
        
        Example:
            candidates = [...]  # Lista ExactScoreCandidate
            group_collection = ScoreGroupBuilder().build_groups_from_candidates(candidates)
            ranking = ranker.create_ranking(candidates, group_collection, "match_1", "Team A - Team B")
        """
        logger.info(f"[ExactScoreRanker] Tworzenie rankingu dla {match_name}")
        
        # Jeśli nie ma group_collection, utwórz go
        if not group_collection and candidates:
            group_collection = self.group_builder.build_groups_from_candidates(candidates)
        
        # Ranking pojedynczych wyników
        individual_scores = self.rank_individual_scores(candidates, group_collection)
        
        # Ranking grup (jeśli dostępne)
        scenario_groups = []
        if group_collection:
            scenario_groups = self.rank_scenario_groups(group_collection)
        
        # Ranking scenariuszy
        match_scenarios = self.rank_match_scenarios(individual_scores, scenario_groups)
        
        # Utwórz ExactScoreRanking
        ranking = ExactScoreRanking(
            match_id=match_id,
            match_name=match_name,
            individual_scores=individual_scores,
            scenario_groups=scenario_groups,
            match_scenarios=match_scenarios,
            metadata={
                "source": "ExactScoreRanker",
                "version": "5.2.9.x",
                "candidates_count": len(candidates),
                "groups_count": len(scenario_groups)
            }
        )
        
        logger.info(f"[ExactScoreRanker] Ranking utworzony: {len(individual_scores)} wyników, {len(scenario_groups)} grup, {len(match_scenarios)} scenariuszy")
        
        return ranking
    
    def create_ranking_from_knowledge(
        self,
        knowledge: ExactScoreKnowledge
    ) -> ExactScoreRanking:
        """
        Utwórz ranking z ExactScoreKnowledge
        
        Args:
            knowledge: ExactScoreKnowledge
        
        Returns:
            ExactScoreRanking
        """
        # Buduj group_collection z knowledge
        group_collection = self.group_builder.build_groups_from_knowledge(knowledge)
        
        return self.create_ranking(
            candidates=knowledge.candidates,
            group_collection=group_collection,
            match_id=knowledge.match_id,
            match_name=knowledge.match_name
        )


