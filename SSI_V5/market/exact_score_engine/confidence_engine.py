class ConfidenceCalculator:
    """
    Kalkulator Confidence Score
    
    Odpowiedzialność:
    - Obliczanie poszczególnych komponentów
    - Łączeniełów w finalny Confidence Score
    - Generowanie wyjaśnień
    """
    
    # Wagi komponentów (sumują się do 1.0)
    DEFAULT_WEIGHTS = {
        ConfidenceComponent.WORLD_CONSISTENCY: 0.35,
        ConfidenceComponent.SAMPLE_STRENGTH: 0.25,
        ConfidenceComponent.MARKET_ALIGNMENT: 0.20,
        ConfidenceComponent.POISSON_ALIGNMENT: 0.20
    }
    
    def __init__(self, weights: Optional[Dict[ConfidenceComponent, float]] = None):
        """
        Inicjalizacja kalkulatora
        
        Args:
            weights: Opcjonalne wagi Componentów (muszą sumować się do 1.0)
        """
        self.weights = weights or self.DEFAULT_WEIGHTS
        self._validate_weights()
        logger.info(f"[ConfidenceCalculator] Inicjalizacja z wagami: {self.weights}")
    
    def _validate_weights(self):
        """Walidacja wag"""
        total = sum(self.weights.values())
        if abs(total - 1.0) > 0.001:
            logger.warning(f"[ConfidenceCalculator] Wagi nie sumują się do 1.0: {total}")
            # Normalizacja
            for component in self.weights:
                self.weights[component] = self.weights[component] / total
    
    def calculate_world_consistency(
        self,
        level_1_percentage: Optional[float],
        level_2_percentage: Optional[float],
        full_group_percentage: Optional[float],
        level_1_samples: int = 0,
        level_2_samples: int = 0,
        full_group_samples: int = 0
    ) -> float:
        """
        Oblicz world_consistency (0-1)
        
        Zasady:
        - Wysoka zgodność: wszystkie poziomy zbliżone -> wysoki score
        - Niska zgodność: duże rozbieżności -> niski score
        - Brak danych: bardzo niski score
        
        Args:
            level_1_percentage: Procent z level_1
            level_2_percentage: Procent z level_2
            full_group_percentage: Procent z full_group
            level_1_samples: Liczba przypadków level_1
            level_2_samples: Liczba przypadków level_2
            full_group_samples: Liczba przypadków full_group
            
        Returns:
            world_consistency (0-1)
        """
        # Zebierz dostępne wartości
        percentages = []
        if level_1_percentage is not None:
            percentages.append((level_1_percentage, level_1_samples))
        if level_2_percentage is not None:
            percentages.append((level_2_percentage, level_2_samples))
        if full_group_percentage is not None:
            percentages.append((full_group_percentage, full_group_samples))
        
        if len(percentages) < 2:
            # Za mało danych do porównania
            return 0.3  # Niski, ale nie zero (jeszcze jakaś informacja)
        
        # Wyekstraktuj wartości procentowe i wagi (sample counts)
        values = [p[0] for p in percentages]
        weights = [p[1] for p in percentages]
        
        # Normalizacja wag
        total_weight = sum(weights)
        if total_weight == 0:
            normalized_weights = [1.0 / len(values)] * len(values)
        else:
            normalized_weights = [w / total_weight for w in weights]
        
        # Oblicz średnią ważoną
        weighted_mean = sum(v * w for v, w in zip(values, normalized_weights))
        
        # Oblicz odchylenie standardowe ważone
        variance = sum(
            normalized_weights[i] * (values[i] - weighted_mean) ** 2
            for i in range(len(values))
        )
        std_dev = math.sqrt(variance)
        
        # Im mniejsze odchylenie, tym wyższa zgodność
        # Max std_dev to np. 15% (przy cyklu 0-15%)
        # Normalizuj do 0-1
        max_expected_std = 15.0
        if std_dev >= max_expected_std:
            consistency = 0.0
        else:
            consistency = 1.0 - (std_dev / max_expected_std)
        
        # Minimalna wartość
        return max(consistency, 0.1)
    
    def calculate_sample_strength(
        self,
        level_1_samples: int = 0,
        level_2_samples: int = 0,
        full_group_samples: int = 0
    ) -> float:
        """
        Oblicz sample_strength (0-1)
        
        Zasady:
        - Im większa próbka, tym wyższa wiarygodność
        - Uwzględnia wzrost próbek na kolejnych poziomach
        
        Args:
            level_1_samples: Liczba przypadków level_1
            level_2_samples: Liczba przypadków level_2
            full_group_samples: Liczba przypadków full_group
            
        Returns:
            sample_strength (0-1)
        """
        samples = [level_1_samples, level_2_samples, full_group_samples]
        
        # Usunięcie zer
        valid_samples = [s for s in samples if s > 0]
        
        if not valid_samples:
            return 0.0
        
        # Największa próbka
        max_sample = max(valid_samples)
        
        # Skala: 0-5000 (przyjmujemy, że 5000 to maksymalna oczekiwana próbka)
        max_expected = 5000.0
        
        # Normalizacja logarytmiczna (lepsza dla dużych zakresów)
        # Używamy log, żeby nie karać zbytnio małych próbek
        if max_sample == 0:
            return 0.0
        
        # Wzór: min(1, log10(max_sample + 1) / log10(max_expected + 1))
        import math
        strength = math.log10(max_sample + 1) / math.log10(max_expected + 1)
        
        # Minimalna wartość
        return max(strength, 0.1)
    
    def calculate_market_alignment(
        self,
        world_probability: Optional[float],
        market_probability: Optional[float]
    ) -> float:
        """
        Oblicz market_alignment (0-1)
        
        Porównuje WORLD probability z Market probability
        
        Args:
            world_probability: Prawdopodobieństwo z WORLD (w %)  
            market_probability: Prawdopodobieństwo z rynku (w %)
            
        Returns:
            market_alignment (0-1)
        """
        if world_probability is None or market_probability is None:
            return 0.5  # Brak danych - neutralny
        
        # Różnica w punktach procentowych
        diff = abs(world_probability - market_probability)
        
        # Max difference to 20% (przy cyklu 0-20%)
        max_diff = 20.0
        
        if diff >= max_diff:
            alignment = 0.0
        else:
            alignment = 1.0 - (diff / max_diff)
        
        # Minimalna wartość
        return max(alignment, 0.2)
    
    def calculate_poisson_alignment(
        self,
        world_probability: Optional[float],
        poisson_probability: Optional[float]
    ) -> float:
        """
        Oblicz poisson_alignment (0-1)
        
        Porównuje WORLD probability z Poisson probability
        
        Args:
            world_probability: Prawdopodobieństwo z WORLD (w %)
            poisson_probability: Prawdopodobieństwo z modelu Poisson (w %)
            
        Returns:
            poisson_alignment (0-1)
        """
        if world_probability is None or poisson_probability is None:
            return 0.5  # Brak danych - neutralny
        
        # Różnica w punktach procentowych
        diff = abs(world_probability - poisson_probability)
        
        # Max difference to 20%
        max_diff = 20.0
        
        if diff >= max_diff:
            alignment = 0.0
        else:
            alignment = 1.0 - (diff / max_diff)
        
        # Minimalna wartość
        return max(alignment, 0.2)
    
    def calculate_confidence_score(
        self,
        world_consistency: float,
        sample_strength: float,
        market_alignment: float,
        poisson_alignment: float
    ) -> float:
        """
        Oblicz finalny Confidence Score z komponentów
        
        Args:
            world_consistency: Zgodność WORLD (0-1)
            sample_strength: Siła próbek (0-1)
            market_alignment: Zgodność z rynkiem (0-1)
            poisson_alignment: Zgodność z Poisson (0-1)
            
        Returns:
            Confidence Score (0-1)
        """
        # Walidacja
        for value in [world_consistency, sample_strength, market_alignment, poisson_alignment]:
            if value < 0.0 or value > 1.0:
                raise ValueError(f"Komponent must be 0-1, got {value}")
        
        # Oblicz punktację
        components = {
            ConfidenceComponent.WORLD_CONSISTENCY: world_consistency,
            ConfidenceComponent.SAMPLE_STRENGTH: sample_strength,
            ConfidenceComponent.MARKET_ALIGNMENT: market_alignment,
            ConfidenceComponent.POISSON_ALIGNMENT: poisson_alignment
        }
        
        score = sum(
            self.weights.get(component, 0.0) * components[component]
            for component in ConfidenceComponent
        )
        
        # Upewnij się, że wynik jest w zakresie 0-1
        return max(0.0, min(1.0, score))
    
    def classify_confidence_level(self, confidence: float) -> ConfidenceLevel:
        """
        Klasyfikuj poziom pewności
        
        Args:
            confidence: Confidence Score (0-1)
            
        Returns:
            ConfidenceLevel
        """
        if confidence >= 0.80:
            return ConfidenceLevel.HIGH
        elif confidence >= 0.60:
            return ConfidenceLevel.MEDIUM
        else:
            return ConfidenceLevel.LOW


