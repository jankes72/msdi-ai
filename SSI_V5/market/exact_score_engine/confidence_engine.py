    def calculate_score_confidence(
        self,
        score: str,
        world_data: Optional[Dict[str, Any]] = None,
        market_data: Optional[Dict[str, Any]] = None,
        poisson_data: Optional[Dict[str, Any]] = None,
        match_id: Optional[str] = None
    ) -> ConfidenceScore:
        """
        Oblicz Confidence Score dla pojedynczego wyniku
        
        Główna funkcja modułu Confidence Engine.
        
        Args:
            score: Wynik w formacie "X:Y"
            world_data: Opcjonalne dane WORLD (dict z level_1, level_2, full_group)
            market_data: Opcjonalne dane Market (dict z probability)
            poisson_data: Opcjonalne dane Poisson (dict z probability)
            match_id: Opcjonalny identyfikator meczu
            
        Returns:
            ConfidenceScore
            
        Example:
            Input: score="1:1", match_id="Inhulets Petrove - Polissya II"
            Output: ConfidenceScore(score="1:1", confidence=0.87, level=HIGH, ...)
        """
        if score not in VALID_SCORES:
            raise ValueError(f"Invalid score: {score}. Must be in VALID_SCORES")
        
        # 1. world_data
        if world_data:
            level_1_pct = world_data.get("level_1", {}).get("percentage")
            level_2_pct = world_data.get("level_2", {}).get("percentage")
            full_pct = world_data.get("full_group", {}).get("percentage")
            l1_samples = world_data.get("level_1", {}).get("sample_count", 0)
            l2_samples = world_data.get("level_2", {}).get("sample_count", 0)
            full_samples = world_data.get("full_group", {}).get("sample_count", 0)
        else:
            # Pobierz z ScoreSpaceGenerator
            if match_id:
                score_space = self.score_space_generator.generate_score_space(match_id)
                if score_space:
                    level_1_pct, level_2_pct, full_pct, l1_samples, l2_samples, full_samples = \
                        self._extract_world_data(score_space, score)
                else:
                    level_1_pct, level_2_pct, full_pct = None, None, None
                    l1_samples, l2_samples, full_samples = 0, 0, 0
            else:
                level_1_pct, level_2_pct, full_pct = None, None, None
                l1_samples, l2_samples, full_samples = 0, 0, 0
        
        # 2. Market data
        if market_data:
            market_prob = market_data.get("probability")
        else:
            market_prob = self._extract_market_data(match_id or "", score)
        
        # 3. Poisson data
        if poisson_data:
            poisson_prob = poisson_data.get("probability")
        else:
            poisson_prob = self._extract_poisson_data(score, match_id)
        
        # Oblicz średnią WORLD (dla porównania z market i poisson)
        world_percentages = [p for p in [level_1_pct, level_2_pct, full_pct] if p is not None]
        world_avg = sum(world_percentages) / len(world_percentages) if world_percentages else None
        
        # Oblicz komponenty
        world_consistency = self.calculator.calculate_world_consistency(
            level_1_pct, level_2_pct, full_pct,
            l1_samples, l2_samples, full_samples
        )
        
        sample_strength = self.calculator.calculate_sample_strength(
            l1_samples, l2_samples, full_samples
        )
        
        market_alignment = self.calculator.calculate_market_alignment(
            world_avg, market_prob
        )
        
        poisson_alignment = self.calculator.calculate_poisson_alignment(
            world_avg, poisson_prob
        )
        
        # Oblicz finalny score
        confidence = self.calculator.calculate_confidence_score(
            world_consistency, sample_strength, market_alignment, poisson_alignment
        )
        
        # Klasyfikacja
        level = self.calculator.classify_confidence_level(confidence)
        
        # Tworzenie obiektu
        components = ConfidenceComponents(
            world_consistency=world_consistency,
            sample_strength=sample_strength,
            market_alignment=market_alignment,
            poisson_alignment=poisson_alignment
        )
        
        confidence_score = ConfidenceScore(
            score=score,
            confidence=confidence,
            level=level,
            components=components
        )
        
        # Generowanie wyjaśnienia
        confidence_score.generate_explanation()
        
        return confidence_score
    
    def calculate_score_confidence_batch(
        self,
        match_id: str,
        scores: Optional[List[str]] = None
    ) -> ConfidenceResult:
        """
        Oblicz Confidence Score dla wszystkich wyników danego meczu
        
        Args:
            match_id: Identyfikator meczui
            scores: Opcjonalna lista wyników do obliczenia (domyślnie VALID_SCORES)
            
        Returns:
            ConfidenceResult
        """
        if match_id in self._confidence_cache:
            return self._confidence_cache[match_id]
        
        target_scores = scores or VALID_SCORES
        
        confidence_scores = {}
        for score in target_scores:
            try:
                confidence_score = self.calculate_score_confidence(
                    score, match_id=match_id
                )
                confidence_scores[score] = confidence_score
            except Exception as e:
                logger.error(f"[ConfidenceEngine] Błąd obliczania confidence dla {score}: {e}")
                # Stwórz pusty score z LOW confidence
                confidence_scores[score] = ConfidenceScore(
                    score=score,
                    confidence=0.0,
                    level=ConfidenceLevel.LOW,
                    components=ConfidenceComponents()
                )
        
        result = ConfidenceResult(
            match_id=match_id,
            confidence_scores=confidence_scores
        )
        
        # Cache
        self._confidence_cache[match_id] = result
        
        return result
    
    def calculate_confidence_batch(
        self,
        match_ids: List[str]
    ) -> Dict[str, ConfidenceResult]:
        """
        Oblicz Confidence Score dla wielu meczów
        
        Args:
            match_ids: Lista identyfikatorów meczów
            
        Returns:
            Dict[match_id, ConfidenceResult]
        """
        results = {}
        for match_id in match_ids:
            try:
                result = self.calculate_score_confidence_batch(match_id)
                results[match_id] = result
            except Exception as e:
                logger.error(f"[ConfidenceEngine] Błąd obliczania confidence batch dla {match_id}: {e}")
                results[match_id] = ConfidenceResult(
                    match_id=match_id,
                    confidence_scores={}
                )
        
        return results
    
    def get_highest_confidence_scores(
        self,
        match_id: str,
        limit: int = 5
    ) -> List[Tuple[str, ConfidenceScore]]:
        """
        Pobierz N wyników z najwyższym confidence
        
        Args:
            match_id: Identyfikator meczu
            limit: Liczba wyników do zwrócenia
            
        Returns:
            Lista (score, ConfidenceScore) posortowana po confidence (malejąco)
        """
        result = self.calculate_score_confidence_batch(match_id)
        sorted_scores = sorted(
            result.confidence_scores.items(),
            key=lambda x: x[1].confidence,
            reverse=True
        )
        return sorted_scores[:limit]
    
    def get_confidence_summary(
        self,
        match_id: str
    ) -> Dict[str, Any]:
        """
        Pobierz podsumowanie Confidence Score dla meczu
        
        Args:
            match_id: Identyfikator meczu
            
        Returns:
            Dict z podsumowaniem
        """
        result = self.calculate_score_confidence_batch(match_id)
        return result.to_dict()
    
    def clear_cache(self):
        """Wyczyść cache"""
        self._confidence_cache.clear()
        logger.info("[ConfidenceEngine] Cache wyczyszczony")


