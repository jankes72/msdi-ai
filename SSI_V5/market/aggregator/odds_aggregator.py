    def _cleanup_cache(self) -> None:
        """Czyści cache, pozostawiając ostatnie elementy"""
        with self._lock:
            # Keep oldest half
            raw_keys = list(self._raw_odds_cache.keys())
            if len(raw_keys) > self.max_cache_size:
                keys_to_remove = raw_keys[:len(raw_keys) // 2]
                for key in keys_to_remove:
                    del self._raw_odds_cache[key]
                    # Also remove from history
                    if len(self._raw_odds_history) > self.max_cache_size:
                        self._raw_odds_history = self._raw_odds_history[len(self._raw_odds_history) // 2:]
    
