    # VALUE DETECTION (Podstawa dla MarketTrendsAnalyzer)
    # ========================================================================
    
    def detect_value_betting_opportunities(
        self,
        aggregated: AggregatedOdds,
        threshold: float = 0.10
    ) -> Dict[str, Dict[str, float]]:
        """
        Wykrywa okazje value betting.
        
        Args:
            aggregated: Zagregowane kursy
            threshold: Próg EV do wykrycia okazji (domyślnie 10%)
            
        Returns:
            Dict[outcome, metrics]
        """
        opportunities = {}
        
        for outcome, odds in aggregated.aggregated_values.items():
            if odds <= 0:
                continue
            
            # Oblicz fair probability
            fair_prob = 1.0 / odds
            fair_odds = aggregated.fair_odds.get(outcome, odds)
            fair_prob_from_odds = 1.0 / fair_odds if fair_odds > 0 else 0
            
            # Expected Value: EV = (fair_odds * probability) - 1
            ev = (fair_odds * fair_prob) - 1
            
            # Value Rating (procentowyEV)
            value_rating = ev * 100
            
            if value_rating > threshold:
                opportunities[outcome] = {
                    'odds': odds,
                    'fair_odds': fair_odds,
                    'fair_probability': fair_prob_from_odds,
                    'expected_value': ev,
                    'value_rating': value_rating,
                    'confidence': aggregated.confidence_score,
                    'overround': aggregated.overround.get(outcome, 0),
                    'std_deviation': aggregated.std_deviation.get(outcome, 0)
                }
        
        return opportunities
    
    def detect_arbitrage_opportunities(
        self,
        match_id: str,
        market_type: MarketType = MarketType.MATCH_RESULT
    ) -> Dict[str, Dict[str, float]]:
        """
        Wykrywa okazje arbitrażowe (sure bets).
        
        Args:
            match_id: ID meczu
            market_type: Typ rynku
            
        Returns:
            Dict[combination, metrics]
        """
        arbitrages = {}
        
        try:
            # Pobierz wszystkie surowe dane dla tego meczu
            raw_odds_list = []
            for cache_key, raw_odds in self._raw_odds_cache.items():
                if (raw_odds.match_id == match_id and 
                    raw_odds.market_type == market_type and
                    raw_odds.is_valid):
                    raw_odds_list.append(raw_odds)
            
            if len(raw_odds_list) < 2:
                return arbitrages
            
            # Znajdź najlepsze kursy z różnych źródeł
            best_odds_by_source = defaultdict(dict)
            for raw_odds in raw_odds_list:
                for outcome, odds in raw_odds.odds_data.items():
                    if outcome not in best_odds_by_source[raw_odds.source] or \
                       odds > best_odds_by_source[raw_odds.source][outcome]:
                        best_odds_by_source[raw_odds.source][outcome] = odds
            
            # Poszukaj kombinacji z różnych źródeł
            sources = list(best_odds_by_source.keys())
            for i, source1 in enumerate(sources):
                for j, source2 in enumerate(sources):
                    if i >= j:
                        continue
                    
                    # Check all outcomes combination
                    if len(best_odds_by_source[source1]) + len(best_odds_by_source[source2]) >= 3:
                        # Calculate total probability
                        total_prob = 0
                        for source_outcomes in [best_odds_by_source[source1], best_odds_by_source[source2]]:
                            for outcome, odds in source_outcomes.items():
                                total_prob += 1.0 / odds
                        
                        # If total probability < 1, arbitrage exists
                        if total_prob < 0.99:  # Small margin
                            profit_percent = ((1.0 / total_prob) - 1.0) * 100
                            arbitrages[f"{source1.value}_{source2.value}"] = {
                                'profit_percent': profit_percent,
                                'total_probability': total_prob,
                                'source1': source1.value,
                                'source2': source2.value
                            }
            
        except Exception as e:
            # Log error but don't crash
            pass
        
        return arbitrages
    
