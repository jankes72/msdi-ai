class OddsAggregator:
    """
    Główna klasa agregująca kursy z wielu źródeł.
    
    Funkcjonalności:
    - Zbiór kursów z różnych bookmakerów
    - Agregacja z użyciem różnych metod (średnia, ważona, mediana, itp.)
    - Obliczanie fair odds i overround
    - Wykrywanie wartości (value detection)
    - Monitorowanie ruchów kursowych
    """
    
    def __init__(
        self,
        data_dir: str = None,
        cache_enabled: bool = True,
        max_cache_size: int = 1000
    ):
        """
        Inicjalizacja OddsAggregator.
        
        Args:
            data_dir: Katalog do zapisywania danych
            cache_enabled: Włącz buforowanie
            max_cache_size: Maksymalny rozmiar cache
        """
        if data_dir is None:
            from ...config.path_config import PathConfig
            data_dir = PathConfig.MARKET_DATA_DIR
        
        self.data_dir = data_dir
        self.cache_enabled = cache_enabled
        self.max_cache_size = max_cache_size
        
        # Cache
        self._raw_odds_cache: Dict[str, RawOddsData] = {}
        self._aggregated_cache: Dict[str, AggregatedOdds] = {}
        self._movement_cache: Dict[str, OddsMovement] = {}
        
        # Lock dla bezpieczeństwa wątkowego
        self._lock = RLock()
        
        # Historia
        self._raw_odds_history: List[RawOddsData] = []
        self._aggregation_history: List[AggregatedOdds] = []
        
        # Statystyki
        self.stats = {
            'total_aggregations': 0,
            'total_sources': 0,
            'last_aggregation': None
        }
        
        # Tworzymy katalog danych
        os.makedirs(self.data_dir, exist_ok=True)
        
        # Wczytanie danych z dysku (jeśli istnieją)
        self._load_from_disk()
    
    # ========================================================================
    # CORE FUNCTIONS
    # ========================================================================
    
    def add_raw_odds(
        self,
        raw_odds: RawOddsData
    ) -> str:
        """
        Dodaje surowe dane kursowe.
        
        Args:
            raw_odds: Obiekt RawOddsData
            
        Returns:
            ID dodanych danych
        """
        with self._lock:
            # Walidacja
            if not raw_odds.is_valid:
                raise ValueError(f"Invalid odds data: {raw_odds.validation_error}")
            
            # Generuj klucz cache
            cache_key = self._generate_cache_key(raw_odds)
            
            # Zapisz w cache
            if self.cache_enabled:
                self._raw_odds_cache[cache_key] = raw_odds
                self._raw_odds_history.append(raw_odds)
                
                # Ograniczenie rozmiaru cache
                if len(self._raw_odds_cache) > self.max_cache_size:
                    self._cleanup_cache()
            
            # Zapisz na dysk (opcjonalnie)
            self._save_to_disk(raw_odds)
            
            self.stats['total_sources'] += 1
            
            return cache_key
    
    def aggregate_odds(
        self,
        match_id: str,
        market_type: MarketType = MarketType.MATCH_RESULT,
        aggregation_method: AggregationMethod = AggregationMethod.WEIGHTED_AVERAGE,
        source_filter: List[OddsSource] = None
    ) -> AggregatedOdds:
        """
        Agreguje kursy z wielu źródeł.
        
        Args:
            match_id: ID meczu
            market_type: Typ rynku
            aggregation_method: Metoda agregacji
            source_filter: Filtrowanie źródeł (opcjonalnie)
            
        Returns:
            Obiekt AggregatedOdds
        """
        with self._lock:
            # Znajdź wszystkie surowe dane dla tego meczu i rynku
            matching_odds = []
            for cache_key, raw_odds in self._raw_odds_cache.items():
                if (raw_odds.match_id == match_id and 
                    raw_odds.market_type == market_type and
                    raw_odds.is_valid):
                    
                    if source_filter is None or raw_odds.source in source_filter:
                        matching_odds.append(raw_odds)
            
            if not matching_odds:
                raise ValueError(f"No valid odds data found for match {match_id}, market {market_type}")
            
            # Wykonaj agregację
            aggregated = self._perform_aggregation(
                matching_odds, 
                aggregation_method
            )
            
            # Oblicz dodatkowe metryki
            self._calculate_additional_metrics(aggregated, matching_odds)
            
            # Zapisz w cache
            cache_key = f"{match_id}_{market_type.value}_{aggregation_method.value}"
            if self.cache_enabled:
                self._aggregated_cache[cache_key] = aggregated
                self._aggregation_history.append(aggregated)
            
            self.stats['total_aggregations'] += 1
            self.stats['last_aggregation'] = datetime.now().isoformat()
            
            return aggregated
    
    def _perform_aggregation(
        self,
        raw_odds_list: List[RawOddsData],
        method: AggregationMethod
    ) -> AggregatedOdds:
        """Wywkonuje agregację według wybranej metody"""
        
        if not raw_odds_list:
            raise ValueError("Empty odds list")
        
        # Zebranie wszystkich outcome'ów
        all_outcomes = set()
        for raw_odds in raw_odds_list:
            all_outcomes.update(raw_odds.odds_data.keys())
        
        # Inicjalizacja
        aggregated_values = {}
        min_odds = {outcome: float('inf') for outcome in all_outcomes}
        max_odds = {outcome: 0.0 for outcome in all_outcomes}
        all_odds_by_outcome = defaultdict(list)
        
        # Zebranie danych
        for raw_odds in raw_odds_list:
            for outcome, odds in raw_odds.odds_data.items():
                all_odds_by_outcome[outcome].append({
                    'odds': odds,
                    'weight': raw_odds.weight,
                    'source': raw_odds.source
                })
                min_odds[outcome] = min(min_odds[outcome], odds)
                max_odds[outcome] = max(max_odds[outcome], odds)
        
        # Agregacja
        for outcome, odds_list in all_odds_by_outcome.items():
            odds_values = [item['odds'] for item in odds_list]
            weights = [item['weight'] for item in odds_list]
            
            if method == AggregationMethod.SIMPLE_AVERAGE:
                aggregated_values[outcome] = float(statistics.mean(odds_values))
            
            elif method == AggregationMethod.WEIGHTED_AVERAGE:
                total_weight = sum(weights)
                weighted_sum = sum(o * w for o, w in zip(odds_values, weights))
                aggregated_values[outcome] = weighted_sum / total_weight if total_weight > 0 else 0.0
            
            elif method == AggregationMethod.HIGHEST:
                aggregated_values[outcome] = max(odds_values)
            
            elif method == AggregationMethod.LOWEST:
                aggregated_values[outcome] = min(odds_values)
            
            elif method == AggregationMethod.MEDIAN:
                aggregated_values[outcome] = float(statistics.median(odds_values))
            
            elif method == AggregationMethod.HARMONIC_MEAN:
                aggregated_values[outcome] = float(statistics.harmonic_mean(odds_values))
            
            elif method == AggregationMethod.BEST_VALUE:
                # Najlepsza wartość (EV) - do implementacji w MarketTrendsAnalyzer
                aggregated_values[outcome] = max(odds_values)
        
        # Utwórz agregowany obiekt
        aggregated = AggregatedOdds(
            match_id=raw_odds_list[0].match_id,
            market_type=raw_odds_list[0].market_type,
            aggregation_method=method,
            aggregated_values=aggregated_values,
            source_count=len(raw_odds_list),
            min_odds=min_odds,
            max_odds=max_odds,
            sources=[r.source for r in raw_odds_list],
            source_weights={r.source: r.weight for r in raw_odds_list},
            timestamp=datetime.now()
        )
        
        return aggregated
    
    def _calculate_additional_metrics(
        self,
        aggregated: AggregatedOdds,
        raw_odds_list: List[RawOddsData]
    ) -> None:
        """Oblicza dodatkowe metryki (odchylenie, overround, fair odds)"""
        
        # Odchylenie standardowe
        for outcome in aggregated.aggregated_values.keys():
            odds_values = []
            for raw_odds in raw_odds_list:
                if outcome in raw_odds.odds_data:
                    odds_values.append(raw_odds.odds_data[outcome])
            
            if len(odds_values) >= 2:
                aggregated.std_deviation[outcome] = float(statistics.stdev(odds_values))
                aggregated.variance[outcome] = aggregated.std_deviation[outcome] ** 2
            else:
                aggregated.std_deviation[outcome] = 0.0
                aggregated.variance[outcome] = 0.0
        
        # Fair odds (na podstawie prawdopodobieństwa)
        self._calculate_fair_odds(aggregated)
        
        # Overround (margin bookmakerów)
        self._calculate_overround(aggregated)
        
        # Confidence score
        aggregated.confidence_score = self._calculate_confidence_score(aggregated, raw_odds_list)
    
    def _calculate_fair_odds(self, aggregated: AggregatedOdds) -> None:
        """Oblicza fair odds na podstawie agregowanych wartości"""
        total_probability = 0.0
        
        for outcome, odds in aggregated.aggregated_values.items():
            # Konwersja odds na probability
            probability = 1.0 / odds if odds > 0 else 0.0
            aggregated.fair_odds[outcome] = 1.0 / probability if probability > 0 else float('inf')
            total_probability += probability
        
        # Normalizacja (bookmakers pozwalają na total_probability < 1)
        if total_probability > 0:
            for outcome in aggregated.fair_odds:
                prob = (1.0 / aggregated.fair_odds[outcome]) if aggregated.fair_odds[outcome] > 0 else 0
                normalized_prob = prob / total_probability
                aggregated.fair_odds[outcome] = 1.0 / normalized_prob if normalized_prob > 0 else float('inf')
    
    def _calculate_overround(self, aggregated: AggregatedOdds) -> None:
        """Oblicza overround (margin bukmachera)"""
        total_probability = sum(
            1.0 / odds for odds in aggregated.aggregated_values.values() 
            if odds > 0
        )
        
        # Overround = 1 - total_probability (im wyższy, tym gorsze kursy)
        overall_overround = max(0, total_probability - 1) * 100
        
        for outcome in aggregated.aggregated_values:
            aggregated.overround[outcome] = overall_overround
    
    def _calculate_confidence_score(
        self,
        aggregated: AggregatedOdds,
        raw_odds_list: List[RawOddsData]
    ) -> float:
        """Oblicza confidence score agregacji"""
        if not raw_odds_list:
            return 0.0
        
        # Czynniki wpływające na confidence:
        # 1. Liczba źródeł
        source_count_factor = min(1.0, len(raw_odds_list) / 10)  # max at 10 sources
        
        # 2. Zgodność między źródłami (niższe std_dev = wyższy confidence)
        avg_std_dev = sum(aggregated.std_deviation.values()) / max(1, len(aggregated.std_deviation))
        std_dev_factor = max(0, 1.0 - (avg_std_dev / 2.0))  # Normalizacja
        
        # 3. Waga źródeł (im wyższa średnia waga, tym lepszy confidence)
        avg_weight = sum(r.weight for r in raw_odds_list) / len(raw_odds_list)
        weight_factor = min(1.0, avg_weight / 2.0)  # Normalizacja
        
        # 4. Overround (niższy overround = wyższy confidence)
        avg_overround = sum(aggregated.overround.values()) / max(1, len(aggregated.overround))
        overround_factor = max(0, 1.0 - (avg_overround / 20))  # 20% to max overround
        
        # Średnia ważona
        confidence = (
            0.3 * source_count_factor +
            0.3 * std_dev_factor +
            0.2 * weight_factor +
            0.2 * overround_factor
        )
        
        return round(confidence, 4)
    
