@dataclass
class OddsMovement:
    """Ruch kursów w czasie"""
    match_id: str
    market_type: MarketType
    outcome: str
    
    # Historia kursów
    timestamp_history: List[datetime] = field(default_factory=list)
    odds_history: List[float] = field(default_factory=list)
    source_history: List[OddsSource] = field(default_factory=list)
    
    # Analiza ruchu
    current_odds: float = 0.0
    previous_odds: float = 0.0
    change_percent: float = 0.0
    change_absolute: float = 0.0
    
    # Trend
    trend_direction: str = "STABLE"  # UP, DOWN, STABLE, VOLATILE
    trend_strength: float = 0.0      # 0-1
    volatility: float = 0.0            # odchylenie standardowe
    
    # Alerty
    significant_movement: bool = False
    arbitrage_opportunity: bool = False
    value_emerging: bool = False
    
    def calculate_trend(self) -> None:
        """Oblicza parametry trendowe"""
        if len(self.odds_history) < 2:
            self.trend_direction = "STABLE"
            self.trend_strength = 0.0
            self.volatility = 0.0
            return
        
        # Oblicz zmianę
        if len(self.odds_history) >= 2:
            self.previous_odds = self.odds_history[-2]
            self.current_odds = self.odds_history[-1]
            self.change_absolute = self.current_odds - self.previous_odds
            self.change_percent = (self.change_absolute / self.previous_odds) * 100 if self.previous_odds > 0 else 0
        
        # Kierunek trendu
        if self.change_absolute > 0.1:
            self.trend_direction = "UP"
        elif self.change_absolute < -0.1:
            self.trend_direction = "DOWN"
        else:
            self.trend_direction = "STABLE"
        
        # Siła trendu
        recent_changes = []
        for i in range(1, min(5, len(self.odds_history))):
            change = self.odds_history[-i] - self.odds_history[-i-1]
            recent_changes.append(change)
        
        if recent_changes:
            self.trend_strength = min(1.0, abs(sum(recent_changes) / len(recent_changes)))
        
        # Volatility
        if len(self.odds_history) >= 3:
            self.volatility = float(np.std(self.odds_history))
        
        # Alerty
        self.significant_movement = abs(self.change_percent) > 10  # >10% change
        self.arbitrage_opportunity = self.current_odds > self.previous_odds * 1.2  # >20% increase
    
    def to_dict(self) -> Dict[str, Any]:
        return {
            'match_id': self.match_id,
            'market_type': self.market_type.value,
            'outcome': self.outcome,
            'current_odds': self.current_odds,
            'previous_odds': self.previous_odds,
            'change_percent': round(self.change_percent, 2),
            'change_absolute': round(self.change_absolute, 4),
            'trend_direction': self.trend_direction,
            'trend_strength': round(self.trend_strength, 4),
            'volatility': round(self.volatility, 4),
            'significant_movement': self.significant_movement,
            'arbitrage_opportunity': self.arbitrage_opportunity,
            'value_emerging': self.value_emerging,
            'history': [
                {
                    'timestamp': t.isoformat(),
                    'odds': o,
                    'source': s.value
                } 
                for t, o, s in zip(self.timestamp_history, self.odds_history, self.source_history)
            ]
        }


