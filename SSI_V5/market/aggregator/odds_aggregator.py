    def convert_odds_format(
        self,
        odds: float,
        from_format: OddsType,
        to_format: OddsType
    ) -> float:
        """Konwertuje format kursów"""
        
        if from_format == to_format:
            return odds
        
        # Convert to decimal first
        if from_format == OddsType.FRACTIONAL:
            # Format: "a/b" or a/b
            if isinstance(odds, str) and '/' in odds:
                num, denom = map(float, odds.split('/'))
                decimal = (num / denom) + 1
            else:
                decimal = float(odds)
        elif from_format == OddsType.AMERICAN:
            if odds > 0:
                decimal = (odds / 100) + 1
            else:
                decimal = (100 / abs(odds)) + 1
        else:
            decimal = float(odds)
        
        # Convert from decimal to target
        if to_format == OddsType.FRACTIONAL:
            if decimal > 1:
                numerator = int((decimal - 1) * 100)
                denominator = 100
                # Simplify fraction
                gcd_val = np.gcd(numerator, denominator)
                return f"{numerator//gcd_val}/{denominator//gcd_val}"
            return "0/1"
        elif to_format == OddsType.AMERICAN:
            if decimal >= 2:
                return (decimal - 1) * 100
            else:
                return -100 / (decimal - 1)
        else:
            return decimal
    
    def get_all_matches(self) -> List[str]:
        """Zwraca listę wszystkich meczów z danymi"""
        with self._lock:
            return list(set(
                raw_odds.match_id 
                for raw_odds in self._raw_odds_cache.values()
                if raw_odds.is_valid
            ))
    
    def get_market_types(self, match_id: str) -> List[MarketType]:
        """Zwraca dostępne typy rynków dla meczu"""
        with self._lock:
            market_types = set()
            for raw_odds in self._raw_odds_cache.values():
                if raw_odds.match_id == match_id and raw_odds.is_valid:
                    market_types.add(raw_odds.market_type)
            return list(market_types)
    
    def get_sources(self, match_id: str, market_type: MarketType = None) -> List[OddsSource]:
        """Zwraca dostępne źródła dla meczu (i opcjonalnie rynku)"""
        with self._lock:
            sources = set()
            for raw_odds in self._raw_odds_cache.values():
                if raw_odds.match_id == match_id and raw_odds.is_valid:
                    if market_type is None or raw_odds.market_type == market_type:
                        sources.add(raw_odds.source)
            return list(sources)
    
    def get_statistics(self) -> Dict[str, Any]:
        """Zwraca statystyki agregatora"""
        with self._lock:
            return {
                **self.stats,
                'cache_size': len(self._raw_odds_cache),
                'aggregation_cache_size': len(self._aggregated_cache),
                'movement_cache_size': len(self._movement_cache),
                'unique_matches': len(self.get_all_matches())
            }
    
    def clear_cache(self) -> None:
        """Czyści wszystkie cache"""
        with self._lock:
            self._raw_odds_cache.clear()
            self._aggregated_cache.clear()
            self._movement_cache.clear()
            self._raw_odds_history.clear()
            self._aggregation_history.clear()
