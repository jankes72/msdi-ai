    def _generate_cache_key(self, raw_odds: RawOddsData) -> str:
        """Generuje unikalny klucz cache"""
        return f"{raw_odds.match_id}_{raw_odds.market_type.value}_{raw_odds.source.value}_{raw_odds.timestamp.timestamp()}"
    
    def _save_to_disk(self, data: Any) -> None:
        """Zapisuje dane na dysk"""
        try:
            if not self.data_dir:
                return
            
            # Separate directories for different data types
            if isinstance(data, RawOddsData):
                subdir = "raw_odds"
            elif isinstance(data, AggregatedOdds):
                subdir = "aggregated"
            elif isinstance(data, OddsMovement):
                subdir = "movements"
            else:
                return
            
            subdir_path = os.path.join(self.data_dir, subdir)
            os.makedirs(subdir_path, exist_ok=True)
            
            # Save individual file
            timestamp_str = datetime.now().strftime("%Y%m%d_%H%M%S")
            if isinstance(data, RawOddsData):
                filename = f"{data.match_id}_{data.source.value}_{timestamp_str}.json"
            else:
                filename = f"{timestamp_str}_{hash(str(data)) % 10000}.json"
            
            filepath = os.path.join(subdir_path, filename)
            
            with open(filepath, 'w', encoding='utf-8') as f:
                json.dump(data.to_dict(), f, ensure_ascii=False, indent=2)
            
        except Exception:
            pass  # Don't crash on save error
    
    def _load_from_disk(self) -> None:
        """Wczytuje dane z dysku"""
        try:
            if not self.data_dir or not os.path.exists(self.data_dir):
                return
            
            # Load raw odds
            raw_dir = os.path.join(self.data_dir, "raw_odds")
            if os.path.exists(raw_dir):
                for filename in os.listdir(raw_dir):
                    if filename.endswith('.json'):
                        filepath = os.path.join(raw_dir, filename)
                        with open(filepath, 'r', encoding='utf-8') as f:
                            data = json.load(f)
                            raw_odds = RawOddsData.from_dict(data)
                            self._raw_odds_cache[self._generate_cache_key(raw_odds)] = raw_odds
                            self._raw_odds_history.append(raw_odds)
            
            # Load aggregated odds
            agg_dir = os.path.join(self.data_dir, "aggregated")
            if os.path.exists(agg_dir):
                for filename in os.listdir(agg_dir):
                    if filename.endswith('.json'):
                        filepath = os.path.join(agg_dir, filename)
                        with open(filepath, 'r', encoding='utf-8') as f:
                            data = json.load(f)
                            aggregated = AggregatedOdds.from_dict(data)
                            cache_key = f"{aggregated.match_id}_{aggregated.market_type.value}_{aggregated.aggregation_method.value}"
                            self._aggregated_cache[cache_key] = aggregated
                            self._aggregation_history.append(aggregated)
            
        except Exception:
            pass  # Don't crash on load error
    
