    def track_odds_movement(
        self,
        match_id: str,
        market_type: MarketType,
        outcome: str,
        current_odds: float,
        source: OddsSource,
        timestamp: datetime = None
    ) -> OddsMovement:
        """
        Smledzenie ruchu kursu w czasie.
        
        Args:
            match_id: ID meczu
            market_type: Typ rynku
            outcome: Wyjście (np. "HOME_WIN")
            current_odds: Aktualny kurs
            source: Źródło kursu
            timestamp: Czas (domyślnie teraz)
            
        Returns:
            Obiekt OddsMovement
        """
        with self._lock:
            cache_key = f"{match_id}_{market_type.value}_{outcome}"
            
            if cache_key not in self._movement_cache:
                movement = OddsMovement(
                    match_id=match_id,
                    market_type=market_type,
                    outcome=outcome
                )
                self._movement_cache[cache_key] = movement
            else:
                movement = self._movement_cache[cache_key]
            
            # Dodaj nową wartość
            if timestamp is None:
                timestamp = datetime.now()
            
            movement.timestamp_history.append(timestamp)
            movement.odds_history.append(current_odds)
            movement.source_history.append(source)
            movement.current_odds = current_odds
            
            # Aktualizuj trend
            movement.calculate_trend()
            
            return movement
    
    def get_odds_movement(
        self,
        match_id: str,
        market_type: MarketType = MarketType.MATCH_RESULT,
        outcome: str = None
    ) -> Dict[str, OddsMovement]:
        """Pobiera ruch kursów dla meczu"""
        with self._lock:
            result = {}
            pattern = f"{match_id}_{market_type.value}"
            
            for cache_key, movement in self._movement_cache.items():
                if cache_key.startswith(pattern):
                    if outcome is None or movement.outcome == outcome:
                        result[movement.outcome] = movement
            
            return result
    
