    def predict_odds_movement(
        self,
        match_id: str,
        market_type: str = "match_result",
        outcome: str = None,
        steps_ahead: int = 3
    ) -> Dict[str, Dict[str, Any]]:
        """
        Przewiduje ruch kursów.
        
        Args:
            match_id: ID meczu
            market_type: Typ rynku
            outcome: Konkretny outcome (opcjonalnie)
            steps_ahead: Ile kroków do przodu
            
        Returns:
            Dict[outcome, prediction_info]
        """
        predictions = {}
        
        # Analiza trendów
        analysis = self.analyze_trends(match_id, market_type)
        
        for out, trend in analysis.outcome_trends.items():
            if outcome and out != outcome:
                continue
            
            if trend.slope == 0:
                predictions[out] = {
                    'predicted_values': [trend.current_odds] * steps_ahead,
                    'confidence': 0.0,
                    'trend_type': trend.trend_type.value,
                    'message': 'No trend detected'
                }
                continue
            
            # Regresja wielomianowa
            try:
                # Przygotuj dane
                X = np.array([i for i in range(len(trend.odds_values))]).reshape(-1, 1)
                y = np.array(trend.odds_values)
                
                # Dopasuj model wielomianowy (stopień 2)
                poly = PolynomialFeatures(degree=2)
                X_poly = poly.fit_transform(X)
                
                from sklearn.linear_model import LinearRegression
                model = LinearRegression(fit_intercept=True)
                model.fit(X_poly, y)
                
                # Przewiduj
                future_steps = [len(trend.odds_values) + i for i in range(1, steps_ahead + 1)]
                X_future = poly.transform(np.array(future_steps).reshape(-1, 1))
                predicted_values = model.predict(X_future).tolist()
                
                # Confidence na podstawie R^2
                r_squared = model.score(X_poly, y)
                confidence = min(0.95, max(0.0, r_squared))
                
                # Sprawdź czy prediction ma sens (tzn. jest dodatni)
                predicted_values = [max(1.01, p) for p in predicted_values]
                
                predictions[out] = {
                    'predicted_values': [float(p) for p in predicted_values],
                    'confidence': float(confidence),
                    'trend_type': trend.trend_type.value,
                    'slope': float(trend.slope),
                    'r_squared': float(trend.r_squared),
                    'current_odds': float(trend.current_odds),
                    'predicted_next': float(trend.predicted_next),
                    'message': f'Predicted based on {trend.trend_type.value} trend'
                }
            except Exception as e:
                predictions[out] = {
                    'predicted_values': [trend.current_odds] * steps_ahead,
                    'confidence': 0.0,
                    'trend_type': trend.trend_type.value,
                    'error': str(e),
                    'message': 'Prediction failed'
                }
        
        return predictions
    
    def detect_market_anomalies(
        self,
        match_id: str,
        market_type: str = "match_result",
        threshold_std: float = 2.0
    ) -> Dict[str, Dict[str, Any]]:
        """
        Wykrywa anomalie rynkowe.
        
        Args:
            match_id: ID meczu
            market_type: Typ rynku
            threshold_std: Próg odchylenia standardowego
            
        Returns:
            Dict[outcome, anomaly_info]
        """
        anomalies = {}
        
        try:
            analysis = self.analyze_trends(match_id, market_type)
            
            # Oblicz średnią i odchylenie standardowe dla całego rynku
            all_odds = []
            for trend in analysis.outcome_trends.values():
                all_odds.extend(trend.odds_values)
            
            if all_odds:
                mean_odds = statistics.mean(all_odds)
                std_odds = statistics.stdev(all_odds) if len(all_odds) > 1 else 0
            else:
                return anomalies
            
            # Sprawdź każdy trend
            for outcome, trend in analysis.outcome_trends.items():
                if not trend.odds_values:
                    continue
                
                current = trend.current_odds
                
                # Anomalia 1: Odchylenie od średniej
                z_score = abs(current - mean_odds) / std_odds if std_odds > 0 else 0
                
                if z_score > threshold_std:
                    anomalies[outcome] = {
                        'type': 'outlier',
                        'z_score': z_score,
                        'value': current,
                        'mean': mean_odds,
                        'std': std_odds,
                        'severity': min(1.0, z_score / 3.0),
                        'message': f"Outlier detected: {z_score:.2f} std deviations from mean"
                    }
                
                # Anomalia 2: Gwałtowne zmiany
                if len(trend.odds_values) >= 2:
                    recent_change = trend.odds_values[-1] - trend.odds_values[-2]
                    avg_change = statistics.mean([
                        trend.odds_values[i] - trend.odds_values[i-1] 
                        for i in range(1, len(trend.odds_values))
                    ]) if len(trend.odds_values) > 1 else 0
                    std_change = statistics.stdev([
                        trend.odds_values[i] - trend.odds_values[i-1] 
                        for i in range(1, len(trend.odds_values))
                    ]) if len(trend.odds_values) > 2 else 0
                    
                    if std_change > 0:
                        change_z_score = abs(recent_change - avg_change) / std_change
                        
                        if change_z_score > 2.5:
                            anomalies[outcome] = {
                                'type': 'sharp_movement',
                                'z_score': change_z_score,
                                'change': recent_change,
                                'message': f"Sharp movement: {change_z_score:.2f} std deviations from average change"
                            }
            
            # Anomalia 3: Niskie korelacje (możliwa błęędna cena)
            for outcome, corr_dict in analysis.correlations.items():
                avg_corr = statistics.mean(list(corr_dict.values())) if corr_dict else 0
                
                if avg_corr < -0.3:  # Ujemna korelacja ( nietypowe)
                    if outcome not in anomalies or anomalies[outcome]['severity'] < 0.7:
                        anomalies[outcome] = {
                            'type': 'negative_correlation',
                            'avg_correlation': avg_corr,
                            'message': f"Unusually low correlation with other outcomes ({avg_corr:.3f})"
                        }
        
        except Exception:
            pass
        
        return anomalies
    
