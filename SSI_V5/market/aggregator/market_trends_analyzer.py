class MarketTrendsAnalyzer:
    """
    Główna klasa do analizy trendów rynkowych i kursowych.
    
    Funkcjonalności:
    - Analiza trendów historycznych
    - Predykcja kierunku ruchu kursów
    - Wykrywanie sygnałówValue betting
    - Wykrywanie anomalii i szans arbitrażowych
    - Integracja z OddsAggregator
    """
    
    def __init__(
        self,
        odds_aggregator: 'OddsAggregator' = None,
        data_dir: str = None,
        max_history: int = 1000,
        min_data_points: int = 5
    ):
        """
        Inicjalizacja MarketTrendsAnalyzer.
        
        Args:
            odds_aggregator: Powiązany OddsAggregator
            data_dir: Katalog do zapisywania danych
            max_history: Maksymalna historia trendów
            min_data_points: Minimalna liczba punktów do analizy
        """
        self.odds_aggregator = odds_aggregator
        self.min_data_points = min_data_points
        
        if data_dir is None:
            from ..config.path_config import PathConfig
            data_dir = PathConfig.MARKET_DATA_DIR
        
        self.data_dir = os.path.join(data_dir, "trends")
        self.max_history = max_history
        
        # Cache
        self._trend_cache: Dict[str, TrendData] = {}
        self._analysis_cache: Dict[str, MarketTrendAnalysis] = {}
        self._signal_cache: Dict[str, MarketSignal] = {}
        
        # Historia
        self._trend_history: List[TrendData] = []
        self._analysis_history: List[MarketTrendAnalysis] = []
        
        # Lock dla bezpieczeństwa wątkowego
        self._lock = RLock()
        
        # Statystyki
        self.stats = {
            'total_analyses': 0,
            'total_signals': 0,
            'total_recommendations': 0
        }
        
        # Tworzymy katalog danych
        os.makedirs(self.data_dir, exist_ok=True)
        
        # Wczytanie danych z dysku
        self._load_from_disk()
    
    # ========================================================================
    # CORE ANALYSIS FUNCTIONS
    # ========================================================================
    
    def analyze_trends(
        self,
        match_id: str,
        market_type: str = "match_result",
        timeframe: TimeFrame = TimeFrame.MEDIUM_TERM
    ) -> MarketTrendAnalysis:
        """
        Wykonająckompleksową analizę trendów.
        
        Args:
            match_id: ID meczu
            market_type: Typ rynku
            timeframe: Rama czasowa analizy
            
        Returns:
            Obiekt MarketTrendAnalysis
        """
        import time
        start_time = time.time()
        
        with self._lock:
            # 1. Pobierz historię kursów z OddsAggregator
            if self.odds_aggregator:
                movement_data = self.odds_aggregator.get_odds_movement(
                    match_id, 
                    self._convert_market_type(market_type)
                )
            else:
                raise ValueError("OddsAggregator not configured")
            
            if not movement_data:
                raise ValueError(f"No movement data found for {match_id}")
            
            # 2. Utwórz i przeanalizuj trendy per-outcome
            outcome_trends = {}
            all_timestamps = set()
            
            for outcome, movement in movement_data.items():
                trend_data = self._create_trend_data(
                    match_id, 
                    market_type, 
                    outcome, 
                    movement
                )
                
                if len(trend_data.odds_values) >= self.min_data_points:
                    self._analyze_trend(trend_data)
                    outcome_trends[outcome] = trend_data
                    all_timestamps.update(trend_data.timestamps)
            
            if not outcome_trends:
                raise ValueError(f"Insufficient data points for analysis (need >= {self.min_data_points})")
            
            # 3. Oblicz korelacje między outcome'ami
            correlations = self._calculate_correlations(outcome_trends)
            
            # 4. Oblicz ogólne statystyki rynku
            overall_trend, market_condition = self._determine_overall_trend(outcome_trends)
            
            # 5. Wygeneruj sygnały
            signals = self._generate_signals(outcome_trends, correlations)
            
            # 6. Wygeneruj rekomendacje
            recommendations = self._generate_recommendations(
                outcome_trends, correlations, signals
            )
            
            # 7. Utwórz analizę
            analysis = MarketTrendAnalysis(
                match_id=match_id,
                market_type=market_type,
                overall_trend=overall_trend,
                market_condition=market_condition,
                outcome_trends=outcome_trends,
                correlations=correlations,
                signals=signals,
                recommendations=recommendations,
                analysis_duration=time.time() - start_time,
                data_points=len(all_timestamps)
            )
            
            # 8. Zapisz w cache i historii
            cache_key = f"{match_id}_{market_type}_{timeframe.value}"
            self._analysis_cache[cache_key] = analysis
            self._analysis_history.append(analysis)
            
            # 9. Ograniczenie historii
            if len(self._analysis_history) > self.max_history:
                self._analysis_history = self._analysis_history[-self.max_history:]
            
            self.stats['total_analyses'] += 1
            self.stats['total_signals'] += len(signals)
            self.stats['total_recommendations'] += len(recommendations)
            
            return analysis
    
    def _create_trend_data(
        self,
        match_id: str,
        market_type: str,
        outcome: str,
        movement: 'OddsMovement'
    ) -> TrendData:
        """Tworzy TrendData z OddsMovement"""
        trend = TrendData(
            match_id=match_id,
            market_type=market_type,
            outcome=outcome,
            timestamps=movement.timestamp_history[:],
            odds_values=movement.odds_history[:],
            current_odds=movement.current_odds
        )
        
        # Oblicz statystyki
        if trend.odds_values:
            trend.mean = float(statistics.mean(trend.odds_values))
            trend.min_odds = min(trend.odds_values)
            trend.max_odds = max(trend.odds_values)
            
            if len(trend.odds_values) >= 2:
                trend.std_dev = float(statistics.stdev(trend.odds_values))
            else:
                trend.std_dev = 0.0
        
        return trend
    
    def _analyze_trend(self, trend: TrendData) -> None:
        """Analizuje pojedynczy trend"""
        if len(trend.odds_values) < 2:
            trend.trend_type = TrendType.STABLE
            trend.trend_strength = 0.0
            return
        
        # 1. Oblicz resume regresji liniowej
        X = np.array([i for i in range(len(trend.odds_values))]).reshape(-1, 1)
        y = np.array(trend.odds_values)
        
        try:
            model = LinearRegression(fit_intercept=True)
            model.fit(X, y)
            trend.slope = model.coef_[0]
            trend.r_squared = model.score(X, y)
        except:
            trend.slope = 0.0
            trend.r_squared = 0.0
        
        # 2. Predykcja następnej wartości
        if trend.slope != 0:
            next_x = len(trend.odds_values)
            trend.predicted_next = float(model.predict([[next_x]])[0])
        else:
            trend.predicted_next = trend.current_odds
        
        # 3. Predykcja confidence
        if trend.r_squared > 0.7:
            trend.prediction_confidence = min(1.0, trend.r_squared)
        elif trend.r_squared > 0.3:
            trend.prediction_confidence = 0.5 + (trend.r_squared * 0.5)
        else:
            trend.prediction_confidence = trend.r_squared
        
        # 4. Określ typ trendu
        percent_change = abs(trend.slope / trend.mean) * 100 if trend.mean > 0 else 0
        
        if trend.slope > TREND_THRESHOLDS['strong']:
            trend.trend_type = TrendType.STRONG_UP
            trend.trend_strength = min(1.0, percent_change / 30)
        elif trend.slope > TREND_THRESHOLDS['moderate']:
            trend.trend_type = TrendType.MODERATE_UP
            trend.trend_strength = min(1.0, percent_change / 15)
        elif trend.slope > TREND_THRESHOLDS['weak']:
            trend.trend_type = TrendType.WEAK_UP
            trend.trend_strength = min(1.0, percent_change / 5)
        elif trend.slope < -TREND_THRESHOLDS['strong']:
            trend.trend_type = TrendType.STRONG_DOWN
            trend.trend_strength = min(1.0, abs(percent_change) / 30)
        elif trend.slope < -TREND_THRESHOLDS['moderate']:
            trend.trend_type = TrendType.MODERATE_DOWN
            trend.trend_strength = min(1.0, abs(percent_change) / 15)
        elif trend.slope < -TREND_THRESHOLDS['weak']:
            trend.trend_type = TrendType.WEAK_DOWN
            trend.trend_strength = min(1.0, abs(percent_change) / 5)
        else:
            # Sprawdź zmienność
            if trend.std_dev > TREND_THRESHOLDS['volatile']:
                trend.trend_type = TrendType.VOLATILE
                trend.trend_strength = min(1.0, trend.std_dev / 2.0)
            elif trend.std_dev > TREND_THRESHOLDS['volatile'] / 2:
                trend.trend_type = TrendType.OSCILLATING
                trend.trend_strength = min(1.0, trend.std_dev)
            else:
                trend.trend_type = TrendType.STABLE
                trend.trend_strength = 0.0
    
    def _calculate_correlations(
        self, 
        outcome_trends: Dict[str, TrendData]
    ) -> Dict[str, Dict[str, float]]:
        """Oblicza korelacje między outcome'ami"""
        correlations = {}
        outcomes = list(outcome_trends.keys())
        
        for i, outcome1 in enumerate(outcomes):
            correlations[outcome1] = {}
            for outcome2 in outcomes[i+1:]:
                try:
                    values1 = outcome_trends[outcome1].odds_values
                    values2 = outcome_trends[outcome2].odds_values
                    
                    # Dopasuj długości
                    min_len = min(len(values1), len(values2))
                    if min_len >= 3:
                        vec1 = values1[-min_len:]
                        vec2 = values2[-min_len:]
                        corr = float(np.corrcoef(vec1, vec2)[0, 1])
                    else:
                        corr = 0.0
                    
                    correlations[outcome1][outcome2] = corr
                    correlations[outcome2][outcome1] = corr
                except:
                    correlations[outcome1][outcome2] = 0.0
                    correlations[outcome2][outcome1] = 0.0
        
        return correlations
    
    def _determine_overall_trend(
        self, 
        outcome_trends: Dict[str, TrendData]
    ) -> Tuple[TrendType, MarketCondition]:
        """Określa ogólny trend i warunek rynku"""
        if not outcome_trends:
            return TrendType.STABLE, MarketCondition.NORMAL
        
        # Badanie trendów
        up_trends = 0
        down_trends = 0
        stable_trends = 0
        volatile_trends = 0
        
        for trend in outcome_trends.values():
            if trend.trend_type in [TrendType.STRONG_UP, TrendType.MODERATE_UP, TrendType.WEAK_UP]:
                up_trends += 1
            elif trend.trend_type in [TrendType.STRONG_DOWN, TrendType.MODERATE_DOWN, TrendType.WEAK_DOWN]:
                down_trends += 1
            elif trend.trend_type == TrendType.STABLE:
                stable_trends += 1
            else:
                volatile_trends += 1
        
        total = up_trends + down_trends + stable_trends + volatile_trends
        
        # Określ ogólny trend
        if up_trends > down_trends and up_trends > stable_trends:
            if up_trends / total > 0.7:
                overall_trend = TrendType.STRONG_UP
            elif up_trends / total > 0.5:
                overall_trend = TrendType.MODERATE_UP
            else:
                overall_trend = TrendType.WEAK_UP
        elif down_trends > up_trends and down_trends > stable_trends:
            if down_trends / total > 0.7:
                overall_trend = TrendType.STRONG_DOWN
            elif down_trends / total > 0.5:
                overall_trend = TrendType.MODERATE_DOWN
            else:
                overall_trend = TrendType.WEAK_DOWN
        else:
            overall_trend = TrendType.STABLE
        
        # Określ warunek rynku
        avg_volatility = sum(
            t.std_dev for t in outcome_trends.values()
        ) / len(outcome_trends)
        
        if volatile_trends / total > 0.5:
            market_condition = MarketCondition.UNCERTAIN
        elif avg_volatility > TREND_THRESHOLDS['volatile']:
            market_condition = MarketCondition.SHARP_MOVEMENT
        elif up_trends > down_trends * 2:
            market_condition = MarketCondition.BULLISH
        elif down_trends > up_trends * 2:
            market_condition = MarketCondition.BEARISH
        else:
            market_condition = MarketCondition.NORMAL
        
        return overall_trend, market_condition
    
    def _generate_signals(
        self, 
        outcome_trends: Dict[str, TrendData],
        correlations: Dict[str, Dict[str, float]]
    ) -> List[Dict[str, Any]]:
        """Generuje sygnały na podstawie analizy trendów"""
        signals = []
        
        for outcome, trend in outcome_trends.items():
            # 1. Sygnał na podstawie trendaregresji
            if trend.slope != 0 and trend.prediction_confidence > 0.5:
                signal = self._create_trend_based_signal(trend)
                if signal:
                    signals.append(signal.to_dict())
            
            # 2. Sygnal na podstawie odchylenia od fair odds
            if self.odds_aggregator:
                try:
                    # Pobierz zagregowane dane
                    aggregated = self.odds_aggregator.aggregate_odds(
                        trend.match_id,
                        self._convert_market_type(trend.market_type)
                    )
                    
                    if outcome in aggregated.aggregated_values:
                        value_signal = self._create_value_based_signal(
                            trend, aggregated, outcome
                        )
                        if value_signal:
                            signals.append(value_signal.to_dict())
                except:
                    pass
            
            # 3. Sygnał na podstawie korelacji
            correlation_signal = self._create_correlation_based_signal(
                outcome, trend, correlations
            )
            if correlation_signal:
                signals.append(correlation_signal.to_dict())
        
        return signals
    
    def _create_trend_based_signal(self, trend: TrendData) -> Optional[MarketSignal]:
        """Tworzy sygnał na podstawie trendu"""
        if trend.slope == 0:
            return None
        
        # Określ typ sygnału
        if trend.slope < 0:  # Kurs spada (staje się bardziej atrakcyjny)
            if trend.trend_type in [TrendType.STRONG_DOWN, TrendType.MODERATE_DOWN]:
                signal_type = SignalType.STRONG_BUY
                strength = trend.trend_strength
            else:
                signal_type = SignalType.BUY
                strength = trend.trend_strength * 0.7
        else:  # Kurs rośnie (staje się mniej atrakcyjny)
            if trend.trend_type in [TrendType.STRONG_UP, TrendType.MODERATE_UP]:
                signal_type = SignalType.STRONG_SELL
                strength = trend.trend_strength
            else:
                signal_type = SignalType.SELL
                strength = trend.trend_strength * 0.7
        
        return MarketSignal(
            signal_type=signal_type,
            strength=strength,
            confidence=min(0.95, trend.prediction_confidence + 0.1),
            source_outcome=trend.outcome,
            current_odds=trend.current_odds,
            expected_odds=trend.predicted_next,
            expected_value=(trend.predicted_next - trend.current_odds) / trend.current_odds if trend.current_odds > 0 else 0,
            risk_level=self._assess_risk_level(trend),
            urgency=self._assess_urgency(trend),
            description=f"{signal_type.value.replace('_', ' ').title()} signal for {trend.outcome}",
            reasoning=f"Based on trend analysis: {trend.trend_type.value.replace('_', ' ')} ({trend.slope:.4f} slope)"
        )
    
    def _create_value_based_signal(
        self, 
        trend: TrendData,
        aggregated: 'AggregatedOdds',
        outcome: str
    ) -> Optional[MarketSignal]:
        """Tworzy sygnał na podstawie analizy value"""
        current_odds = aggregated.aggregated_values.get(outcome, 0)
        fair_odds = aggregated.fair_odds.get(outcome, current_odds)
        
        if current_odds <= 0 or fair_odds <= 0:
            return None
        
        # Oblicz EV
        prob = 1.0 / fair_odds if fair_odds > 0 else 0
        ev = (current_odds * prob) - 1
        value_rating = ev * 100
        
        # Określ typ sygnału
        if value_rating > 15:  # Wysoka wartość
            signal_type = SignalType.STRONG_BUY
            strength = min(1.0, value_rating / 30)
            confidence = min(0.95, aggregated.confidence_score + 0.1)
        elif value_rating > 5:  # Umiarkowana wartość
            signal_type = SignalType.BUY
            strength = min(1.0, value_rating / 15)
            confidence = min(0.90, aggregated.confidence_score)
        elif value_rating < -15:  # Przewartościowany
            signal_type = SignalType.STRONG_SELL
            strength = min(1.0, abs(value_rating) / 30)
            confidence = min(0.95, aggregated.confidence_score + 0.1)
        elif value_rating < -5:  # Lekko przewartościowany
            signal_type = SignalType.SELL
            strength = min(1.0, abs(value_rating) / 15)
            confidence = min(0.90, aggregated.confidence_score)
        else:
            return None  # Brak sygnału
        
        return MarketSignal(
            signal_type=signal_type,
            strength=strength,
            confidence=confidence,
            source_outcome=outcome,
            current_odds=current_odds,
            expected_odds=fair_odds,
            fair_odds=fair_odds,
            expected_value=ev,
            probability=prob,
            risk_level=self._assess_risk_level_from_odds(current_odds, aggregated),
            urgency=self._assess_urgency_from_ev(ev),
            description=f"{signal_type.value.replace('_', ' ').title()} signal for {outcome}",
            reasoning=f"Value analysis: EV={ev:.3f}, Value Rating={value_rating:.1f}%"
        )
    
    def _create_correlation_based_signal(
        self,
        outcome: str,
        trend: TrendData,
        correlations: Dict[str, Dict[str, float]]
    ) -> Optional[MarketSignal]:
        """Tworzy sygnał na podstawie korelacji"""
        if outcome not in correlations:
            return None
        
        # Znajdź najsilniejszą negatywną korelację
        strongest_negative_corr = 0
        correlated_outcome = None
        
        for other_outcome, corr in correlations[outcome].items():
            if corr < strongest_negative_corr and other_outcome != outcome:
                strongest_negative_corr = corr
                correlated_outcome = other_outcome
        
        # Jeśli silna negatywna korelacja i trend w dół
        if (strongest_negative_corr < -0.8 and 
            trend.trend_type in [TrendType.STRONG_DOWN, TrendType.MODERATE_DOWN]):
            
            other_trend = self._trend_cache.get(f"{trend.match_id}_{trend.market_type}_{correlated_outcome}")
            
            if other_trend and other_trend.trend_type in [TrendType.STRONG_UP, TrendType.MODERATE_UP]:
                return MarketSignal(
                    signal_type=SignalType.STRONG_BUY,
                    strength=0.8,
                    confidence=0.75,
                    source_outcome=outcome,
                    target_outcome=correlated_outcome,
                    current_odds=trend.current_odds,
                    description=f"Strong BUY signal: {outcome} and {correlated_outcome} are negatively correlated",
                    reasoning=f"Negative correlation ({strongest_negative_corr:.3f}) with opposite trends"
                )
        
        return None
    
    def _assess_risk_level(self, trend: TrendData) -> str:
        """Ocenia poziom ryzyka"""
        if trend.std_dev > TREND_THRESHOLDS['volatile']:
            return "very_high"
        elif trend.std_dev > TREND_THRESHOLDS['volatile'] / 2:
            return "high"
        elif trend.trend_strength > 0.7:
            return "medium"
        else:
            return "low"
    
    def _assess_risk_level_from_odds(self, odds: float, aggregated: 'AggregatedOdds') -> str:
        """Ocenia poziom ryzyka na podstawie kursów"""
        if odds > 5.0:
            return "very_high"  # Very long shot
        elif odds > 3.0:
            return "high"
        elif odds > 2.0:
            return "medium"
        else:
            return "low"
    
    def _assess_urgency(self, trend: TrendData) -> str:
        """Ocenia pilność"""
        if trend.trend_strength > 0.8:
            return "high"
        elif trend.trend_strength > 0.5:
            return "medium"
        else:
            return "low"
    
    def _assess_urgency_from_ev(self, ev: float) -> str:
        """Ocenia pilność na podstawie EV"""
        if abs(ev) > 0.2:
            return "high"
        elif abs(ev) > 0.1:
            return "medium"
        else:
            return "low"
    
    def _generate_recommendations(
        self,
        outcome_trends: Dict[str, TrendData],
        correlations: Dict[str, Dict[str, float]],
        signals: List[Dict[str, Any]]
    ) -> List[Dict[str, Any]]:
        """Generuje rekomendacje na podstawie sygnałów"""
        recommendations = []
        
        # Grupa sygnałów po typie
        signals_by_type = defaultdict(list)
        for signal_data in signals:
            signal = MarketSignal.from_dict(signal_data)
            signals_by_type[signal.signal_type].append(signal)
        
        # Rekomendacja ogólna
        buy_count = len(signals_by_type.get(SignalType.STRONG_BUY, [])) + \
                    len(signals_by_type.get(SignalType.BUY, []))
        sell_count = len(signals_by_type.get(SignalType.STRONG_SELL, [])) + \
                     len(signals_by_type.get(SignalType.SELL, []))
        
        if buy_count > sell_count:
            recommendations.append({
                'type': 'overall_position',
                'action': 'consider_betting',
                'strength': min(1.0, buy_count / max(1, len(signals))),
                'confidence': statistics.mean([
                    s.confidence for s in signals_by_type.get(SignalType.STRONG_BUY, []) + 
                    signals_by_type.get(SignalType.BUY, [])
                ]) if (signals_by_type.get(SignalType.STRONG_BUY, []) or signals_by_type.get(SignalType.BUY, [])) else 0.0,
                'rationale': f"{buy_count} BUY signals vs {sell_count} SELL signals",
                'risk_level': 'medium'
            })
        elif sell_count > buy_count:
            recommendations.append({
                'type': 'overall_position',
                'action': 'avoid_betting',
                'strength': min(1.0, sell_count / max(1, len(signals))),
                'confidence': statistics.mean([
                    s.confidence for s in signals_by_type.get(SignalType.STRONG_SELL, []) + 
                    signals_by_type.get(SignalType.SELL, [])
                ]) if (signals_by_type.get(SignalType.STRONG_SELL, []) or signals_by_type.get(SignalType.SELL, [])) else 0.0,
                'rationale': f"{sell_count} SELL signals vs {buy_count} BUY signals",
                'risk_level': 'medium'
            })
        
        # Rekomendacje per-outcome
        for outcome, signals_list in signals_by_type.items():
            if len(signals_list) > 0:
                # Najsilniejszy sygnał dla tego outcome
                strongest_signal = max(signals_list, key=lambda s: s.strength * s.confidence)
                
                recommendations.append({
                    'type': 'outcome_specific',
                    'outcome': strongest_signal.source_outcome,
                    'action': strongest_signal.signal_type.value,
                    'strength': strongest_signal.strength,
                    'confidence': strongest_signal.confidence,
                    'current_odds': strongest_signal.current_odds,
                    'expected_odds': strongest_signal.expected_odds,
                    'expected_value': strongest_signal.expected_value,
                    'risk_level': strongest_signal.risk_level,
                    'urgency': strongest_signal.urgency,
                    'rationale': strongest_signal.description
                })
        
        # Rekomendacje arbitrażowe
        if self.odds_aggregator:
            try:
                arbitrages = self.odds_aggregator.detect_arbitrage_opportunities(
                    list(outcome_trends.values())[0].match_id
                )
                
                for combo, metrics in arbitrages.items():
                    if metrics.get('profit_percent', 0) > 2.0:  # >2% zysk
                        recommendations.append({
                            'type': 'arbitrage_opportunity',
                            'combination': combo,
                            'profit_percent': metrics['profit_percent'],
                            'risk_level': 'low',
                            'confidence': 0.9,
                            'action': 'exploit_arbitrage',
                            'rationale': f"Risk-free opportunity with {metrics['profit_percent']:.2f}% profit"
                        })
            except:
                pass
        
        return recommendations
    
