    def generate_market_report(
        self,
        match_id: str,
        market_type: str = "match_result"
    ) -> Dict[str, Any]:
        """Generuje kompleksowy raport rynkowy"""
        import time
        start_time = time.time()
        
        report = {
            'match_id': match_id,
            'market_type': market_type,
            'generated_at': datetime.now().isoformat(),
            'sections': {}
        }
        
        try:
            # Sekcja 1: Podsumowanie
            analysis = self.analyze_trends(match_id, market_type)
            report['sections']['summary'] = {
                'overall_trend': analysis.overall_trend.value,
                'market_condition': analysis.market_condition.value,
                'analysis_duration': analysis.analysis_duration,
                'data_points': analysis.data_points,
                'outcomes_analyzed': len(analysis.outcome_trends)
            }
            
            # Sekcja 2: Trendy per outcome
            report['sections']['outcome_trends'] = {
                outcome: {
                    'trend_type': trend.trend_type.value,
                    'trend_strength': trend.trend_strength,
                    'current_odds': trend.current_odds,
                    'slope': trend.slope,
                    'r_squared': trend.r_squared,
                    'mean': trend.mean,
                    'std_dev': trend.std_dev,
                    'predicted_next': trend.predicted_next
                }
                for outcome, trend in analysis.outcome_trends.items()
            }
            
            # Sekcja 3: Korelacje
            report['sections']['correlations'] = {
                outcome: {corr_outcome: round(corr, 4) 
                        for corr_outcome, corr in correlations.items()}
                for outcome, correlations in analysis.correlations.items()
            }
            
            # Sekcja 4: Sygnały
            report['sections']['signals'] = []
            for signal_data in analysis.signals:
                signal = MarketSignal.from_dict(signal_data)
                report['sections']['signals'].append({
                    'type': signal.signal_type.value,
                    'strength': signal.strength,
                    'confidence': signal.confidence,
                    'outcome': signal.source_outcome,
                    'current_odds': signal.current_odds,
                    'expected_value': signal.expected_value,
                    'description': signal.description
                })
            
            # Sekcja 5: Rekomendacje
            report['sections']['recommendations'] = []
            for rec in analysis.recommendations:
                report['sections']['recommendations'].append({
                    'type': rec.get('type', 'unknown'),
                    'action': rec.get('action', ''),
                    'strength': rec.get('strength', 0),
                    'confidence': rec.get('confidence', 0),
                    'rationale': rec.get('rationale', '')
                })
            
            # Sekcja 6: Predykcje
            predictions = self.predict_odds_movement(match_id, market_type)
            report['sections']['predictions'] = {
                outcome: {
                    'predicted_next': info.get('predicted_next'),
                    'confidence': info.get('confidence', 0),
                    'trend_type': info.get('trend_type', 'unknown')
                }
                for outcome, info in predictions.items()
            }
            
            # Sekcja 7: Anomalie
            anomalies = self.detect_market_anomalies(match_id, market_type)
            report['sections']['anomalies'] = anomalies
            
            # Sekcja 8: Statystyki agregatora
            if self.odds_aggregator:
                report['sections']['aggregator_stats'] = self.odds_aggregator.get_statistics()
            
            report['generation_time'] = time.time() - start_time
            report['status'] = 'success'
            
        except Exception as e:
            report['status'] = 'error'
            report['error'] = str(e)
            report['generation_time'] = time.time() - start_time
        
        return report
    
