    def load_report(self, filepath: str) -> Dict[str, Any]:
        """Wczytuje raport z pliku"""
        filepath = os.path.join(self.data_dir, filepath)
        
        if os.path.exists(filepath):
            with open(filepath, 'r', encoding='utf-8') as f:
                return json.load(f)
        
        return {}
    
    def save_state(self, filepath: str = None) -> None:
        """Zapisuje stan analizatora"""
        if filepath is None:
            filepath = os.path.join(self.data_dir, "market_trends_analyzer_state.json")
        
        state = {
            'stats': self.stats,
            'trend_cache': [t.to_dict() for t in self._trend_cache.values()],
            'analysis_cache': [a.to_dict() for a in self._analysis_cache.values()]
        }
        
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(state, f, ensure_ascii=False, indent=2)
    
    def load_state(self, filepath: str = None) -> None:
        """Wczytuje stan analizatora"""
        if filepath is None:
            filepath = os.path.join(self.data_dir, "market_trends_analyzer_state.json")
        
        if not os.path.exists(filepath):
            return
        
        with open(filepath, 'r', encoding='utf-8') as f:
            state = json.load(f)
        
        with self._lock:
            self.stats.update(state.get('stats', {}))
            
            for trend_dict in state.get('trend_cache', []):
                trend = TrendData.from_dict(trend_dict)
                cache_key = f"{trend.match_id}_{trend.market_type}_{trend.outcome}"
                self._trend_cache[cache_key] = trend
            
            for analysis_dict in state.get('analysis_cache', []):
                analysis = MarketTrendAnalysis.from_dict(analysis_dict)
                cache_key = f"{analysis.match_id}_{analysis.market_type}"
                self._analysis_cache[cache_key] = analysis
